def check_vault_layout(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    home = policy["home_file"]
    maps_dir = policy["maps_dir"]
    if home not in vault.index:
        findings.append(Finding(
            "error", home, 1, "vault_layout",
            "vault has no home note",
            "materialize the vault payload (setup, or the stewardship copy"
            " rule) so navigation has a root"))
    for subtree in policy["subtrees"]:
        if not (vault.root / subtree).is_dir():
            continue
        map_rel = f"{maps_dir}/{subtree}.md"
        if map_rel not in vault.index:
            findings.append(Finding(
                "error", map_rel, 1, "vault_layout",
                f"subtree '{subtree}' has no map note",
                "seed the map from the vault payload and curate it"))
    for name in policy.get("extra_maps", []):
        map_rel = f"{maps_dir}/{name}.md"
        if map_rel not in vault.index:
            findings.append(Finding(
                "error", map_rel, 1, "vault_layout",
                f"map note '{name}' is missing",
                "seed it from the vault payload"))
    known_roots = set(policy["subtrees"]) | {
        maps_dir, ".obsidian", ".trash",
        policy.get("attachments_dir", "_attachments"),
    }
    known_roots.update(p.rstrip("/").split("/")[0]
                       for p in policy.get("generated_subtrees", []))
    known_files = {home, policy["start_here_file"]}
    known_files.update(v for v in policy.get("generated_views", [])
                       if "/" not in v)
    attachments = policy.get("attachments_dir", "_attachments")
    embedded = {t for note in vault.notes.values()
                for (_, embed, t, _, _, _) in note.wikilinks if embed}
    for rel in sorted(vault.index):
        top = rel.split("/")[0]
        if rel.rsplit("/", 1)[-1] == ".gitkeep":
            continue  # git plumbing for empty skeleton directories
        if rel.endswith(".base"):
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                "base files are not part of the vault contract",
                "views are markdown map notes and generated indexes;"
                " remove the base file"))
            continue
        if top == ".obsidian":
            continue
        if "/" not in rel:
            if rel.endswith(".md"):
                if rel not in known_files and rel not in {home}:
                    findings.append(Finding(
                        "error", rel, 1, "vault_layout",
                        f"root-level note '{rel}' is outside the vault layout",
                        "notes live inside a policy subtree; move it or"
                        " register the surface in vault-policy.json"))
            elif rel not in known_files:
                findings.append(Finding(
                    "error", rel, 1, "vault_layout",
                    f"root-level file '{rel}' is outside the vault layout",
                    "only policy-listed views and the payload live at the"
                    " vault root"))
            continue
        if top not in known_roots:
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                f"unknown top-level directory '{top}'",
                "vault subtrees are policy-listed; add it to"
                " vault-policy.json or move the content"))
        elif top == attachments:
            if rel not in embedded:
                findings.append(Finding(
                    "error", rel, 1, "vault_layout",
                    "attachment is not referenced by any embed",
                    "reference it with an embed wikilink or delete it"))
        elif not rel.endswith(".md") and top not in {
                p.rstrip("/").split("/")[0]
                for p in policy.get("generated_subtrees", [])}:
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                f"non-markdown file '{rel}' inside a note subtree",
                "attachments live under the attachments directory;"
                " transient working files leave the vault before the gate"))


def check_wikilink_resolution(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, embed, target, _anchor, _alias, _inner) in note.wikilinks:
            if not target:
                continue  # pure in-note anchor form is judged by anchor check
            resolved = (target in vault.index if embed
                        else f"{target}.md" in vault.index)
            if not resolved:
                findings.append(Finding(
                    "error", note.rel, lineno, "wikilink_resolution",
                    f"unresolved wikilink target '{target}'",
                    "targets are vault-absolute paths from the vault root"
                    " (no leading slash, forward slashes, exact case)"))


def check_anchor_resolution(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, _embed, target, anchor, _alias, _inner) in note.wikilinks:
            if not anchor:
                continue
            if not anchor.startswith("^"):
                findings.append(Finding(
                    "error", note.rel, lineno, "anchor_resolution",
                    f"heading anchor '#{anchor}' is banned",
                    "link the note itself, or a block id (#^block-id);"
                    " heading text is prose and dies silently"))
                continue
            target_note = vault.notes.get(f"{target}.md" if target else note.rel)
            if target_note and anchor[1:] not in target_note.block_ids:
                findings.append(Finding(
                    "error", note.rel, lineno, "anchor_resolution",
                    f"block anchor '{anchor}' does not exist in"
                    f" '{target or note.rel}'",
                    "add the ^block-id to the target line or fix the anchor"))


def check_link_policy(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, _text, target) in note.mdlinks:
            if target.startswith(("http://", "https://", "mailto:", "#", "/")):
                continue
            clean = target.split("#", 1)[0]
            if not clean:
                continue
            resolved = (note.path.parent / clean).resolve()
            try:
                resolved.relative_to(vault.root)
                inside = True
            except ValueError:
                inside = False
            if inside:
                findings.append(Finding(
                    "error", note.rel, lineno, "link_policy",
                    f"vault-internal citation uses a markdown link: {target}",
                    "cite vault content as a vault-absolute wikilink with an"
                    " alias; the migrate verb rewrites this class"))
            elif not resolved.exists():
                findings.append(Finding(
                    "warning", note.rel, lineno, "link_policy",
                    f"out-of-vault link target does not exist: {target}",
                    "fix the relative path or drop the link"))


def check_table_pipe(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        in_fence = False
        for lineno, line in enumerate(note.lines, start=1):
            if lineno < note.fm_end:
                continue
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence or not is_table_row(line):
                continue
            for match in WIKILINK_RE.finditer(INLINE_CODE_RE.sub("", line)):
                inner = match.group("inner")
                if re.search(r"(?<!\\)\|", inner):
                    findings.append(Finding(
                        "error", note.rel, lineno, "table_pipe",
                        "unescaped alias pipe inside a table-cell wikilink",
                        "escape it as \\| or the pipe splits the row"))


def check_orphans(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    home = policy["home_file"]
    for note in authored(vault):
        if note.rel == home:
            continue  # the navigation root is exempt by definition
        if not vault.inbound.get(note.rel):
            findings.append(Finding(
                "error", note.rel, 1, "orphans",
                "note has no inbound wikilink",
                "link it from its map note or owning hub; every note is"
                " part of the graph or it does not exist"))


def check_moc_coverage(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    home = policy["home_file"]
    if home not in vault.notes:
        return  # vault_layout already reports the missing root
    reachable: set[str] = set()
    frontier = [home]
    while frontier:
        rel = frontier.pop()
        if rel in reachable:
            continue
        reachable.add(rel)
        note = vault.notes.get(rel)
        if note is None:
            continue
        targets = [t for (_, _, t, _, _, _) in note.wikilinks if t]
        targets.extend(t for (_, t) in note.fm_targets if t)
        for target in targets:
            frontier.append(f"{target}.md")
    for note in authored(vault):
        if note.rel not in reachable:
            findings.append(Finding(
                "error", note.rel, 1, "moc_coverage",
                "note is not reachable from the home note",
                "add it to its subtree map (directly or through a hub the"
                " map links)"))


def check_nav_footer(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    maps_dir = policy["maps_dir"]
    exempt = {policy["home_file"], policy["start_here_file"]}
    peer_min = policy["nav_peer_min"]
    peer_max = policy["nav_peer_max"]
    subtree_counts: dict[str, int] = {}
    for note in authored(vault):
        subtree_counts[note.subtree] = subtree_counts.get(note.subtree, 0) + 1
    for note in authored(vault):
        if note.rel in exempt or note.subtree == maps_dir or not note.subtree:
            continue
        nav_line = next((i for i, line in enumerate(note.lines, start=1)
                         if NAV_MARKER in line), None)
        if nav_line is None:
            findings.append(Finding(
                "error", note.rel, max(len(note.lines), 1), "nav_footer",
                f"note has no nav section ({NAV_MARKER})",
                "end every leaf with the nav section: first wikilink is the"
                " owning map, then the contextual peers"))
            continue
        links = [(lineno, target)
                 for (lineno, embed, target, _a, _al, _inner) in note.wikilinks
                 if lineno >= nav_line and target and not embed]
        owning_map = f"{maps_dir}/{note.subtree}"
        if not links or links[0][1] != owning_map:
            findings.append(Finding(
                "error", note.rel, nav_line, "nav_footer",
                f"nav section's first wikilink must be the owning map"
                f" '{owning_map}'",
                "the up-edge is positional: owning map first, peers after"))
            continue
        peers = [t for (_, t) in links[1:] if f"{t}.md" in vault.index]
        floor = min(peer_min, max(subtree_counts.get(note.subtree, 1) - 1, 0))
        if not floor <= len(peers) <= peer_max:
            findings.append(Finding(
                "error", note.rel, nav_line, "nav_footer",
                f"nav section has {len(peers)} resolving peer links"
                f" (policy range {floor}-{peer_max})",
                "link the contextual peers a reader would jump to next"))


def property_type_ok(value, expected: str) -> bool:
    if expected == "list":
        return isinstance(value, list)
    if expected == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if expected == "checkbox":
        return isinstance(value, bool)
    if expected in ("date", "datetime"):
        return isinstance(value, str) and bool(DATE_RE.match(value[:10]))
    return isinstance(value, str)


def check_frontmatter_props(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    prop_types = policy.get("property_types", {})
    for note in authored(vault):
        if note.fm_error:
            findings.append(Finding(
                "error", note.rel, 1, "frontmatter_props",
                f"frontmatter: {note.fm_error}",
                "every authored note opens with a frontmatter block"))
            continue
        for key in ("type",):
            if not note.fm.get(key):
                findings.append(Finding(
                    "error", note.rel, 1, "frontmatter_props",
                    f"frontmatter floor: '{key}' is missing",
                    "every authored note declares its type"))
        for key in ("tag", "alias", "cssclass"):
            if key in note.fm:
                findings.append(Finding(
                    "error", note.rel, 1, "frontmatter_props",
                    f"singular '{key}:' key is dead vault grammar",
                    f"use the list key '{key}s' (dash items, one per line)"))
        for key in ("tags", "aliases"):
            if key not in note.fm:
                continue
            value = note.fm[key]
            if isinstance(value, str):
                shape = ("inline flow list" if FLOW_LIST_RE.match(value)
                         else "scalar")
                findings.append(Finding(
                    "error", note.rel, 1, "frontmatter_props",
                    f"'{key}' is a {shape}; the contract is a block list",
                    f"write '{key}:' then one '- item' line per value"))
        if "tags" not in note.fm:
            findings.append(Finding(
                "error", note.rel, 1, "frontmatter_props",
                "frontmatter floor: 'tags' is missing",
                "every authored note carries its tag mirror"))
        for key, expected in sorted(prop_types.items()):
            if key in note.fm and not property_type_ok(note.fm[key], expected):
                findings.append(Finding(
                    "error", note.rel, 1, "frontmatter_props",
                    f"'{key}' does not match its vault-wide property type"
                    f" '{expected}'",
                    "one value type per key, vault-wide; dates are"
                    " YYYY-MM-DD"))
        for key, target in note.fm_targets:
            if target and f"{target}.md" not in vault.index:
                findings.append(Finding(
                    "error", note.rel, 1, "frontmatter_props",
                    f"frontmatter link '{key}' targets missing note"
                    f" '{target}'",
                    "frontmatter links are vault-absolute wikilinks to"
                    " existing notes"))
        for lineno in range(1, note.fm_end - 1):
            if lineno - 1 >= len(note.lines):
                break
            raw = note.lines[lineno - 1]
            if re.match(r"^\s*(?:- )?(?:[a-z0-9_]+:)?\s*\[\[", raw):
                findings.append(Finding(
                    "error", note.rel, lineno, "frontmatter_props",
                    "unquoted wikilink in frontmatter",
                    "quote wikilink values (\"[[...]]\") or the frontmatter"
                    " is not valid YAML to the vault app"))


def kebab(value: str) -> str:
    return str(value).replace("_", "-").lower()


def check_tags_mirror(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        tags = note.fm.get("tags")
        note_type = note.fm.get("type")
        if not isinstance(tags, list) or not note_type:
            continue  # the frontmatter floor already reports the shape
        expected = {f"doc/{kebab(note_type)}"}
        status = note.fm.get("status")
        if status:
            expected.add(f"status/{kebab(status)}")
        if set(tags) != expected:
            findings.append(Finding(
                "error", note.rel, 1, "tags_mirror",
                f"tags {sorted(tags)} must be exactly {sorted(expected)}",
                "tags are the script-stamped mirror of type and status;"
                " never hand-pick tags"))


def decision_notes(vault: Vault, tree: dict) -> list[Note]:
    prefix = tree["path"].rstrip("/") + "/"
    return [n for n in sorted(vault.notes.values(), key=lambda n: n.rel)
            if n.rel.startswith(prefix) and not n.generated]


def decision_filename_re(tree: dict) -> re.Pattern:
    return re.compile(
        rf"^{tree['id_prefix'].lower()}-(\d{{{tree['id_min_width']},}})"
        rf"-[a-z0-9]+(?:-[a-z0-9]+)*\.md$")


def decision_id(tree: dict, note_rel: str) -> str | None:
    match = decision_filename_re(tree).match(note_rel.rsplit("/", 1)[-1])
    if not match:
        return None
    return f"{tree['id_prefix']}-{match.group(1)}"


def check_decision_records(vault: Vault, findings: list[Finding]) -> None:
    for tree_name, tree in sorted(vault.policy.get("decision_trees", {}).items()):
        seen: dict[str, str] = {}
        notes = decision_notes(vault, tree)
        for note in notes:
            rec_id = decision_id(tree, note.rel)
            if rec_id is None:
                findings.append(Finding(
                    "error", note.rel, 1, "decision_records",
                    f"filename does not match the {tree['id_prefix']} note"
                    " grammar",
                    f"decision notes are {tree['id_prefix'].lower()}-"
                    f"<{tree['id_min_width']}+ digits>-<kebab-slug>.md"))
                continue
            number = rec_id.split("-")[1]
            if number in seen:
                findings.append(Finding(
                    "error", note.rel, 1, "decision_records",
                    f"decision id number {number} already minted by"
                    f" {seen[number]}",
                    "ids are unique per tree; renumber the younger note and"
                    " rewrite its referrers in the same commit"))
            else:
                seen[number] = note.rel
            first_heading = note.headings[0][1] if note.headings else ""
            if not first_heading.startswith(f"{rec_id}: "):
                findings.append(Finding(
                    "error", note.rel,
                    note.headings[0][0] if note.headings else 1,
                    "decision_records",
                    f"first heading must read '{rec_id}: <title>'",
                    "the id leads the heading so previews and the graph"
                    " show it"))
            aliases = note.fm.get("aliases")
            if not (isinstance(aliases, list) and rec_id in aliases):
                findings.append(Finding(
                    "error", note.rel, 1, "decision_records",
                    f"aliases must contain the bare id '{rec_id}'",
                    "the alias makes the bare id searchable and linkable"))
            for key in ("supersedes", "superseded_by"):
                target = dict(note.fm_targets).get(key, "")
                raw = note.fm.get(key, "")
                if raw and not target:
                    findings.append(Finding(
                        "error", note.rel, 1, "decision_records",
                        f"'{key}' must be a quoted wikilink or empty",
                        "the supersede chain is a pair of frontmatter"
                        " wikilinks"))
            fm_map = dict(note.fm_targets)
            other_rel = (f"{fm_map['superseded_by']}.md"
                         if "superseded_by" in fm_map else None)
            if other_rel:
                other = vault.notes.get(other_rel)
                back = dict(other.fm_targets).get("supersedes", "") if other else ""
                if not other or f"{back}.md" != note.rel:
                    findings.append(Finding(
                        "error", note.rel, 1, "decision_records",
                        "supersede chain is not symmetric",
                        "stamp-decision writes both ends in one operation;"
                        " never hand-edit the chain"))
        index_rel = index_path_for(tree)
        expected = render_decision_index(vault, tree)
        actual_path = vault.root / index_rel
        actual = (actual_path.read_text(encoding="utf-8", errors="replace")
                  if actual_path.is_file() else "")
        if notes and actual != expected:
            findings.append(Finding(
                "error", index_rel, 1, "decision_records",
                f"decision index is stale for tree '{tree_name}'",
                "run the render-decisions verb; the index is generated,"
                " never merged by hand"))


def check_generated_views(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    marker_prefix = policy.get("generated_marker_prefix", "<!-- generated by")
    decision_indexes = {index_path_for(tree)
                        for tree in policy.get("decision_trees", {}).values()}
    for view in policy.get("generated_views", []):
        path = vault.root / view
        if not path.is_file():
            if view in decision_indexes:
                owners = [t for t in policy["decision_trees"].values()
                          if index_path_for(t) == view]
                if not any(decision_notes(vault, t) for t in owners):
                    continue  # an index is born with its first decision
            findings.append(Finding(
                "error", view, 1, "generated_views",
                "policy-listed generated view is missing",
                "render it with its owning verb (render backlog/ledger,"
                " render-decisions)"))
            continue
        first = path.read_text(encoding="utf-8",
                               errors="replace").splitlines()
        if not first or not first[0].startswith(marker_prefix):
            findings.append(Finding(
                "error", view, 1, "generated_views",
                "generated view lacks the first-line marker",
                "re-render it; a marker-less copy dodges the edit guard"))


def check_home_shape(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    maps_dir = policy["maps_dir"]
    home = vault.notes.get(policy["home_file"])
    start_stem = policy["start_here_file"].rsplit(".", 1)[0]
    if home is not None:
        for (lineno, _e, target, _a, _al, _inner) in home.wikilinks:
            if not (target.startswith(f"{maps_dir}/") or target == start_stem):
                findings.append(Finding(
                    "error", home.rel, lineno, "home_shape",
                    f"home links '{target}'; home links only map notes",
                    "the graph star topology depends on home -> maps ->"
                    " docs; move the link into the owning map"))
        if home.fm.get("type") != "home":
            findings.append(Finding(
                "error", home.rel, 1, "home_shape",
                "home note must carry type: home",
                "home and maps are navigation, typed as such"))
    for rel, note in sorted(vault.notes.items()):
        if not rel.startswith(f"{maps_dir}/") or note.generated:
            continue
        if note.fm.get("type") != "moc":
            findings.append(Finding(
                "error", rel, 1, "home_shape",
                "map note must carry type: moc",
                "maps are navigation hubs, typed as such"))
        if "status" in note.fm:
            findings.append(Finding(
                "error", rel, 1, "home_shape",
                "map notes carry no status lifecycle",
                "navigation is never draft or approved; drop the key"))


def check_obsidian_payload(vault: Vault, findings: list[Finding],
                           payload_dir: Path | None) -> None:
    policy = vault.policy
    obsidian = vault.root / ".obsidian"
    for name in PAYLOAD_FILES:
        if not (obsidian / name).is_file():
            findings.append(Finding(
                "error", f".obsidian/{name}", 1, "obsidian_payload",
                "committed payload file is missing",
                "copy the vault payload (per-file, only where missing)"))
    app_path = obsidian / "app.json"
    if app_path.is_file():
        try:
            app = json.loads(app_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            app = None
            findings.append(Finding(
                "error", ".obsidian/app.json", 1, "obsidian_payload",
                "app.json does not parse", "restore it from the payload"))
        if isinstance(app, dict):
            sentinels = dict(APP_SENTINELS)
            sentinels["attachmentFolderPath"] = policy.get(
                "attachments_dir", "_attachments")
            for key, expected in sentinels.items():
                if app.get(key) != expected:
                    findings.append(Finding(
                        "error", ".obsidian/app.json", 1, "obsidian_payload",
                        f"app.json {key} must be {json.dumps(expected)}",
                        "these keys control what the vault app writes;"
                        " drift makes the app author against the law"))
    core_path = obsidian / "core-plugins.json"
    if core_path.is_file():
        try:
            core = json.loads(core_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            core = None
            findings.append(Finding(
                "error", ".obsidian/core-plugins.json", 1, "obsidian_payload",
                "core-plugins.json does not parse",
                "restore it from the payload"))
        bases_on = (("bases" in core) if isinstance(core, list)
                    else bool(core.get("bases")) if isinstance(core, dict)
                    else False)
        if bases_on:
            findings.append(Finding(
                "error", ".obsidian/core-plugins.json", 1, "obsidian_payload",
                "the bases plugin is off in this vault generation",
                "views are markdown maps and generated indexes; disable it"))
    types_path = obsidian / "types.json"
    if types_path.is_file():
        try:
            types = json.loads(types_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            types = {}
            findings.append(Finding(
                "error", ".obsidian/types.json", 1, "obsidian_payload",
                "types.json does not parse", "restore it from the payload"))
        declared = types.get("types", {}) if isinstance(types, dict) else {}
        for key, expected in sorted(policy.get("property_types", {}).items()):
            if declared.get(key) != expected:
                findings.append(Finding(
                    "error", ".obsidian/types.json", 1, "obsidian_payload",
                    f"property '{key}' must be typed '{expected}'",
                    "types.json is derived from vault-policy.json"
                    " property_types; restore the drifted entry"))


