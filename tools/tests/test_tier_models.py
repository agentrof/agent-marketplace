"""Per-project role models, efforts and tiers.

Every build ships one tier map, `templates/tier-map.json`: each role's package
tier, generated variants included, and per host each of the high, medium and
low tiers' package model and effort, the host's model catalog with the
efforts each model takes, the host's effort vocabulary and model ID shape,
and the efforts the host's `effort-policy.json` asks the owner to confirm or
refuses. A project's `workspace/config.json` holds only overrides:
`tier_models`, per host and tier a `model` (a model ID or `session`) and an
`effort`, either one optional, and `role_tiers`, which moves any role,
variants included, between the high, medium and low tiers on every host. `project_config.py set-tier` and `set-role-tier` write
them, `role_settings.py` resolves them, and setup renders every role and
variant with its resolved model and effort on both hosts.
"""

