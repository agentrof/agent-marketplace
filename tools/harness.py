#!/usr/bin/env python3
"""Multi-harness artifact renderer for the Agent Marketplace.

One source tree under plugins/ (Claude Code native), many install surfaces.
Every per-harness value (paths, event routes, matcher token expansions,
frontmatter dispositions, model map, command rewrite policy) lives in
tools/data/harnesses.json; this module implements only the closed action
vocabulary, the emitters and the drift differ. Adding a harness whose needs
fit the listed vocabulary is a config edit, never a Python change.

Consumed by tools/generate.py (CLI), tools/validate.py (drift + scope) and
tools/scaffold.py (regeneration after scaffolding).

Stdlib only. Deterministic output: rendering twice is byte-identical.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

CONFIG_RELPATH = "tools/data/harnesses.json"

MATRIX_START = "<!-- harness-matrix:start -->"
MATRIX_END = "<!-- harness-matrix:end -->"
HARNESSES_DOC_RELPATH = "docs/harnesses.md"

# The one hand-authored sentence pair around the injected matrix when the
# doc does not exist yet; later prose edits around the markers survive.
HARNESSES_DOC_SKELETON = """# Harness support

The source of truth is the Claude Code tree under plugins/. Every other
install surface is generated by tools/generate.py from
tools/data/harnesses.json; generated files are never hand-edited and CI
fails on drift.

{start}
{end}
"""

FRONTMATTER_ACTIONS = {
    "keep",
    "drop",
    "rename",
    "replace_when_present",
    "map_model",
    "policy_flag",
    "nest",
}

COMMAND_TOKEN_RE = re.compile(
    r"\"\$\{CLAUDE_PLUGIN_ROOT\}\"/([A-Za-z0-9_\-./]+)"
)


class HarnessConfigError(ValueError):
    """Raised when the config cannot drive a deterministic render."""


# ---------------------------------------------------------------------------
# Loading and parsing
# ---------------------------------------------------------------------------


def load_config(root: Path) -> dict:
    path = root / CONFIG_RELPATH
    if not path.is_file():
        raise HarnessConfigError(f"missing {CONFIG_RELPATH}")
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise HarnessConfigError(f"{CONFIG_RELPATH}: invalid JSON: {exc}") from exc
    if not isinstance(config.get("harnesses"), dict) or not config["harnesses"]:
        raise HarnessConfigError(f"{CONFIG_RELPATH}: harnesses must be a non-empty object")
    return config


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Return (ordered frontmatter dict with raw values, body text)."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    fm: dict[str, str] = {}
    for i in range(1, len(lines)):
        stripped = lines[i].strip()
        if stripped == "---":
            return fm, "\n".join(lines[i + 1:])
        if not stripped or stripped.startswith("#"):
            continue
        if ":" in stripped:
            key, _, value = stripped.partition(":")
            fm[key.strip()] = value.strip()
    return {}, text


def title_of(name: str) -> str:
    return " ".join(word.capitalize() for word in name.split("-"))


def plugin_dirs(root: Path) -> list[Path]:
    plugins = root / "plugins"
    if not plugins.is_dir():
        return []
    return sorted(p for p in plugins.iterdir() if p.is_dir())


def agent_files(plugin: Path) -> list[Path]:
    agents = plugin / "agents"
    return sorted(agents.glob("*.md")) if agents.is_dir() else []


def skill_dirs(plugin: Path) -> list[Path]:
    skills = plugin / "skills"
    if not skills.is_dir():
        return []
    return sorted(d for d in skills.iterdir() if d.is_dir() and (d / "SKILL.md").is_file())


# ---------------------------------------------------------------------------
# Emit helpers (format code, not variation points)
# ---------------------------------------------------------------------------


def dumps_json(data: object) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def toml_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def toml_multiline(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rewrite_command(command: str, policy: dict) -> str:
    """Apply the harness command_rewrite policy to one hook command.

    keep_verbatim: identity. env_prefix: swap the Claude plugin-root token
    for the harness variable with a shell-level default, keeping the quoted
    path unit and any argument tail intact.
    """
    kind = policy.get("policy", "keep_verbatim")
    if kind == "keep_verbatim":
        return command
    if kind == "env_prefix":
        var = policy["var"]
        fallback = policy.get("fallback", ".")
        return COMMAND_TOKEN_RE.sub(
            lambda m: f'"${{{var}:-{fallback}}}/{m.group(1)}"', command
        )
    raise HarnessConfigError(f"unknown command_rewrite policy '{kind}'")


# ---------------------------------------------------------------------------
# Model and frontmatter dispositions
# ---------------------------------------------------------------------------


def resolve_model(harness: dict, alias: str) -> dict:
    model_map = harness.get("model_map", {})
    if alias in model_map:
        return model_map[alias]
    fallback = harness.get("model_fallback", "inherit")
    return model_map.get(fallback, {})


def _check_action(spec: dict, key: str, harness_id: str) -> str:
    action = spec.get("action", "")
    if action not in FRONTMATTER_ACTIONS:
        raise HarnessConfigError(
            f"harness '{harness_id}' frontmatter key '{key}' uses unknown"
            f" action '{action}'"
        )
    return action


# ---------------------------------------------------------------------------
# Agents
# ---------------------------------------------------------------------------


def render_cursor_agent(fm: dict[str, str], body: str, harness: dict, harness_id: str) -> str:
    lines = ["---"]
    for key, raw in fm.items():
        spec = harness.get("agent_frontmatter", {}).get(key)
        if spec is None:
            continue
        action = _check_action(spec, key, harness_id)
        if action == "drop":
            continue
        if action == "keep":
            lines.append(f"{key}: {raw}")
        elif action == "rename":
            lines.append(f"{spec['to']}: {raw}")
        elif action == "map_model":
            row = resolve_model(harness, raw)
            if "model" in row:
                lines.append(f"model: {row['model']}")
        elif action == "replace_when_present":
            value = spec["value"]
            rendered = "true" if value is True else "false" if value is False else str(value)
            lines.append(f"{spec['key']}: {rendered}")
    lines.append("---")
    return "\n".join(lines) + "\n" + body.rstrip("\n") + "\n"


def render_toml_agent(fm: dict[str, str], body: str, harness: dict, harness_id: str) -> str:
    pairs: list[tuple[str, str]] = []
    for key, raw in fm.items():
        spec = harness.get("agent_frontmatter", {}).get(key)
        if spec is None:
            continue
        action = _check_action(spec, key, harness_id)
        if action == "drop":
            continue
        if action == "keep":
            pairs.append((key, f'"{toml_escape(raw)}"'))
        elif action == "rename":
            pairs.append((spec["to"], f'"{toml_escape(raw)}"'))
        elif action == "map_model":
            row = resolve_model(harness, raw)
            for mk in ("model", "model_reasoning_effort"):
                if mk in row:
                    pairs.append((mk, f'"{toml_escape(str(row[mk]))}"'))
        elif action == "replace_when_present":
            value = spec["value"]
            rendered = ("true" if value is True else "false" if value is False
                        else f'"{toml_escape(str(value))}"')
            pairs.append((spec["key"], rendered))
    out = [f"{key} = {value}" for key, value in pairs]
    out.append('developer_instructions = """')
    out.append(toml_multiline(body.strip("\n")))
    out.append('"""')
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# Skill policy files (openai.yaml)
# ---------------------------------------------------------------------------


def render_skill_policy(fm: dict[str, str], harness: dict, harness_id: str) -> str | None:
    """Render the per-skill policy file for harnesses that declare one.

    Emits the two-level interface/policy nesting; the only list-bearing
    block of the documented schema (dependencies) is never emitted, so a
    flat hand-rolled writer is sufficient.
    """
    if "skill_policy_file" not in harness:
        return None
    policy_lines: list[str] = []
    for key, spec in harness.get("skill_frontmatter", {}).items():
        action = _check_action(spec, key, harness_id)
        if action != "policy_flag":
            continue
        raw = fm.get(key, "false")
        flag = spec["when_true"] if raw == "true" else spec["when_false"]
        policy_lines.append(
            f"  {spec['policy_key']}: {'true' if flag else 'false'}"
        )
    name = fm.get("name", "")
    description = fm.get("description", "")
    lines = [
        "interface:",
        f"  display_name: {yaml_quote(title_of(name))}",
        f"  short_description: {yaml_quote(description)}",
    ]
    if policy_lines:
        lines.append("policy:")
        lines.extend(policy_lines)
    return "\n".join(lines) + "\n"


