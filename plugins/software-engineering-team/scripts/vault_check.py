def load_policy(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def utc_today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def glob_match(pattern: str, path: str) -> bool:
    """Single-segment glob match: '*' never crosses '/'. ONE matcher
    serves the hub ladder and the decision-tree globs so the two can
    never drift."""
    pattern_parts = pattern.split("/")
    parts = path.split("/")
    if len(pattern_parts) != len(parts):
        return False
    return all(fnmatch.fnmatchcase(seg, pat)
               for pat, seg in zip(pattern_parts, parts))


def machine_dir_set(policy: dict) -> set:
    return set(policy.get("machine_dirs", []))


def in_machine_dir(policy: dict, rel: str) -> bool:
    return any(part in machine_dir_set(policy)
               for part in rel.split("/")[:-1])


def normalize_vault_rel(raw: str) -> str:
    """Map a repo- or workspace-relative path onto its vault-relative
    form (freeze manifests and callers hand in either)."""
    p = raw.replace("\\", "/")
    for prefix in ("workspace/docs/", "docs/"):
        if p.startswith(prefix):
            return p[len(prefix):]
    return p


def is_hub(policy: dict, rel: str) -> bool:
    return any(glob_match(entry.get("note", ""), rel)
               for entry in policy.get("hubs", []))


def resolve_hub(policy: dict, index: set, rel: str) -> str | None:
    """The deepest EXISTING hub note covering rel, or None. Index-aware:
    a hub file that is not in the current index cannot be a nav target,
    so rename and retarget compose in either order."""
    entries = sorted(policy.get("hubs", []),
                     key=lambda e: -len(e.get("covers", "").split("/")))
    for entry in entries:
        covers_parts = entry.get("covers", "").split("/")
        parts = rel.split("/")
        if len(parts) <= len(covers_parts):
            continue
        covered_dir = "/".join(parts[:len(covers_parts)])
        if not glob_match(entry["covers"], covered_dir):
            continue
        candidates = sorted(
            c for c in index
            if c != rel and c.startswith(covered_dir + "/")
            and glob_match(entry.get("note", ""), c))
        if candidates:
            return candidates[0]
    return None


def subtree_has_notes(vault: Vault, subtree: str) -> bool:
    prefix = subtree + "/"
    return any(rel.startswith(prefix) and rel.endswith(".md")
               for rel in vault.index)


def rel_posix(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def is_table_row(line: str) -> bool:
    return line.lstrip().startswith("|")


def scan_note(root: Path, path: Path, marker_prefix: str) -> Note:
    text = path.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    generated = bool(lines) and lines[0].startswith(marker_prefix)
    fm, fm_end, fm_error = parse_frontmatter(text)
    rel = rel_posix(root, path)
    parts = rel.split("/")
    note = Note(
        rel=rel, path=path, fm=fm, fm_end=fm_end, fm_error=fm_error,
        lines=lines, generated=generated,
        subtree=parts[0] if len(parts) > 1 else "",
    )
    in_fence = False
    for lineno, line in enumerate(lines, start=1):
        if lineno < note.fm_end:
            continue
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            note.headings.append((lineno, heading.group(2).strip(),
                                  len(heading.group(1))))
        block = BLOCK_ID_RE.search(line)
        if block:
            note.block_ids.add(block.group(1))
        scrubbed = INLINE_CODE_RE.sub("", line)
        for match in WIKILINK_RE.finditer(scrubbed):
            target, anchor, alias = split_wikilink(match.group("inner"))
            note.wikilinks.append((lineno, match.group("embed") == "!",
                                   target, anchor, alias,
                                   match.group("inner")))
        for match in LINK_RE.finditer(scrubbed):
            note.mdlinks.append((lineno, match.group(1), match.group(2)))
    for key, value in note.fm.items():
        values = value if isinstance(value, list) else [value]
        for item in values:
            if isinstance(item, str) and item.startswith("[[") and item.endswith("]]"):
                target, _, _ = split_wikilink(item[2:-2])
                note.fm_targets.append((key, target))
    return note


def build_vault(root: Path, policy: dict) -> Vault:
    vault = Vault(root=root, policy=policy)
    marker_prefix = policy.get("generated_marker_prefix", "<!-- generated by")
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = rel_posix(root, path)
        if rel.split("/")[0] == ".trash":
            continue
        vault.index.add(rel)
        if path.suffix == ".md" and rel.split("/")[0] != ".obsidian":
            vault.notes[rel] = scan_note(root, path, marker_prefix)
    for note in vault.notes.values():
        targets = [t for (_, _, t, _, _, _) in note.wikilinks if t]
        targets.extend(t for (_, t) in note.fm_targets if t)
        for target in targets:
            vault.inbound.setdefault(f"{target}.md", set()).add(note.rel)
    vault.designations = load_designations(root)
    vault.taxonomy_types = designation_type_universe(policy)
    return vault


def authored(vault: Vault) -> list[Note]:
    return [n for n in sorted(vault.notes.values(), key=lambda n: n.rel)
            if not n.generated]


