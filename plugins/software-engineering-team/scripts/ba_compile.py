def resolve_vault_root(space_dir: Path, override: str) -> Path | None:
    """The vault root: --vault-root, else the nearest ancestor named
    docs. No silent fallback: a wikilink-resolving run without a vault
    root is a usage error, not a guess."""
    if override:
        return Path(override).resolve()
    for ancestor in space_dir.resolve().parents:
        if ancestor.name == "docs":
            return ancestor
    return None


def require_vault_root(args) -> Path | None:
    root = resolve_vault_root(Path(args.space), getattr(args, "vault_root", ""))
    if root is None:
        print("ba_compile: FAIL: no ancestor named docs and no --vault-root;"
              " wikilink resolution needs the vault root named explicitly",
              file=sys.stderr)
    return root


def vault_prefix_for(space_dir: Path, vault_root: Path) -> str:
    try:
        return space_dir.resolve().relative_to(
            vault_root.resolve()).as_posix() + "/"
    except ValueError:
        return ""


def cmd_init(args, schema: dict) -> int:
    space_dir = Path(args.space)
    if space_dir.is_dir() and any(space_dir.iterdir()):
        print(f"ba_compile: FAIL: {space_dir} already exists and is not empty",
              file=sys.stderr)
        return 1
    vault_root = require_vault_root(args)
    if vault_root is None:
        return 2
    prefix = vault_prefix_for(space_dir, vault_root)
    hub = f"{prefix}{space_overview_rel(schema)[:-3]}"
    (space_dir / GENERATED_DIR).mkdir(parents=True, exist_ok=True)
    write_stub(schema, space_dir / space_overview_rel(schema), "space",
               args.title, code=args.code, aliases=[args.code])
    write_stub(schema, space_dir / named_file_name(schema, "glossary"),
               "glossary", f"{args.title} Glossary", nav_hub=hub)
    write_stub(schema, space_dir / named_file_name(schema, "actor_roster"),
               "actor_roster", f"{args.title} Actors", nav_hub=hub)
    budgets_name = named_file_name(schema, "budget_set")
    write_stub(schema, space_dir / budgets_name, "budget_set",
               f"{args.title} Non-Functional Budgets", nav_hub=hub,
               scope="space")
    budgets_path = space_dir / budgets_name
    budgets_path.write_text(
        budgets_path.read_text(encoding="utf-8")
        .replace("To be analyzed.", "None stated, confirmed."),
        encoding="utf-8")
    print(f"ba_compile: space initialized at {space_dir} (code {args.code})")
    return 0


def cmd_stub(args, schema: dict) -> int:
    if args.type not in schema["doc_types"]:
        print(f"ba_compile: FAIL: unknown type '{args.type}'", file=sys.stderr)
        return 2
    vault_root = require_vault_root(args)
    if vault_root is None:
        return 2
    space_dir = Path(args.space)
    prefix = vault_prefix_for(space_dir, vault_root)
    spec = schema["doc_types"][args.type]
    loc = spec["location"]
    node = args.node.strip("/")
    title = args.title
    extra: dict = {}
    aliases: list[str] | None = None
    seed_rows: dict[str, list[str]] | None = None
    # Overview docs are hubs and nav to the subtree map (the default);
    # everything else navs to its owning node's overview hub.
    nav_hub = ("" if args.type in ("space", "domain")
               else f"{prefix}{node_overview_rel(schema, node)[:-3]}")
    if args.type == "domain":
        if not node:
            print("ba_compile: FAIL: domain stubs need --node domains/<slug>",
                  file=sys.stderr)
            return 2
        target = space_dir / node / named_file_name(schema, "domain")
        extra["code"] = args.code or ""
        aliases = [args.code] if args.code else None
    elif loc["kind"] == "named_file":
        name = named_file_name(schema, args.type)
        target = space_dir / node / name if node else space_dir / name
        if args.type == "budget_set":
            extra["scope"] = "domain" if node else "space"
        if args.type == "space":
            extra["code"] = args.code or ""
            aliases = [args.code] if args.code else None
    elif args.type == "challenge_record":
        name = round_file_name(schema, args.review_scope, args.round)
        base = space_dir / node if node else space_dir
        target = base / loc["folder"] / name
    elif args.type == "decision":
        if not args.slug:
            print("ba_compile: FAIL: folder docs need --slug", file=sys.stderr)
            return 2
        pre_space, _ = scan_space(space_dir, schema)
        code = nearest_code(pre_space, node)
        if not code:
            print("ba_compile: FAIL: decision stubs need an owning node"
                  " code; declare the node overview first", file=sys.stderr)
            return 2
        # The id is minted in the ruling row and the alias; the filename
        # and the title stay natural (display-native naming).
        dec_id = next_ids(pre_space, code)["DEC"]
        base = space_dir / node if node else space_dir
        target = (base / loc["folder"]
                  / f"{args.slug}-{loc['filename_suffix']}.md")
        aliases = [dec_id]
        seed_rows = {"ruling": [dec_id, "To be decided.", "active",
                                utc_today().isoformat()]}
    else:
        if not args.slug:
            print("ba_compile: FAIL: folder docs need --slug", file=sys.stderr)
            return 2
        base = space_dir / node if node else space_dir
        suffix = loc.get("filename_suffix")
        name = f"{args.slug}-{suffix}.md" if suffix else f"{args.slug}.md"
        target = base / loc["folder"] / name
    if args.type == "rule_set":
        if not args.governs:
            print("ba_compile: FAIL: rule_set stubs need --governs", file=sys.stderr)
            return 2
        extra["governs"] = args.governs.split(",")
    if args.type == "acceptance_set":
        if not args.verifies:
            print("ba_compile: FAIL: acceptance_set stubs need --verifies",
                  file=sys.stderr)
            return 2
        extra["verifies"] = args.verifies.split(",")
    if args.type == "integration":
        extra["system_name"] = args.slug or ""
        extra["direction"] = args.direction
    if args.type == "challenge_record":
        extra["round"] = args.round
        extra["review_scope"] = args.review_scope
        extra["verdict"] = "continue"
    if target.exists():
        print(f"ba_compile: FAIL: {target} already exists", file=sys.stderr)
        return 1
    write_stub(schema, target, args.type, title, vault_prefix=prefix,
               nav_hub=nav_hub, aliases=aliases, seed_rows=seed_rows,
               **extra)
    space, _ = scan_space(space_dir, schema)
    code = nearest_code(space, node)
    print(f"ba_compile: created {target}")
    if code:
        free = next_ids(space, code)
        print("ba_compile: next free ids: "
              + ", ".join(free[k] for k in sorted(free)))
    return 0


def cmd_check(args, schema: dict) -> int:
    vault_root = require_vault_root(args)
    if vault_root is None:
        return 2
    schema = effective_schema(schema, vault_root)
    space, base = scan_space(Path(args.space), schema)
    space.vault_root = vault_root
    findings = run_checks(space, base, gate=args.gate == "approval",
                          gate_node=args.node)
    if not space.broken:
        warnings = [f for f in findings if f.severity == "warning"]
        findings += freshness_findings(space, warnings)
    return emit(findings, args.json)


def restamp_frontmatter(text: str, stamps: dict) -> str | None:
    """Set the given frontmatter keys in place (replace or insert before the
    closing delimiter), preserving everything else byte for byte."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        return None
    close = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            close = i
            break
    if close is None:
        return None
    remaining = dict(stamps)
    for i in range(1, close):
        key = lines[i].strip().partition(":")[0].strip()
        if key in remaining:
            lines[i] = f"{key}: {remaining.pop(key)}\n"
    lines[close:close] = [f"{k}: {v}\n" for k, v in remaining.items()]
    return "".join(lines)


def cmd_approve(args, schema: dict) -> int:
    """Approve a doc: the script stamps status, the UTC date and (for
    challenge records) verdict + locked in one write, then re-runs the
    checks; a doc the compiler rejects is restored untouched. The model
    never types the date."""
    space_dir = Path(args.space)
    vault_root = require_vault_root(args)
    if vault_root is None:
        return 2
    schema = effective_schema(schema, vault_root)
    space, base = scan_space(space_dir, schema)
    space.vault_root = vault_root
    rel = args.doc
    doc = space.docs.get(rel)
    if doc is None:
        print(f"ba_compile: FAIL: unknown doc '{rel}' in space {space_dir}",
              file=sys.stderr)
        return 2
    status = doc_status(doc)
    if status in ("approved", "superseded"):
        print(f"ba_compile: FAIL: {rel} is already {status}", file=sys.stderr)
        return 1
    if status != "in_review":
        print(f"ba_compile: FAIL: {rel} is '{status}', not in_review;"
              " approval follows review, flip the doc to in_review first",
              file=sys.stderr)
        return 1
    if doc.doc_type == "challenge_record" and not args.verdict:
        print("ba_compile: FAIL: a challenge record closes with --verdict",
              file=sys.stderr)
        return 2
    if args.verdict and doc.doc_type != "challenge_record":
        print("ba_compile: FAIL: --verdict applies only to challenge"
              " records", file=sys.stderr)
        return 2
    target = doc.abs_path
    original = target.read_text(encoding="utf-8")
    today = utc_today().isoformat()
    stamps: dict = {"status": "approved", "approved_at": today}
    if doc.doc_type == "challenge_record":
        stamps["verdict"] = args.verdict
        stamps["locked"] = "true"
    updated = restamp_frontmatter(original, stamps)
    if updated is None:
        print(f"ba_compile: FAIL: {rel} has no parseable frontmatter block",
              file=sys.stderr)
        return 1
    # The tag mirror rides the same write (one-clock, one operation).
    updated = re.sub(r"(?m)^(\s*- status/)[a-z0-9-]+\s*$",
                     r"\g<1>approved", updated, count=1)
    target.write_text(updated, encoding="utf-8")
    space, base = scan_space(space_dir, schema)
    space.vault_root = vault_root
    findings = run_checks(space, base)
    blocking = [f for f in findings
                if f.severity == "error" and f.path == rel]
    if blocking:
        target.write_text(original, encoding="utf-8")
        emit(blocking, args.json)
        print(f"ba_compile: FAIL: {rel} does not pass the checks as"
              " approved; original restored", file=sys.stderr)
        return 1
    closed = f", verdict {args.verdict}, locked" if args.verdict else ""
    print(f"ba_compile: approved {rel} (approved_at {today}{closed})")
    return 0


def cmd_render(args, schema: dict) -> int:
    vault_root = require_vault_root(args)
    if vault_root is None:
        return 2
    schema = effective_schema(schema, vault_root)
    space, base = scan_space(Path(args.space), schema)
    space.vault_root = vault_root
    if space.broken:
        emit([f for f in base if f.severity == "error"], args.json)
        print("ba_compile: FAIL: ambiguity findings block render", file=sys.stderr)
        return 1
    findings = run_checks(space, base)
    duplicate = [f for f in findings if f.check == "id_unique"]
    if duplicate:
        emit(duplicate, args.json)
        print("ba_compile: FAIL: duplicate ids block render", file=sys.stderr)
        return 1
    warnings = [f for f in findings if f.severity == "warning"]
    rendered = render_views(space, warnings)
    gen_dir = space.root / GENERATED_DIR
    if args.check_only:
        stale = freshness_findings(space, warnings)
        if stale:
            return emit(stale, args.json)
        print("ba_compile: generated views are fresh")
        return 0
    gen_dir.mkdir(parents=True, exist_ok=True)
    wrote = 0
    for name, content in rendered.items():
        target = gen_dir / name
        if target.is_file() and \
                target.read_text(encoding="utf-8", errors="replace") == content:
            continue
        target.write_text(content, encoding="utf-8")
        wrote += 1
    removed = 0
    for stray in sorted(gen_dir.iterdir()):
        if stray.name not in GENERATED_VIEWS and stray.name != ".gitkeep":
            stray.unlink()
            removed += 1
    print(f"ba_compile: rendered {wrote} view(s), removed {removed} stray file(s),"
          f" {len(rendered) - wrote} unchanged")
    return 0


def cmd_resolve(args, schema: dict) -> int:
    space, _ = scan_space(Path(args.space), schema)
    wanted = [i.strip() for i in args.ids.split(",") if i.strip()]
    result = {}
    missing = []
    for id_value in wanted:
        info = space.ids.get(id_value)
        if info is None:
            missing.append(id_value)
            continue
        statement = statement_of(space, id_value)
        result[id_value] = {
            "doc": info["doc"],
            "doc_status": doc_status(space.docs[info["doc"]]),
            "statement": statement,
            "statement_sha256": hashlib.sha256(statement.encode("utf-8")).hexdigest(),
        }
    print(json.dumps(result, indent=2, sort_keys=True))
    if missing:
        print(f"ba_compile: FAIL: unknown ids: {', '.join(missing)}", file=sys.stderr)
        return 1
    return 0


def cmd_verify_import(args, schema: dict) -> int:
    space, _ = scan_space(Path(args.space), schema)
    data = json.loads(Path(args.json_file).read_text(encoding="utf-8"))
    failures = []
    for entry in data.get("criteria", []):
        criterion = str(entry.get("criterion_id", ""))
        info = space.ids.get(criterion)
        if info is None:
            failures.append(f"{criterion}: not declared in the space")
            continue
        if str(entry.get("disposition", "")) == "deferred":
            continue
        owner_status = doc_status(space.docs[info["doc"]])
        if owner_status != "approved":
            failures.append(f"{criterion}: owning doc {info['doc']} is"
                            f" {owner_status}, not approved")
    for failure in failures:
        print(f"ba_compile: FAIL: {failure}", file=sys.stderr)
    if failures:
        return 1
    print(f"ba_compile: OK: {len(data.get('criteria', []))} criterion id(s) verified")
    return 0


