class ModelChoiceTests(unittest.TestCase):
    """`tiers --model-list` lists each tier's model choices for the configure topic:
    the package model, then the active host's list or the catalog, then `session`."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.market = COMMITTED

    def setUp(self) -> None:
        self.project = Project(self.market)
        self.addCleanup(self.project.close)

    def package_with(self, adapter: str | None) -> Path:
        """A copy of the Claude package, with a host_models adapter of ``adapter`` source."""
        target = self.project.work / "install" / PLUGIN
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(self.market.package, target)
        if adapter is not None:
            (target / "scripts" / "host_models.py").write_text(adapter, encoding="utf-8")
        return target

    def choices(self, host: str, package: Path | None = None) -> dict:
        result = self.project.project_config("classes", "--host", host, "--model-list", "--json",
                                             package=package)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return json.loads(result.stdout)["hosts"][host]

    def recommended(self, host: str, tier: str, efforts: list[str]) -> str | None:
        """The tier's package effort when the model takes it, else the nearest one
        below it, else the lowest."""
        package = self.market.tier(host, tier).get("effort")
        levels = self.market.host(host)["efforts"]
        if not efforts or package in efforts:
            return package if efforts else None
        below = [effort for effort in efforts if levels.index(effort) < levels.index(package)]
        return below[-1] if below else efforts[0]

    def assert_catalog_choices(self, report: dict, host: str) -> None:
        catalog = sorted(self.market.host(host)["models"])
        for tier in TIERS:
            package = self.market.tier(host, tier)
            with self.subTest(host=host, tier=tier):
                models = [choice["model"] for choice in report["model_choices"][tier]]
                self.assertEqual(models, [package["model"],
                                          *[model for model in catalog if model != package["model"]],
                                          "session"])
                for choice in report["model_choices"][tier]:
                    efforts = self.market.efforts(host, choice["model"])
                    self.assertEqual(choice["efforts"], efforts)
                    self.assertEqual(choice["recommended_effort"],
                                     self.recommended(host, tier, efforts))

    def test_the_host_list_offers_its_models_in_the_hosts_shape(self):
        listing = {
            "status": "ok", "binary": "/bin/fake", "version": "9.9.9", "view": "account",
            "models": {"claude-opus-5-5": {"efforts": ["low", "medium", "high", "xhigh", "max"]},
                       UNLISTED["claude"]: {"efforts": ["low", "medium", "high"]},
                       "opus[1m]": {"efforts": [LOW]},
                       "claude-sonnet-5-5": {"efforts": [MEDIUM]}},
        }
        package = self.package_with(
            "import json\n"
            f"LISTING = json.loads({json.dumps(json.dumps(listing))})\n"
            "def list_models(environ=None, timeout=None):\n    return LISTING\n"
            "def efforts(model_id, listing):\n"
            "    entry = listing['models'].get(model_id)\n"
            "    return None if entry is None else entry['efforts']\n"
            "def verdict(model_id, listing):\n    return 'available'\n")
        report = self.choices("claude", package)
        self.assertEqual(report["model_list"], {"source": "host", "status": "ok",
                                                "view": "account", "binary": "/bin/fake",
                                                "version": "9.9.9", "hidden": []})
        high = report["model_choices"][TOP]
        package_model = self.market.tier("claude", TOP)["model"]
        self.assertEqual([choice["model"] for choice in high],
                         [package_model, *sorted(model for model in listing["models"]
                                                 if model != package_model and "[" not in model),
                          "session"])
        by_model = {choice["model"]: choice for choice in high}
        # A model outside the catalog takes the host list's levels, and the
        # recommended effort is the nearest one below the slot's package effort.
        self.assertEqual(by_model[UNLISTED["claude"]]["efforts"], ["low", "medium", "high"])
        self.assertEqual(by_model[UNLISTED["claude"]]["recommended_effort"],
                         self.recommended("claude", TOP, ["low", "medium", "high"]))
