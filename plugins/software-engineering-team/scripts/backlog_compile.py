def init(args) -> int:
    docs = docs_root(args.docs)
    planning_mode = getattr(args, "planning_mode", "")
    requirement_ref = getattr(args, "requirement_ref", "")
    input_ref = list(getattr(args, "input_ref", []) or [])
    absent = list(getattr(args, "absent_input", []) or [])
    existing_root = docs / "backlog" / "backlog.md"
    if existing_root.is_file():
        existing_props, _existing_body = parse_front_matter(existing_root)
        if absent or existing_props.get("input_contract") or existing_props.get("absent_input_stages"):
            if (existing_props.get("status") == "approved"
                    or set(values(existing_props, "absent_input_stages")) != set(absent)):
                print("backlog_compile: init cannot change an existing absence contract; "
                      "approve the current draft and use begin-revision", file=sys.stderr)
                return 1
    if absent and planning_mode != "requirement":
        print("backlog_compile: --absent-input requires Requirement mode", file=sys.stderr)
        return 2
    if planning_mode == "manual" and (requirement_ref or len(input_ref) < 4):
        print(
            "backlog_compile: manual init needs BA, Solution, Design, one "
            "application and its exact zero-or-more Experience process "
            "--input-ref values, with no Requirement",
            file=sys.stderr,
        )
        return 2
    if planning_mode == "requirement" and not requirement_ref:
        print("backlog_compile: requirement init needs --requirement-ref; --input-ref pins "
              "only the stages the Requirement marks not_applicable", file=sys.stderr)
        return 2
    input_bindings: list[str] = []
    # Resolve every selected receipt against one immutable graph snapshot.
    # Recompiling that graph per receipt turns a valid manual handoff into a
    # quadratic preflight without increasing its freshness guarantee.
    session = (
        stage_package.candidate_session()
        if planning_mode == "manual" else contextlib.nullcontext()
    )
    with session:
        if planning_mode == "manual":
            input_bindings, binding_errors = resolve_manual_input_bindings(
                docs, input_ref, "backlog/backlog.md")
            if binding_errors:
                print(json.dumps({"ok": False, "errors": binding_errors},
                                 indent=2, ensure_ascii=False), file=sys.stderr)
                return 1
        elif planning_mode == "requirement":
            input_bindings, binding_errors = requirement_input_bindings(
                docs, requirement_ref, [], input_ref, "backlog/backlog.md", absent_stages=absent)
            if binding_errors:
                print(json.dumps({"ok": False, "errors": binding_errors},
                                 indent=2, ensure_ascii=False), file=sys.stderr)
                return 1
        # Resolve all upstreams before creating the backlog directory.  A failed
        # selection must not leave a half-created manual or Requirement package.
        if planning_mode:
            candidate_props = {"planning_mode": planning_mode}
            if absent:
                candidate_props.update(input_contract=backlog_contract()["applicable_inputs"]["contract"],
                                       absent_input_stages=absent)
            if requirement_ref:
                candidate_props["requirement_ref"] = requirement_ref
            if input_bindings:
                candidate_props["input_bindings"] = input_bindings
            _mode, _refs, preflight = planning_package_findings(
                docs, candidate_props, "backlog/backlog.md")
            if preflight:
                print(json.dumps({"ok": False, "errors": sorted(set(preflight))},
                                 indent=2, ensure_ascii=False), file=sys.stderr)
                return 1
    root = docs / "backlog"
    (root / "reviews").mkdir(parents=True, exist_ok=True)
    (root / "epics").mkdir(parents=True, exist_ok=True)
    if vault_check is not None and (docs / ".obsidian").is_dir():
        policy = vault_check.load_policy(vault_check.DEFAULT_POLICY)
        vault_check.reconcile_payload_fragment(docs, policy, "backlog")
    backlog_title = DEFAULT_BACKLOG_TITLE
    review_title = DEFAULT_BACKLOG_REVIEW_TITLE
    files = {
        root / "backlog.md": front_matter(
            {"type": "backlog", "title": backlog_title, "status": "draft",
             "owner_role": "product_owner", "revision": 1,
             "tags": ["doc/backlog", "status/draft"], "aliases": ["BACKLOG"]},
            f"# {backlog_title}\n\nThis file indexes the approved project scope.\n"),
        root / "reviews" / "round-1-backlog-review.md": front_matter(
            {"type": "backlog-review", "title": review_title,
             "status": "draft", "owner_role": "product_owner", "round": 1,
             "derives_from": [f"[[backlog/backlog|{backlog_title}]]"],
             "tags": ["doc/backlog-review", "status/draft"],
             "aliases": ["BACKLOG-REVIEW-001"], **round_pin(docs)},
            review_body(review_title, backlog_review_sections(planning_mode))),
    }
    for path, text in files.items():
        if not path.exists():
            path.write_bytes(text.encode("utf-8"))
    root_note = root / "backlog.md"
    props, body = parse_front_matter(root_note)
    if planning_mode:
        props["planning_mode"] = planning_mode
    else:
        # Internal legacy readers may materialize an old package for
        # verification. Public CLI creation always requires planning_mode.
        props["legacy_contract"] = True
    if requirement_ref:
        props["requirement_ref"] = requirement_ref
    if input_bindings:
        props["input_bindings"] = input_bindings
    if absent:
        props["input_contract"] = backlog_contract()["applicable_inputs"]["contract"]
        props["absent_input_stages"] = absent
    root_note.write_bytes(front_matter(props, body).encode("utf-8"))
    map_path = docs / "maps" / "backlog.md"
    map_path.parent.mkdir(parents=True, exist_ok=True)
    if not map_path.is_file():
        map_path.write_bytes(front_matter(
            {"type": "moc", "title": "Backlog map", "tags": ["doc/moc"]},
            "# Backlog map\n").encode("utf-8"))
    normalize_backlog_map_aliases(map_path, backlog_title)
    ensure_home_map(docs)
    append_nav(root / "backlog.md", ["[[maps/backlog|Backlog map]]"])
    append_nav(root / "reviews" / "round-1-backlog-review.md", [
        "[[maps/backlog|Backlog map]]",
        f"[[backlog/backlog|{backlog_title}]]",
    ])
    print(root)
    return 0


