def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def render_cursor_plugin_manifest(plugin: Path, source_manifest: dict,
                                  harness: dict, has_hooks: bool) -> dict:
    out: dict = {"name": source_manifest.get("name", plugin.name)}
    if source_manifest.get("description"):
        out["description"] = source_manifest["description"]
    if source_manifest.get("version"):
        out["version"] = source_manifest["version"]
    author = source_manifest.get("author") or {}
    if author.get("name"):
        out["author"] = {"name": author["name"]}
    if author.get("url"):
        out["homepage"] = author["url"]
    if source_manifest.get("license"):
        out["license"] = source_manifest["license"]
    if agent_files(plugin):
        out["agents"] = "./" + harness["agents_dir"]
    if has_hooks:
        out["hooks"] = "./" + harness["hooks_manifest"]
    return out


def render_codex_plugin_manifest(plugin: Path, source_manifest: dict,
                                 harness: dict, has_hooks: bool) -> dict:
    out: dict = {"name": source_manifest.get("name", plugin.name)}
    if source_manifest.get("version"):
        out["version"] = source_manifest["version"]
    if source_manifest.get("description"):
        out["description"] = source_manifest["description"]
    author = source_manifest.get("author") or {}
    if author.get("name"):
        out["author"] = {"name": author["name"]}
    if author.get("url"):
        out["homepage"] = author["url"]
    if source_manifest.get("license"):
        out["license"] = source_manifest["license"]
    if skill_dirs(plugin):
        out["skills"] = "./skills/"
    if has_hooks:
        out["hooks"] = "./" + harness["hooks_manifest"]
    return out


def render_cursor_marketplace(source_marketplace: dict) -> dict:
    owner = source_marketplace.get("owner") or {}
    out: dict = {"name": source_marketplace.get("name", "")}
    out["owner"] = {"name": owner.get("name", "")}
    out["plugins"] = [
        {
            "name": entry.get("name", ""),
            "source": entry.get("source", ""),
            "description": entry.get("description", ""),
            "version": entry.get("version", ""),
            "license": entry.get("license", ""),
        }
        for entry in source_marketplace.get("plugins", [])
    ]
    return out


def render_codex_marketplace(source_marketplace: dict) -> dict:
    return {
        "name": source_marketplace.get("name", ""),
        "plugins": [
            {
                "name": entry.get("name", ""),
                "description": entry.get("description", ""),
                "source": {"source": "local", "path": entry.get("source", "")},
            }
            for entry in source_marketplace.get("plugins", [])
        ],
    }


