def emit(findings: list[Finding], as_json: bool) -> int:
    ordered = sorted(findings, key=lambda f: (f.path, f.line, f.check, f.message))
    errors = sum(1 for f in ordered if f.severity == "error")
    warnings = len(ordered) - errors
    for f in ordered:
        if as_json:
            print(json.dumps({"severity": f.severity, "path": f.path,
                              "line": f.line, "check": f.check,
                              "message": f.message, "fix": f.remediation},
                             sort_keys=True))
        else:
            print(f"{f.severity.upper()} {f.path}:{f.line} [{f.check}]"
                  f" {f.message} | Fix: {f.remediation}")
    if not as_json:
        print(f"ba_compile: {errors} error(s), {warnings} warning(s)")
    return 1 if errors else 0


def load_schema(path: Path) -> dict:
    schema = json.loads(path.read_text(encoding="utf-8"))
    if schema.get("schema_version") != 1:
        raise SystemExit(f"ba_compile: unknown schema_version in {path}")
    return schema


