@unittest.skipIf(os.name == "nt", "a Windows writer needs an attested cmd payload")
class VaultHookTests(unittest.TestCase):
    """The package's own vault hook keeps what `project_config.py` writes in a session."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.market = Marketplace()

    @classmethod
    def tearDownClass(cls) -> None:
        cls.market.cleanup()

    def setUp(self) -> None:
        self.project = Project(self.market)
        self.addCleanup(self.project.close)
        (self.project.root / "workspace" / "docs").mkdir()
        self.recovery = self.project.work / "recovery"
        self.recovery.mkdir()
        self.events = 0

    def guarded(self, host: str, *args: str) -> subprocess.CompletedProcess:
        """Run one `project_config.py` command between the host package's hook pre and post."""
        package = self.market.root / "dist" / host / PLUGIN
        argv = [sys.executable, str(package / "scripts" / "project_config.py"), args[0],
                "--config", str(self.project.config), *args[1:]]
        self.events += 1
        payload = {"tool_name": "Bash", "tool_input": {"command": shlex.join(argv)},
                   "cwd": str(self.project.root), "session_id": f"models-hook-{host}",
                   "tool_use_id": f"toolu_models_{self.events}"}
        env = dict(os.environ, TMPDIR=str(self.recovery), PYTHONDONTWRITEBYTECODE="1")

        def hook(mode: str, event: str) -> subprocess.CompletedProcess:
            return subprocess.run(
                [sys.executable, str(package / "scripts" / "vault_hook.py"), mode],
                input=json.dumps({**payload, "hook_event_name": event}), capture_output=True,
                text=True, check=False, timeout=120, env=env)

        pre = hook("pre", "PreToolUse")
        self.assertEqual(pre.returncode, 0, pre.stdout + pre.stderr)
        subprocess.run(argv, cwd=self.project.root, capture_output=True, text=True,
                       check=False, timeout=120, env=env)
        return hook("post", "PostToolUse")

    def config(self) -> dict:
        return load(self.project.config)

    def assert_restored(self, host: str, *args: str) -> None:
        before = self.project.config.read_bytes()
        post = self.guarded(host, *args)
        self.assertEqual(post.returncode, 2, post.stdout + post.stderr)
        self.assertIn("the original config was restored", post.stdout + post.stderr)
        self.assertEqual(self.project.config.read_bytes(), before)

    def test_the_hook_keeps_set_tier_and_set_role_tier_writes_on_every_host(self):
        for host in build_distributions.HOSTS:
            with self.subTest(host=host):
                self.project.write_config()
                effort = self.market.non_default(host, "high", model="session")
                post = self.guarded(host, "set-tier", "--host", host, "--tier", "high",
                                    "--model", "session", "--effort", effort)
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["tier_models"],
                                 {host: {"high": {"model": "session", "effort": effort}}})
                post = self.guarded(host, "set-tier", "--host", host, "--tier", "high",
                                    "--default", "--json")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                post = self.guarded(host, "set-role-tier", "--role", MOVED, "--tier", "medium")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["role_tiers"], {MOVED: "medium"})
                post = self.guarded(host, "set-role-tier", "--role", MOVED, "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                post = self.guarded(host, "set", "--field", "output_language", "--value",
                                    "Turkish")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["output_language"], "Turkish")
                # The repair of a tier, host or role the package retired survives too.
                self.project.write_config(tier_models={"retired": {"ghost": {"effort": "high"}}},
                                          role_tiers={"retired-role": "low"})
                post = self.guarded(host, "set-tier", "--host", "retired", "--tier", "ghost",
                                    "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                post = self.guarded(host, "set-role-tier", "--role", "retired-role", "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                # A form the writer takes but the hook's exact parse does not, such
                # as an abbreviated option, is still put back.
                self.assert_restored(host, "set-tier", "--host", host, "--tier", "high",
                                     "--eff", effort)
                self.assert_restored(host, "set-role-tier", "--ro", MOVED, "--tier", "medium")


