@integration
@unittest.skipIf(os.name == "nt", "a Windows writer needs an attested cmd payload")
class VaultHookTests(unittest.TestCase):
    """The package's own vault hook keeps what `project_config.py` writes in a session."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.market = Marketplace()

    @classmethod
    def tearDownClass(cls) -> None:
        cls.market.cleanup()

    def setUp(self) -> None:
        self.project = Project(self.market)
        self.addCleanup(self.project.close)
        (self.project.root / "workspace" / "docs").mkdir()
        self.recovery = self.project.work / "recovery"
        self.recovery.mkdir()
        self.events = 0

    def guarded(self, host: str, *args: str) -> subprocess.CompletedProcess:
        """Run one `project_config.py` command between the host package's hook pre and post."""
        package = self.market.root / "dist" / host / PLUGIN
        argv = [sys.executable, str(package / "scripts" / "project_config.py"), args[0],
                "--config", str(self.project.config), *args[1:]]
        self.events += 1
        payload = {"tool_name": "Bash", "tool_input": {"command": shlex.join(argv)},
                   "cwd": str(self.project.root), "session_id": f"models-hook-{host}",
                   "tool_use_id": f"toolu_models_{self.events}"}
        env = dict(os.environ, TMPDIR=str(self.recovery), PYTHONDONTWRITEBYTECODE="1")

        def hook(mode: str, event: str) -> subprocess.CompletedProcess:
            return subprocess.run(
                [sys.executable, str(package / "scripts" / "hook_launcher.py"), "scripts/vault_hook.py", mode],
                input=json.dumps({**payload, "hook_event_name": event}), capture_output=True,
                text=True, check=False, timeout=120, env=env)

        pre = hook("pre", "PreToolUse")
        self.assertEqual(pre.returncode, 0, pre.stdout + pre.stderr)
        subprocess.run(argv, cwd=self.project.root, capture_output=True, text=True,
                       check=False, timeout=120, env=env)
        return hook("post", "PostToolUse")

    def config(self) -> dict:
        return load(self.project.config)

    def assert_restored(self, host: str, *args: str) -> None:
        before = self.project.config.read_bytes()
        post = self.guarded(host, *args)
        self.assertEqual(post.returncode, 2, post.stdout + post.stderr)
        self.assertIn("the original config was restored", post.stdout + post.stderr)
        self.assertEqual(self.project.config.read_bytes(), before)

    def test_the_hook_keeps_set_class_and_set_role_class_writes_on_every_host(self):
        for host in build_distributions.HOSTS:
            with self.subTest(host=host):
                self.project.write_config()
                effort = self.market.non_default(host, HIGH, model="session")
                post = self.guarded(host, "set-class", "--host", host, "--class", HIGH,
                                    "--model", "session", "--effort", effort)
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["class_models"],
                                 {host: {HIGH: {"model": "session", "effort": effort}}})
                post = self.guarded(host, "set-class", "--host", host, "--class", HIGH,
                                    "--default", "--json")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                post = self.guarded(host, "set-role-class", "--role", MOVED, "--class", MEDIUM)
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["role_classes"], {MOVED: MEDIUM})
                post = self.guarded(host, "set-role-class", "--role", MOVED, "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                post = self.guarded(host, "set", "--field", "output_language", "--value",
                                    "Turkish")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(self.config()["output_language"], "Turkish")
                # The repair of a tier, host or role the package retired survives too.
                self.project.write_config(class_models={"retired": {"ghost": {"effort": "high"}}},
                                          role_classes={"retired-role": LOW})
                post = self.guarded(host, "set-class", "--host", "retired", "--class", "ghost",
                                    "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                post = self.guarded(host, "set-role-class", "--role", "retired-role", "--default")
                self.assertEqual(post.returncode, 0, post.stdout + post.stderr)
                self.assertEqual(set(self.config()), BASE_KEYS)
                # A form the writer takes but the hook's exact parse does not, such
                # as an abbreviated option, is still put back.
                self.assert_restored(host, "set-class", "--host", host, "--class", HIGH,
                                     "--eff", effort)
                self.assert_restored(host, "set-role-class", "--ro", MOVED, "--class", MEDIUM)


# A hand-written CLAUDE.md beside its user-owned companion: apply replaces the
# root only after the owner chooses to preserve or discard that text.
HAND_WRITTEN = "# Team notes\n\nHand-written before setup.\n"
COMPANION = "# Project Instructions\n\nThe owner's own rules.\n"


def tree(root: Path) -> dict[str, bytes | None]:
    """Every path under ``root``: a file with its bytes, a directory with None."""
    return {path.relative_to(root).as_posix(): path.read_bytes() if path.is_file() else None
            for path in sorted(root.rglob("*"))}


def assert_inspect_previews(test: unittest.TestCase, root: Path, generate) -> None:
    """A project generator's `inspect` plans what its `check` plans: the change to a
    hand-written CLAUDE.md and the owner's open choice, reading no model list and
    writing nothing."""
    (root / "CLAUDE.md").write_text(HAND_WRITTEN, encoding="utf-8")
    (root / "CLAUDE.user.md").write_text(COMPANION, encoding="utf-8")
    before = tree(root)
    inspected = generate("inspect")
    test.assertEqual(inspected.returncode, 0, inspected.stdout + inspected.stderr)
    test.assertEqual(tree(root), before)
    plan = json.loads(inspected.stdout)
    test.assertEqual(plan["status"], "choice_required")
    test.assertIn("CLAUDE.md", plan["changes"])
    [request] = plan["choice_requests"]
    test.assertEqual((request["id"], request["surface"], request["reason"]),
                     ("claude.root.claude", "CLAUDE.md", "unmanaged_content"))
    test.assertEqual(request["preview"]["companion_before_sha256"],
                     hashlib.sha256(COMPANION.encode("utf-8")).hexdigest())
    test.assertNotEqual(plan["target_surfaces"], plan["current_surfaces"])
    test.assertEqual(plan["model_check"], {"status": "not_run"})
    checked = generate("check")
    test.assertEqual(checked.returncode, 0, checked.stdout + checked.stderr)
    test.assertEqual(json.loads(checked.stdout), plan)


