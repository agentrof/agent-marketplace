def table_row_columns(note: Note) -> dict[int, list[str]]:
    """lineno -> header columns for every data row of a well-formed table."""
    mapping: dict[int, list[str]] = {}
    in_fence = False
    block: list[tuple[int, str]] = []

    def flush() -> None:
        if len(block) >= 2 and is_separator_row(block[1][1]):
            columns = [c.strip().lower()
                       for c in re.split(r"(?<!\\)\|",
                                         block[0][1].strip().strip("|"))]
            for lineno, _raw in block[2:]:
                mapping[lineno] = columns
        block.clear()

    for lineno, line in enumerate(note.lines, start=1):
        if lineno < note.fm_end:
            continue
        if line.lstrip().startswith("```"):
            flush()
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if is_table_row(line):
            block.append((lineno, line))
        else:
            flush()
    flush()
    return mapping


def ba_id_lookup(vault: Vault) -> dict[str, str]:
    """id -> vault-absolute owner rel (no .md) for every analysis space
    in the vault, through ba_compile.scan_space (the single parser)."""
    lookup: dict[str, str] = {}
    try:
        schema = ba_compile.load_schema(ba_compile.DEFAULT_SCHEMA)
    except (OSError, json.JSONDecodeError, SystemExit):
        return lookup
    roots = set()
    for rel in vault.index:
        parts = rel.split("/")
        if len(parts) >= 2 and parts[-1] == ba_compile.space_overview_rel(
                schema):
            roots.add("/".join(parts[:-1]))
    for root_rel in sorted(roots):
        space, _ = ba_compile.scan_space(vault.root / root_rel, schema)
        for id_value, info in space.ids.items():
            lookup.setdefault(id_value, f"{root_rel}/{info['doc'][:-3]}")
    return lookup


def rewrite_citation_cells(line: str, columns: list[str],
                           citation_columns: list[str],
                           id_lookup: dict[str, str]) -> tuple[str, int, int]:
    """Rewrite bare id tokens in id-citation cells to escaped-pipe
    wikilinks targeting the owning doc; unresolvable ids stay manual."""
    parts = re.split(r"(?<!\\)\|", line)
    if len(parts) != len(columns) + 2:
        return line, 0, 0
    rewrites = manual = 0
    for i, column in enumerate(columns, start=1):
        if column not in citation_columns:
            continue
        cell = parts[i]
        masked = WIKILINK_RE.sub(lambda m: "\0" * len(m.group(0)), cell)
        matches = sorted(
            list(NAMESPACED_ID_RE.finditer(masked))
            + list(BARE_ID_RE.finditer(masked)),
            key=lambda m: -m.start())
        for match in matches:
            token = match.group(0)
            owner = id_lookup.get(token)
            if owner is None:
                manual += 1
                continue
            cell = (cell[:match.start()] + f"[[{owner}\\|{token}]]"
                    + cell[match.end():])
            rewrites += 1
        parts[i] = cell
    return "|".join(parts), rewrites, manual


def migrate_note(vault: Vault, note: Note, citation_columns: list[str],
                 id_lookup: dict[str, str]) -> tuple[str, int, int]:
    """Return (new_text, rewrites, manual_left) for one note."""
    root = vault.root
    rewrites = 0
    manual = 0
    out: list[str] = []
    in_fence = False
    row_columns = table_row_columns(note) if citation_columns else {}
    for lineno, line in enumerate(note.lines, start=1):
        if lineno < note.fm_end:
            new_line, n = migrate_fm_line(vault, note, line)
            rewrites += n
            out.append(new_line)
            continue
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        new_line = line
        for match in sorted(LINK_RE.finditer(line),
                            key=lambda m: -m.start()):
            text_part, target = match.group(1), match.group(2)
            if target.startswith(("http://", "https://", "mailto:", "#", "/")):
                continue
            clean, _, fragment = target.partition("#")
            if fragment and not fragment.startswith("^"):
                manual += 1  # heading anchors need judgment, not rewriting
                continue
            resolved = (note.path.parent / clean).resolve()
            try:
                rel = resolved.relative_to(root).as_posix()
            except ValueError:
                continue
            if rel not in vault.index or not rel.endswith(".md"):
                continue
            alias = text_part.replace("\\|", "|")
            inner = rel[:-3] + (f"#{fragment}" if fragment else "")
            sep = "\\|" if is_table_row(line) else "|"
            new_line = (new_line[:match.start()]
                        + f"[[{inner}{sep}{alias}]]"
                        + new_line[match.end():])
            rewrites += 1
        if lineno in row_columns:
            new_line, n, m = rewrite_citation_cells(
                new_line, row_columns[lineno], citation_columns, id_lookup)
            rewrites += n
            manual += m
        if is_table_row(new_line):
            fixed = fix_table_pipes(new_line)
            if fixed != new_line:
                rewrites += 1
                new_line = fixed
        out.append(new_line)
    text = "\n".join(out)
    if note.lines and note.path.read_text(encoding="utf-8").endswith("\n"):
        text += "\n"
    return text, rewrites, manual


def deid_lead_decision(policy: dict, note: Note,
                       lines: list[str]) -> int:
    """Strip a decision-tree note's legacy '<ID>: ' lead from the title
    AND the first H1 in the same write (title law v2: labels are never
    id-led; the id's single home is the frontmatter alias)."""
    tree = note_decision_tree(policy, note.rel)
    if tree is None:
        return 0
    rec_id = decision_id(tree, note)
    if rec_id is None:
        return 0
    prefix = f"{rec_id}: "
    changed = 0
    for i in range(min(note.fm_end - 1, len(lines))):
        stripped = lines[i].strip()
        if not stripped.startswith("title:"):
            continue
        value = stripped[len("title:"):].strip().strip("\"'")
        if value.startswith(prefix):
            indent = lines[i][:len(lines[i]) - len(lines[i].lstrip())]
            new_value = value[len(prefix):]
            quoted = f'"{new_value}"' if ":" in new_value else new_value
            lines[i] = f"{indent}title: {quoted}"
            changed += 1
        break
    for i in range(note.fm_end - 1, len(lines)):
        if lines[i].startswith("# "):
            if lines[i][2:].startswith(prefix):
                lines[i] = "# " + lines[i][2 + len(prefix):]
                changed += 1
            break
    return changed


def append_designation(vault: Vault, note: Note, lines: list[str]) -> int:
    """Append the type's configured designation to a title that lacks it,
    rewriting the first H1 in the same write (title == H1 law). Reads the
    CURRENT title from lines, so it composes with the id-lead strip; skips
    when the map is absent, the type is nav or unmapped, or the designation
    is already present (idempotent through the SAME test the check uses).
    Challenge records are excluded: round-number placement is judgment, so
    they stay a check finding for build-docs-vault to retitle."""
    designations = vault.designations
    if designations is None:
        return 0
    note_type = note.fm.get("type")
    kebab_type = kebab(note_type) if note_type else ""
    if kebab_type not in vault.taxonomy_types or kebab_type == "challenge-record":
        return 0
    designation = designations.get(kebab_type)
    if not designation:
        return 0
    title_idx = None
    current = ""
    for i in range(min(note.fm_end - 1, len(lines))):
        stripped = lines[i].strip()
        if stripped.startswith("title:"):
            current = stripped[len("title:"):].strip().strip("\"'")
            title_idx = i
            break
    if title_idx is None or not current or designation_present(current, designation):
        return 0
    new_title = f"{current} {designation}"
    indent = lines[title_idx][:len(lines[title_idx])
                              - len(lines[title_idx].lstrip())]
    quoted = f'"{new_title}"' if ":" in new_title else new_title
    lines[title_idx] = f"{indent}title: {quoted}"
    for i in range(note.fm_end - 1, len(lines)):
        if lines[i].startswith("# "):
            if lines[i][2:].strip() == current:
                lines[i] = f"# {new_title}"
            break
    return 1


def retarget_nav(vault: Vault, note: Note, lines: list[str]) -> int:
    """Rewrite a maps/<subtree> nav first link to the covering hub that
    EXISTS in the current index (composing with --rename in either
    order); a hub already among the peers is promoted by dropping the
    map link instead of duplicating it."""
    policy = vault.policy
    maps_dir = policy["maps_dir"]
    if not note.subtree or note.subtree == maps_dir \
            or is_hub(policy, note.rel):
        return 0
    hub = resolve_hub(policy, vault.index, note.rel)
    if hub is None:
        return 0
    hub_stem = hub[:-3]
    owning_map = f"{maps_dir}/{note.subtree}"
    nav_idx = next((i for i, l in enumerate(lines) if NAV_MARKER in l), None)
    if nav_idx is None:
        return 0
    nav_text = "\n".join(lines[nav_idx:])
    matches = list(WIKILINK_RE.finditer(nav_text))
    if not matches:
        return 0
    first_target, _, _ = split_wikilink(matches[0].group("inner"))
    if first_target != owning_map:
        return 0
    hub_note = vault.notes.get(hub)
    alias = str(hub_note.fm.get("title") or "") if hub_note else ""
    if not alias:
        alias = hub_stem.rsplit("/", 1)[-1].replace("-", " ").title()
    peer_targets = [split_wikilink(m.group("inner"))[0] for m in matches[1:]]
    nav_text = (nav_text[:matches[0].start()] + f"[[{hub_stem}|{alias}]]"
                + nav_text[matches[0].end():])
    if hub_stem in peer_targets:
        for match in list(WIKILINK_RE.finditer(nav_text))[1:]:
            target, _, _ = split_wikilink(match.group("inner"))
            if target == hub_stem:
                nav_text = (nav_text[:match.start()] + "\0DROP\0"
                            + nav_text[match.end():])
                break
        cleaned = []
        for line in nav_text.splitlines():
            if "\0DROP\0" in line:
                line = line.replace("\0DROP\0", "").strip()
                line = line.strip("-").strip()
                if not line:
                    continue
            cleaned.append(line)
        nav_text = "\n".join(cleaned)
    lines[nav_idx:] = nav_text.splitlines()
    return 1


def fix_table_pipes(line: str) -> str:
    def fix(match: re.Match) -> str:
        inner = match.group("inner")
        fixed_inner = re.sub(r"(?<!\\)\|", r"\\|", inner)
        return f"{match.group('embed')}[[{fixed_inner}]]"
    return WIKILINK_RE.sub(fix, line)


# Doc-ref keys whose contract form is a BLOCK LIST (single target = one
# item); a scalar value is the migrate class that converts it.
LIST_REF_KEYS = ("governs", "verifies")


def migrate_fm_line(vault: Vault, note: Note, line: str) -> tuple[str, int]:
    stripped = line.strip()
    for key in DOC_REF_KEYS:
        if not stripped.startswith(f"{key}:"):
            continue
        value = stripped[len(key) + 1:].strip().strip("\"'")
        if not value:
            return line, 0
        indent = line[:len(line) - len(line.lstrip())]
        if value.startswith("[["):
            if key in LIST_REF_KEYS:
                return f"{indent}{key}:\n{indent}  - \"{value}\"", 1
            return line, 0
        resolved = (note.path.parent / value).resolve()
        try:
            rel = resolved.relative_to(vault.root).as_posix()
        except ValueError:
            return line, 0
        if rel in vault.index and rel.endswith(".md"):
            link = f"\"[[{rel[:-3]}]]\""
            if key in LIST_REF_KEYS:
                return f"{indent}{key}:\n{indent}  - {link}", 1
            return f"{indent}{key}: {link}", 1
    return line, 0


def migrate_tags(note: Note) -> tuple[list[str], bool]:
    note_type = note.fm.get("type")
    if not note_type:
        return [], False
    expected = [f"doc/{kebab(note_type)}"]
    status = note.fm.get("status")
    if status:
        expected.append(f"status/{kebab(status)}")
    current = note.fm.get("tags")
    if isinstance(current, list) and set(current) == set(expected):
        return expected, False
    return expected, True


def apply_tags(text: str, tags: list[str]) -> str:
    lines = text.splitlines()
    out: list[str] = []
    in_fm = False
    fm_closed = False
    skipping = False
    wrote = False
    for line in lines:
        stripped = line.strip()
        if stripped == "---" and not fm_closed:
            if in_fm:
                if not wrote:
                    out.append("tags:")
                    out.extend(f"  - {t}" for t in tags)
                    wrote = True
                fm_closed = True
                in_fm = False
            else:
                in_fm = True
            out.append(line)
            continue
        if in_fm:
            if skipping:
                if stripped.startswith("- "):
                    continue
                skipping = False
            if stripped.startswith("tags:") or stripped.startswith("tag:"):
                out.append("tags:")
                out.extend(f"  - {t}" for t in tags)
                wrote = True
                skipping = True
                continue
        out.append(line)
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


def freeze_skip_set(vault_path: Path) -> set:
    """Vault-relative paths frozen by any work order. MECHANICAL and
    PMO-independent: the workspace root is derived from --vault, the
    manifests are globbed from work-orders/, and the set is loaded
    BEFORE any write. PMO absence never voids freeze protection."""
    frozen: set = set()
    orders = vault_path.resolve().parent / "work-orders"
    if not orders.is_dir():
        return frozen
    for manifest in sorted(orders.glob("*/freeze.json")):
        try:
            data = json.loads(manifest.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        paths = data.get("frozen_paths", []) if isinstance(data, dict) else data
        if not isinstance(paths, list):
            continue
        frozen.update(normalize_vault_rel(p) for p in paths
                      if isinstance(p, str))
    return frozen


