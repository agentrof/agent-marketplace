def payload_reconcile(root: Path, policy: dict,
                      payload_src: Path | None) -> int:
    """Heal present-but-stale payload files by rewriting ONLY the
    policy-asserted keys, preserving the consumer's tuned unasserted
    knobs. community-plugins.json and plugins/ are only-if-missing
    copies."""
    changed = 0
    obsidian = root / ".obsidian"
    if not obsidian.is_dir():
        return 0

    def load_json(path: Path):
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return None

    def dump(path: Path, data) -> None:
        path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")

    graph_path = obsidian / "graph.json"
    groups = policy.get("graph_color_groups")
    if graph_path.is_file() and isinstance(groups, list):
        data = load_json(graph_path)
        if isinstance(data, dict):
            new = dict(data)
            dirty = False
            queries = [str(g.get("query", ""))
                       for g in data.get("colorGroups", [])
                       if isinstance(g, dict)]
            if queries != groups:
                old_colors = {str(g.get("query", "")): g.get("color")
                              for g in data.get("colorGroups", [])
                              if isinstance(g, dict)}
                new["colorGroups"] = [
                    {"query": q,
                     "color": old_colors.get(q) or group_color(policy, i)}
                    for i, q in enumerate(groups)]
                dirty = True
            if new.get("search", "") != policy.get("graph_search", ""):
                new["search"] = policy.get("graph_search", "")
                dirty = True
            if dirty:
                dump(graph_path, new)
                changed += 1
    types_path = obsidian / "types.json"
    if types_path.is_file():
        data = load_json(types_path)
        if isinstance(data, dict):
            types = dict(data.get("types") or {})
            dirty = False
            for key, value in policy.get("property_types", {}).items():
                if types.get(key) != value:
                    types[key] = value
                    dirty = True
            if dirty:
                new = dict(data)
                new["types"] = types
                dump(types_path, new)
                changed += 1
    app_path = obsidian / "app.json"
    if app_path.is_file():
        data = load_json(app_path)
        if isinstance(data, dict):
            sentinels = dict(APP_SENTINELS)
            sentinels["attachmentFolderPath"] = policy.get(
                "attachments_dir", "_attachments")
            new = dict(data)
            dirty = False
            for key, value in sentinels.items():
                if new.get(key) != value:
                    new[key] = value
                    dirty = True
            if dirty:
                dump(app_path, new)
                changed += 1
    community = policy.get("community_plugins", [])
    if community:
        cp_path = obsidian / "community-plugins.json"
        if not cp_path.is_file():
            dump(cp_path, list(community))
            changed += 1
        for plugin_id in community:
            plugin_dir = obsidian / "plugins" / plugin_id
            src = (payload_src / "plugins" / plugin_id
                   if payload_src is not None else None)
            if not plugin_dir.is_dir() and src is not None and src.is_dir():
                shutil.copytree(src, plugin_dir)
                changed += 1
    return changed


def retired_reconcile(root: Path, policy: dict, skip: set) -> int:
    """Delete the retired scaffold notes and strip home's links to them.
    Deterministic and IDEMPOTENT, and (payload_reconcile pattern) runs
    regardless of --scope inside cmd_migrate: a scoped gate on an older
    tree must never deadlock on root files it cannot repair."""
    maps_dir = policy["maps_dir"]
    retired = ["backlog.md", "quality-ledger.md", "start-here.md",
               f"{maps_dir}/delivery.md"]
    removed = 0
    for rel in retired:
        if rel in skip:
            continue
        path = root / rel
        if path.is_file():
            path.unlink()
            removed += 1
            print(f"vault_check: deleted retired file {rel}")
    home_rel = policy["home_file"]
    home = root / home_rel
    if home.is_file() and home_rel not in skip:
        stems = {r[:-3] for r in retired}
        text = home.read_text(encoding="utf-8")
        out = []
        dirty = False
        for line in text.splitlines():
            targets = [split_wikilink(m.group("inner"))[0]
                       for m in WIKILINK_RE.finditer(line)]
            if targets and all(t in stems for t in targets):
                dirty = True
                continue
            out.append(line)
        if dirty:
            home.write_text("\n".join(out)
                            + ("\n" if text.endswith("\n") else ""),
                            encoding="utf-8")
            removed += 1
            print(f"vault_check: stripped retired links from {home_rel}")
    return removed


def cmd_migrate(args, policy: dict) -> int:
    root = args.vault.resolve()
    vault = build_vault(root, policy)
    frozen = set() if args.override_freeze else freeze_skip_set(args.vault)
    skip = frozen | {normalize_vault_rel(x) for x in (args.exclude or [])}
    if args.rename:
        return migrate_rename(args, policy, vault, skip)
    try:
        schema = ba_compile.load_schema(ba_compile.DEFAULT_SCHEMA)
    except (OSError, json.JSONDecodeError, SystemExit):
        schema = None
    citation_columns = (list(schema.get("id_citation_columns", []))
                        if schema else [])
    id_lookup = ba_id_lookup(vault) if citation_columns else {}
    total_rewrites = 0
    total_manual = 0
    touched = 0
    for note in authored(vault):
        if note.rel in skip:
            continue
        if args.scope and not (note.rel.startswith(args.scope.rstrip("/") + "/")
                               or note.subtree == ""):
            continue
        text, rewrites, manual = migrate_note(vault, note, citation_columns,
                                              id_lookup)
        trailing = text.endswith("\n")
        lines = text.splitlines()
        rewrites += deid_lead_decision(policy, note, lines)
        rewrites += append_designation(vault, note, lines)
        rewrites += retarget_nav(vault, note, lines)
        text = "\n".join(lines) + ("\n" if trailing else "")
        tags, tags_changed = migrate_tags(note)
        if tags_changed:
            text = apply_tags(text, tags)
            rewrites += 1
        total_manual += manual
        if rewrites:
            note.path.write_text(text, encoding="utf-8")
            touched += 1
            total_rewrites += rewrites
            print(f"vault_check: migrated {note.rel} ({rewrites} rewrites)")
    retired = retired_reconcile(root, policy, skip)
    reconciled = payload_reconcile(root, policy, args.payload)
    print(f"vault_check: migrate touched {touched} notes,"
          f" {total_rewrites} rewrites;"
          f" {retired} retired surface(s) cleared;"
          f" {reconciled} payload file(s) reconciled;"
          f" {total_manual} link(s) left for stewardship")
    return 0


# Review-round filenames the inverted --rename migrates FROM: the v6 plain
# forms (round-N.md, space-round-N.md) and the v4/v5 chain-prefixed forms
# both map to the -review target. The chain prefix is OPTIONAL; the \.md
# anchor sits right after the digits, so an already-suffixed round-N-review
# name never matches (a second run is a no-op). The two are applied per node
# (space-round at the root, round at a domain), so a domain-round pattern
# can never claim a space-round name. V5_DEC_RE strips id-prefixed decisions.
ROUND_RE = re.compile(r"^(?:[a-z0-9]+(?:-[a-z0-9]+)*-)?round-(\d+)\.md$")
SPACE_ROUND_RE = re.compile(
    r"^(?:[a-z0-9]+(?:-[a-z0-9]+)*-)?space-round-(\d+)\.md$")
V5_DEC_RE = re.compile(
    r"^dec-[a-z][a-z0-9]{1,3}-\d{3,}-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")


def build_rename_map(vault: Vault, policy: dict,
                     schema: dict) -> tuple[dict, list]:
    """Inverted (v6) rename plan: v5 chain-qualified named files, chain
    round files, id-prefixed decision notes and bare typed-content files
    become plain, type-suffixed names. Forward-only: compliant names are
    skipped; the decision skip gate is the filename-suffix test, NEVER
    the record id (both generations carry the id alias)."""
    renames: dict[str, str] = {}
    manual: list[str] = []
    ch_folder = schema["doc_types"]["challenge_record"]["location"]["folder"]
    plain_space = ba_compile.space_overview_rel(schema)
    roots = set()
    for rel in vault.index:
        parts = rel.split("/")
        if len(parts) < 2 or not rel.endswith(".md"):
            continue
        if parts[-1] == plain_space \
                or parts[-1] == f"{parts[-2]}-{plain_space}":
            roots.add("/".join(parts[:-1]))
    for root_rel in sorted(roots):
        for rel in sorted(vault.index):
            if not rel.startswith(root_rel + "/") or not rel.endswith(".md"):
                continue
            sub = rel[len(root_rel) + 1:]
            rest = sub.split("/")
            node_parts: list[str] = []
            while len(rest) > 2 and rest[0] == "domains":
                node_parts.extend(rest[:2])
                rest = rest[2:]
            node_rel = "/".join(node_parts)
            node_prefix = f"{root_rel}/{node_rel}/" if node_rel \
                else f"{root_rel}/"
            if len(rest) == 1:
                name = rest[0]
                for doc_type, spec in schema["doc_types"].items():
                    loc = spec["location"]
                    if loc.get("kind") != "named_file":
                        continue
                    plain = loc["name"]
                    if name == plain:
                        break  # already v6
                    if not name.endswith(f"-{plain}"):
                        continue
                    if loc.get("root_only") and node_rel:
                        continue
                    if loc.get("domain_only") and not node_rel:
                        continue
                    renames[rel] = f"{node_prefix}{plain}"
                    break
            elif len(rest) == 2 and rest[0] == ch_folder:
                # Node-scoped inverses: the root applies only the space-round
                # inverse and a domain only the round inverse, so a domain
                # never claims a space-round name; the -review target is
                # schema-driven and already-suffixed names never re-match.
                name = rest[1]
                if node_rel:
                    m = None if SPACE_ROUND_RE.match(name) else ROUND_RE.match(name)
                    new_name = (ba_compile.round_file_name(
                        schema, "domain", int(m.group(1))) if m else None)
                else:
                    m = SPACE_ROUND_RE.match(name)
                    new_name = (ba_compile.round_file_name(
                        schema, "space", int(m.group(1))) if m else None)
                if new_name and new_name != name:
                    renames[rel] = f"{node_prefix}{ch_folder}/{new_name}"
            elif len(rest) == 2:
                folder, name = rest
                for doc_type, spec in schema["doc_types"].items():
                    loc = spec["location"]
                    if loc.get("kind") != "folder" \
                            or loc["folder"] != folder:
                        continue
                    suffix = loc.get("filename_suffix")
                    if not suffix:
                        break
                    stem = name[:-3]
                    if stem.endswith(f"-{suffix}"):
                        break  # already v6 (the suffix gate, never the id)
                    if doc_type == "decision":
                        m = V5_DEC_RE.match(name)
                        if m:
                            stem = m.group(1)
                    renames[rel] = f"{node_prefix}{folder}/{stem}-{suffix}.md"
                    break
    for tree in policy.get("decision_trees", {}).values():
        # Flat (non-glob) alias-id trees: v5 prefix-number-slug names
        # lose the id prefix and gain the type suffix.
        if tree_is_glob(tree) or tree.get("id_source", "alias") != "alias":
            continue
        prefix = tree["path"].rstrip("/") + "/"
        v5_re = re.compile(
            rf"^{tree['id_prefix'].lower()}-\d{{{tree['id_min_width']},}}"
            rf"-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$")
        for rel in sorted(vault.index):
            if not rel.startswith(prefix) or not rel.endswith(".md"):
                continue
            name = rel[len(prefix):]
            if "/" in name or name[:-3].endswith("-decision"):
                continue
            m = v5_re.match(name)
            if m:
                renames[rel] = f"{prefix}{m.group(1)}-decision.md"
    return renames, manual


def rename_referrers(vault: Vault, old_rel: str) -> list:
    """Authored notes citing old_rel; generated views re-render instead."""
    return sorted(r for r in vault.inbound.get(old_rel, set())
                  if r in vault.notes and not vault.notes[r].generated
                  and r != old_rel)


def migrate_rename(args, policy: dict, vault: Vault, skip: set) -> int:
    try:
        schema = ba_compile.load_schema(ba_compile.DEFAULT_SCHEMA)
    except (OSError, json.JSONDecodeError, SystemExit) as exc:
        print(f"vault_check: --rename needs the analysis schema: {exc}",
              file=sys.stderr)
        return 2
    renames, manual = build_rename_map(vault, policy, schema)
    if args.scope:
        prefix = args.scope.rstrip("/") + "/"
        renames = {o: n for o, n in renames.items() if o.startswith(prefix)}
        manual = [m for m in manual if m.startswith(prefix)]
    # Ambiguous targets route to the manual list and the run PROCEEDS:
    # two sources minting one target, or a target already on disk, are
    # judgment calls (never append a code or number to disambiguate;
    # that would reintroduce ids into filenames).
    collisions = []
    by_new: dict[str, list[str]] = {}
    for old, new in sorted(renames.items()):
        by_new.setdefault(new, []).append(old)
    for new, olds in sorted(by_new.items()):
        exists = new in vault.index and new not in renames
        if len(olds) > 1 or exists:
            for old in olds:
                renames.pop(old)
                manual.append(old)
                collisions.append(
                    f"{old} -> {new}: "
                    + ("target already exists" if exists
                       else "also produced by "
                       + ", ".join(o for o in olds if o != old)))
    blocked = []
    for old in sorted(renames):
        blockers = sorted(
            ({old} if old in skip else set())
            | {r for r in rename_referrers(vault, old) if r in skip})
        if blockers:
            blocked.append({"old": old, "new": renames.pop(old),
                            "blocked_by": blockers})
    plan = [{"old": old, "new": renames[old],
             "referrers": len(rename_referrers(vault, old))}
            for old in sorted(renames)]
    if args.json:
        print(json.dumps({
            "renames": plan,
            "blocked": blocked,
            "blocked_paths": [b["old"] for b in blocked],
            "manual": sorted(manual),
            "collisions": collisions,
            "dry_run": bool(args.dry_run),
        }, indent=2, sort_keys=True))
    else:
        for entry in plan:
            print(f"vault_check: rename {entry['old']} -> {entry['new']}"
                  f" ({entry['referrers']} referrers)")
        for entry in blocked:
            print(f"vault_check: BLOCKED {entry['old']} -> {entry['new']}"
                  f" blocked_by_frozen_referrer:"
                  f" {', '.join(entry['blocked_by'])}")
        for rel in sorted(manual):
            print(f"vault_check: manual {rel} (ambiguous rename target;"
                  " resolve by hand)")
        for collision in collisions:
            print(f"vault_check: COLLISION -> manual {collision}",
                  file=sys.stderr)
    if args.dry_run or not plan:
        if not args.json:
            print(f"vault_check: rename plan: {len(plan)} rename(s),"
                  f" {len(blocked)} blocked, {len(manual)} manual"
                  + (" (dry run)" if args.dry_run else ""))
        return 0
    # Referrer rewrite across the WHOLE vault first (files still at their
    # old paths), then the renames; one operation, either scope.
    stem_map = {old[:-3]: renames[old][:-3] for old in renames}
    pattern = re.compile(
        r"\[\[(" + "|".join(re.escape(s) for s in sorted(stem_map)) + r")"
        r"(?=[#|\\\]])")
    for note in authored(vault):
        text = "\n".join(note.lines)
        trailing = note.path.read_text(encoding="utf-8").endswith("\n")
        new_text = pattern.sub(lambda m: f"[[{stem_map[m.group(1)]}", text)
        if new_text != text:
            note.path.write_text(new_text + ("\n" if trailing else ""),
                                 encoding="utf-8")
    for old in sorted(renames):
        (vault.root / old).rename(vault.root / renames[old])
        print(f"vault_check: renamed {old} -> {renames[old]}")
    print(f"vault_check: renamed {len(renames)} file(s); generated views"
          " must be re-rendered (render, render-decisions)")
    return 0


