#!/usr/bin/env python3
"""Vault checker for the team's workspace docs tree (the product vault).

The consuming project's workspace/docs/ is one vault: wikilinked notes,
typed frontmatter, map hubs and a committed app payload. Every rule the
obsidian-vault skill states is enforced here; a rule without a check is
not a rule. Variation points (subtrees, map notes, tag namespaces, id
grammars, peer range, generated surfaces, property types) come from the
skill's data/vault-policy.json, never from constants.

Verbs:
  check            validate the vault (exit 0 clean/warnings, 1 errors)
  render-decisions render each decision tree's generated index
  stamp-decision   stamp a decision note's status (one clock, one write)
  migrate          apply the deterministic legacy-to-vault rewrites

Stdlib only. Findings sorted by (path, line, check). Wikilink resolution
runs against one posix-keyed file index, never the filesystem, so wrong
case or separators fail identically on every platform.
"""

