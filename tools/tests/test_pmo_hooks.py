        generated = docs / "generated.md"
        generated.parent.mkdir(parents=True, exist_ok=True)
        generated.write_text(
            "<!-- generated by vault_check render; do not edit by hand -->\n# View\n",
            encoding="utf-8")
        patch = "\n".join([
            "*** Begin Patch", f"*** Update File: {generated}", "@@",
            "-# View", "+# Changed", "*** End Patch",
        ])
        code, _, err = self.guard_patch(patch)
        self.assertEqual(code, 2)
        self.assertIn("GENERATED view", err)

        frozen_rel = "workspace/docs/business-analysis/core.md"
        frozen = self.project_root / frozen_rel
        frozen.parent.mkdir(parents=True)
        frozen.write_text("# Core\n", encoding="utf-8")
