FLOW_LIST_RE = re.compile(r"^\[.*\]$")


@dataclass(frozen=True)
class Finding:
    severity: str  # "error" | "warning"
    path: str
    line: int
    check: str
    message: str
    remediation: str


@dataclass
class Note:
    rel: str
    path: Path
    fm: dict
    fm_end: int
    fm_error: str | None
    lines: list[str]
    generated: bool
    subtree: str  # first path segment, "" for root-level notes
    wikilinks: list = field(default_factory=list)  # (line, embed, target, anchor, alias, raw_inner)
    mdlinks: list = field(default_factory=list)    # (line, text, target)
    fm_targets: list = field(default_factory=list)  # (key, target) wikilink values
    headings: list = field(default_factory=list)   # (line, text)
    block_ids: set = field(default_factory=set)


@dataclass
class Vault:
    root: Path
    policy: dict
    index: set = field(default_factory=set)   # every file, posix rel
    notes: dict = field(default_factory=dict)  # rel -> Note
    inbound: dict = field(default_factory=dict)  # rel -> set of citing rels


