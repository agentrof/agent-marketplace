class EffortPolicyCheckTests(unittest.TestCase):
    """The effort_policy validator check reads each host's effort-policy.json."""

    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        fixtures.make_valid_root(self.root, build=False)

    def tearDown(self) -> None:
        self.temporary.cleanup()

    def messages(self) -> list[str]:
        found: list = []
        validate.CHECKS["effort_policy"](validate.build_tree(self.root), found)
        return [finding.message for finding in found]

    def edit(self, host: str, mutate) -> None:
        path = self.root / "platforms" / host / "effort-policy.json"
        value = load(path)
        mutate(value)
        path.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")

    def test_policy_shape_and_vocabulary_errors_are_rejected(self):
        evidence = load(self.root / "platforms/codex/effort-policy.json")["confirm"]["max"]
        cases = (
            ("codex", lambda value: value["refuse"].update(extreme=value["refuse"]["ultra"]),
             "refuse names 'extreme'"),
            ("claude", lambda value: value["refuse"].update(max=dict(value["confirm"]["max"])),
             "both confirms and refuses 'max'"),
            ("claude", lambda value: value["confirm"]["max"].update(evidence=" "),
             "confirm.max: evidence must be"),
            ("claude", lambda value: value["confirm"]["max"].update(sources=["http://a"]),
             "confirm.max: sources must"),
            ("claude", lambda value: value["confirm"]["max"].update(verified="2026-13-01"),
             "confirm.max: verified must"),
            ("codex", lambda value: value["refuse"]["ultra"].pop("reason"),
             "refuse.ultra must hold exactly"),
            ("codex", lambda value: value.update(extra={}), "policy must hold exactly"),
            ("codex", lambda value: value["confirm"].update(ultra=dict(evidence)),
             "both confirms and refuses 'ultra'"),
        )
        original = {host: (self.root / "platforms" / host / "effort-policy.json").read_bytes()
                    for host in ("claude", "codex")}
        for host, mutate, fragment in cases:
            with self.subTest(fragment=fragment):
                for name, data in original.items():
                    (self.root / "platforms" / name / "effort-policy.json").write_bytes(data)
                self.edit(host, mutate)
                messages = self.messages()
                self.assertTrue(any(fragment in message for message in messages), messages)

    def test_a_package_pin_at_a_refused_effort_is_rejected(self):
        path = build_distributions.execution_profile_path(self.root, "codex")
        table = load(path)
        table["profiles"]["auto"][HIGH]["effort"] = "ultra"
        path.write_text(json.dumps(table, indent=2) + "\n", encoding="utf-8")
        self.assertTrue(any(f"pins the {HIGH} class at 'ultra'" in message
                            for message in self.messages()), self.messages())

    def test_a_missing_policy_is_a_finding(self):
        (self.root / "platforms" / "claude" / "effort-policy.json").unlink()
        self.assertTrue(any("missing or not valid JSON" in message
                            for message in self.messages()))


class ResolutionTests(unittest.TestCase):
    """`role_settings.resolve` applies role_classes, then class_models, over the package."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.market = Marketplace()
        cls.tiers = package_tiers(cls.market.map)

    @classmethod
    def tearDownClass(cls) -> None:
        cls.market.cleanup()

    def resolve(self, host: str, config: dict | None = None) -> dict:
        return role_settings.resolve(self.market.map, config or {}, host)

    def package_row(self, host: str, tier: str, *, moved: bool = False) -> dict:
        spec = self.market.tier(host, tier)
        return {"class": tier, "class_source": "config" if moved else "package",
                "model": spec.get("model", "session"), "model_source": "package",
                "effort": spec.get("effort"), "effort_source": "package"}

    def test_without_overrides_every_role_runs_the_package_settings(self):
        for host in build_distributions.HOSTS:
            rows = self.resolve(host)
            roles = package_tiers(self.market.map, host)
            self.assertEqual(set(rows), set(roles))
            for role, tier in roles.items():
                with self.subTest(host=host, role=role):
                    self.assertEqual(rows[role], self.package_row(host, tier))

    def test_role_classes_moves_each_role_on_its_own(self):
        self.assertEqual((self.tiers[MOVED], self.tiers[VARIANT]), (OWN, OWN))
        for host in build_distributions.HOSTS:
            rows = self.resolve(host, {"role_classes": {MOVED: MEDIUM}})
            with self.subTest(host=host):
                self.assertEqual(rows[MOVED], self.package_row(host, MEDIUM, moved=True))
                self.assertEqual(rows[VARIANT], self.package_row(host, OWN))
                self.assertEqual({role: row for role, row in rows.items() if role != MOVED},
                                 {role: row for role, row in self.resolve(host).items()
                                  if role != MOVED})
                # Another role moves by its own entry.
                rows = self.resolve(host, {"role_classes": {VARIANT: HIGH}})
                self.assertEqual(rows[VARIANT], self.package_row(host, HIGH, moved=True))
                self.assertEqual(rows[MOVED], self.package_row(host, OWN))
                # A role on its package class records nothing new.
                self.assertEqual(self.resolve(host, {"role_classes": {MOVED: OWN}}),
                                 self.resolve(host))

    def test_a_missing_class_models_key_keeps_the_package_value(self):
        market = self.market
        for host in build_distributions.HOSTS:
            other = market.other_model(host, MEDIUM)
            effort = market.non_default(host, MEDIUM, model=other)
            package = self.package_row(host, MEDIUM)
            for override, model, effort_value in (
                    ({"model": other}, other, package["effort"]),
                    ({"effort": effort}, package["model"], effort),
                    ({"model": other, "effort": effort}, other, effort),
                    ({"model": "session"}, "session", package["effort"])):
                with self.subTest(host=host, override=override):
                    config = {"class_models": {host: {MEDIUM: override}},
                              "role_classes": {MOVED: MEDIUM}}
                    self.assertEqual(role_settings.config_errors(config, market.map), [])
                    rows = self.resolve(host, config)
                    for role in [*market.roles_on(MEDIUM), MOVED]:
                        self.assertEqual(rows[role], {
                            "class": MEDIUM,
                            "class_source": "config" if role == MOVED else "package",
                            "model": model,
                            "model_source": "config" if "model" in override else "package",
                            "effort": effort_value,
                            "effort_source": "config" if "effort" in override else "package"})
                    # Another host's settings reach no role here.
                    other_host = next(name for name in build_distributions.HOSTS if name != host)
                    self.assertEqual(
                        self.resolve(other_host, {"class_models": config["class_models"]}),
                        self.resolve(other_host))

    def test_a_model_that_takes_no_effort_drops_the_package_effort(self):
        market = self.market
        hosts = [host for host in build_distributions.HOSTS
                 if any(not entry["efforts"] for entry in market.host(host)["models"].values())]
        self.assertTrue(hosts, "no host catalog holds a model that takes no effort")
        for host in hosts:
            model = market.other_model(host, MEDIUM, efforts=False)
            config = {"class_models": {host: {MEDIUM: {"model": model}}}}
            with self.subTest(host=host):
                self.assertEqual(role_settings.config_errors(config, market.map), [])
                row = self.resolve(host, config)[market.roles_on(MEDIUM)[0]]
                self.assertEqual((row["model"], row["effort"]), (model, None))

    def test_a_package_effort_the_chosen_model_does_not_take_must_be_set(self):
        # A catalog model that takes fewer efforts than the tier's package one.
        tier_map = copy.deepcopy(self.market.map)
        spec = tier_map["hosts"]["claude"]
        model = self.market.other_model("claude", HIGH)
        package = spec["classes"][HIGH]["effort"]
        spec["models"][model]["efforts"] = [effort for effort in spec["efforts"]
                                            if effort != package]
        config = {"class_models": {"claude": {HIGH: {"model": model}}}}
        errors = role_settings.config_errors(config, tier_map)
        self.assertEqual(len(errors), 1, errors)
        self.assertIn(f"class_models.claude.{HIGH}: {model} does not take the package effort"
                      f" {package!r}", errors[0])
        self.assertTrue(errors[0].endswith(REMEDY))
        chosen = spec["models"][model]["efforts"][0]
        config["class_models"]["claude"][HIGH]["effort"] = chosen
        self.assertEqual(role_settings.config_errors(config, tier_map), [])

    def test_a_shape_valid_model_outside_the_catalog_takes_the_host_vocabulary(self):
        for host, model in UNLISTED.items():
            spec = self.market.host(host)
            self.assertNotIn(model, spec["models"])
            for effort in self.market.efforts(host, model):
                config = {"class_models": {host: {HIGH: {"model": model, "effort": effort}}}}
                with self.subTest(host=host, effort=effort):
                    self.assertEqual(role_settings.config_errors(config, self.market.map), [])
                    role = self.market.roles_on(HIGH)[0]
                    self.assertEqual(self.resolve(host, config)[role]["model"], model)

    def test_the_table_lists_role_tier_model_effort_and_source(self):
        host = "claude"
        config = {"class_models": {host: {MEDIUM: {"model": "session"}}},
                  "role_classes": {MOVED: MEDIUM}}
        rows = self.resolve(host, config)
        lines = role_settings.table(rows)
        self.assertEqual(lines[0].split(), ["role", "class", "model", "effort", "source"])
        self.assertEqual(len(lines), len(rows) + 1)
        by_role = {line.split()[0]: line.split() for line in lines[1:]}
        effort = rows[MOVED]["effort"]
        self.assertEqual(by_role[MOVED], [MOVED, MEDIUM, "session", effort, "config:", "class,",
                                          "model"])
        self.assertEqual(by_role[VARIANT][-1], "package")
        self.assertEqual(role_settings.source_text(rows[VARIANT]), "package")


