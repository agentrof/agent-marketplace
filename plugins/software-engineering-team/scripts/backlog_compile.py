def check(args) -> int:
    docs = docs_root(args.docs)
    try:
        # Collecting manual bindings resolves a recursive upstream graph. Keep
        # that read-only graph snapshot stable for this one verification pass.
        with stage_package.candidate_session(), experience_validation_session():
            record, errors = collect(docs)
    except RuntimeError as exc:
        record = {"epics": [], "stories": [], "test_plans": [],
                  "backlog_reviews": [], "epic_reviews": [], "backlog": None}
        errors = [str(exc)]
    # A review round the Product Owner wrote records the Process Policy in
    # force the first time the compiler sees it.
    pinned_reviews = (pin_first_seen_reviews(docs, record)
                      if record["backlog"] and getattr(args, "pin_reviews", True) else [])
    if args.approved and record["backlog"]:
        errors.extend(approval_findings(record, docs))
    if getattr(args, "pre_approval", False) and record["backlog"]:
        # The offer to the owner runs approval's own checks, on the reviews as
        # approval will read them, so a refusal surfaces before the owner gate.
        current, collect_errors = record, list(errors)
        if pinned_reviews:
            try:
                with stage_package.candidate_session(), experience_validation_session():
                    current, collect_errors = collect(docs)
            except RuntimeError as exc:
                collect_errors = [str(exc)]
        errors.extend(approval_preflight(docs, current, collect_errors)[0])
    # A story over budget is advisory: the block adds no error of its own.
    # Only the Size Exceptions a review records are checked, and only while
    # the budget is on; at the default nothing is read.
    story_size = None
    try:
        budget = story_size_budget(docs)
        if budget is not None:
            story_size = story_size_report(record, docs, budget)
            errors.extend(size_exception_findings(record, docs))
    except (ValueError, RuntimeError) as exc:
        errors.append(str(exc))
    # A scenario over the serial-row limit is advisory too; at the default nothing is read.
    test_cost = None
    try:
        cost = test_cost_budget(docs)
        if cost is not None:
            test_cost = test_cost_block(cost, record["stories"])
    except (ValueError, RuntimeError) as exc:
        errors.append(str(exc))
    errors = sorted(set(errors))
    result = {
        "ok": not errors, "errors": errors,
        "counts": {"epics": len(record["epics"]),
                   "stories": len(record["stories"]),
                   "test_plans": len(record["test_plans"]),
                   "backlog_reviews": len(record["backlog_reviews"]),
                   "epic_reviews": len(record["epic_reviews"])},
    }
    if story_size is not None:
        result["story_size"] = story_size
    if test_cost is not None:
        result["test_cost"] = test_cost
    if pinned_reviews:
        result["pinned_reviews"] = pinned_reviews
    # Only a backlog that has one gains the key, so every other output is unchanged.
    advisories = record.get("advisory_findings", [])
    if advisories:
        result["advisories"] = advisories
    if args.render and not errors:
        try:
            render(record, docs)
            render_backlog_navigation(record, docs)
            result["rendered"] = True
            if args.approved:
                with stage_package.candidate_session(), experience_validation_session():
                    record, closing_errors = collect(docs)
                closing_errors.extend(approval_findings(record, docs))
                errors.extend(closing_errors)
        except RuntimeError as exc:
            errors.append(f"render failed: {exc}")
        errors = sorted(set(errors))
        result["ok"] = not errors
        result["errors"] = errors
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False, sort_keys=True))
    else:
        for error in errors:
            print(f"ERROR [backlog] {error}")
        for advisory in advisories:
            print(f"ADVISORY [backlog] {advisory}")
        if not errors:
            print("backlog ok")
    return 1 if errors else 0


def snapshot_tree(root: Path) -> tuple[dict[Path, bytes], set[Path]]:
    files = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
    dirs = {path for path in root.rglob("*") if path.is_dir()}
    dirs.add(root)
    return files, dirs


def restore_tree(root: Path, snapshot: tuple[dict[Path, bytes], set[Path]]) -> None:
    files, directories = snapshot
    for path in sorted((item for item in root.rglob("*") if item.is_file()),
                       reverse=True):
        if path not in files:
            path.unlink()
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for path in sorted((item for item in root.rglob("*") if item.is_dir()),
                       key=lambda item: len(item.parts), reverse=True):
        if path not in directories:
            try:
                path.rmdir()
            except OSError:
                pass


# The flow whose switches set how a backlog review runs.
BACKLOG_FLOW = "backlog-planning"


def policy_pin(docs: Path) -> tuple[dict, list[str]]:
    """Return the Process Policy pin a review round and an approval record,
    the one a Delivery takes.

    Outside a Delivery nothing else records the switch values a backlog
    revision and its reviews ran under. No policy means no pin; a draft or
    invalid policy is refused, never recorded.
    """
    import process_policy

    return process_policy.approved_snapshot(docs)


def round_pin(docs: Path) -> dict:
    """Return the pin a review round records as it is written, or none.

    A round written while the policy is a draft or invalid records nothing;
    no review can run until the policy is approved, and the first check
    after that pins the round. Without a policy a round records nothing
    either, so the default path writes the bytes it wrote before; the
    policy's init records revision 0 in it should a policy follow.
    """
    pin, errors = policy_pin(docs)
    return {} if errors else pin


def no_policy_pin() -> dict:
    """Return the pin of a round written before the project had a Process Policy.

    Its review ran with every switch at its default. Revision 0 precedes the
    policy's first revision, so no approved revision ever records it.
    """
    import process_policy

    return {"process_policy_path": process_policy.RELATIVE, "process_policy_revision": 0}


def recorded_pin(props: dict) -> dict:
    import process_policy

    return {key: props[key] for key in process_policy.PIN_FIELDS if key in props}


def pin_label(pin: dict) -> str:
    if not pin or pin == no_policy_pin():
        return "no Process Policy"
    return f"Process Policy revision {pin.get('process_policy_revision')}"


def draft_review_rounds(record: dict) -> list[dict]:
    """Return every review round that no approval has stamped."""
    return [review for review in (*record["backlog_reviews"], *record["epic_reviews"])
            if not (review["props"].get("approved_at_utc") or review["props"].get("source_hash"))]


class RoundChanged(RuntimeError):
    """Raised when a review round changes while the compiler pins it."""


def record_round_pins(docs: Path, paths: list[str], pin: dict) -> list[str]:
    """Write ``pin`` into each draft review round of ``paths`` that records no policy yet.

    A pinned or approved round is never touched, and a round that changes
    while it is pinned is left as it is.
    """
    import atomic_file

    pinned = []
    for relative in paths:
        path = docs / relative
        original = path.read_bytes()
        props, body = parse_front_matter_text(original.decode("utf-8"))
        if recorded_pin(props) or props.get("approved_at_utc") or props.get("source_hash"):
            continue

        def unchanged(path: Path = path, original: bytes = original) -> None:
            if path.read_bytes() != original:
                raise RoundChanged(path)

        try:
            atomic_file.replace_bytes(
                path, front_matter({**props, **pin}, body).encode("utf-8"), unchanged)
        except RoundChanged:
            continue
        pinned.append(relative)
    return pinned


def pin_first_seen_reviews(docs: Path, record: dict) -> list[str]:
    """Pin each draft review round that records no Process Policy yet.

    A round records the policy in force when it is written: init, stub-epic
    and begin-revision write theirs with it, and a round the Product Owner
    writes is pinned here, the first time the compiler sees it. A pinned or
    approved round is never touched, and without an approved policy nothing
    is written. A round that changes while it is pinned is left for the next
    check.
    """
    pin = round_pin(docs)
    if not pin:
        return []
    drafts = [review for review in draft_review_rounds(record)
              if not recorded_pin(review["props"])]
    pinned = record_round_pins(docs, [review["path"] for review in drafts], pin)
    for review in drafts:
        if review["path"] in pinned:
            review["props"].update(pin)
    return pinned


def pin_rounds_before_policy_change(docs: Path) -> list[str]:
    """Record the policy in force in each draft review round that records none yet.

    ``process_policy.py`` calls this as init and begin-revision start, the
    only steps that change the policy in force, so a round that no check has
    pinned keeps the state its review ran under: revision 0 before the
    project's first policy, the approved revision before its successor. A
    draft or invalid policy lets no review run and records nothing. A round
    still without a pin afterwards was written under the policy approved
    next, which check or the approval records in it.
    """
    pin, errors = policy_pin(docs)
    if errors:
        return []
    root = docs / "backlog"
    rounds = []
    for path in (*sorted((root / "reviews").glob("round-*-backlog-review.md")),
                 *sorted((root / "epics").glob("*/reviews/round-*-epic-review.md"))):
        try:
            kind = parse_front_matter(path)[0].get("type")
        except (OSError, UnicodeDecodeError):
            continue
        if kind in {"backlog-review", "epic-review"}:
            rounds.append(path.relative_to(docs).as_posix())
    return record_round_pins(docs, rounds, pin or no_policy_pin())


def review_pin_findings(record: dict, docs: Path, pin: dict,
                        preserved: dict[Path, bytes]) -> list[str]:
    """Refuse a review the approval stamps that ran under other backlog switch values.

    Every review the approval stamps must have run with the value, parameters
    included, that the approval's policy sets for each switch the
    backlog-planning flow owns. Its round's pin is the record: the values it
    names are read from the current policy or from the Git history of its
    path, as a Delivery's are, and compared, never the revision or hash that
    names them. So a revision that changes only other switches, a Delivery's
    among them, leaves the review valid, and a round written before the
    project's first policy agrees with a policy that keeps those switches at
    their defaults. A pinned revision that cannot be read back is refused as
    unverifiable. A round that records no policy is pinned by this approval,
    the first compiler step to see it under one. A review approved in an
    earlier revision keeps its own pin and is not compared.
    """
    import process_policy

    registry = process_policy.load_registry()
    switches = sorted(switch for switch, entry in registry.items()
                      if BACKLOG_FLOW in (entry["spec"].get("flows") or []))
    values = process_policy.effective_values(docs)[0]
    findings = []
    reviews = [latest(record["backlog_reviews"])] + [latest(epic["reviews"])
                                                      for epic in record["epics"]]
    for review in reviews:
        if review is None or docs / review["path"] in preserved:
            continue
        recorded = recorded_pin(review["props"])
        if not recorded or recorded == pin:
            continue
        try:
            ran = process_policy.pinned_values(
                docs, {} if recorded == no_policy_pin() else recorded, registry)[0]
        except ValueError as exc:
            findings.append(
                f"{review['path']} records {pin_label(recorded)}, whose switch values this"
                f" approval cannot read back to compare: {exc}; or write a new review round and"
                " rerun its review under the current Process Policy")
            continue
        changed = [switch for switch in switches
                   if (ran[switch]["value"], ran[switch].get("parameters"))
                   != (values[switch]["value"], values[switch].get("parameters"))]
        if changed:
            findings.append(
                f"{review['path']} records {pin_label(recorded)}, but the approval runs under"
                f" {pin_label(pin)}; write a new review round and rerun its review under the"
                " current Process Policy, or approve a Process Policy revision that sets back"
                " the values it ran under: " + "; ".join(
                    f"switch {switch} ran at {process_policy.described(ran[switch])} and the"
                    f" approval's policy sets {process_policy.described(values[switch])}"
                    for switch in changed))
    return findings


def without_policy_pin(props: dict) -> dict:
    import process_policy

    return {key: value for key, value in props.items() if key not in process_policy.PIN_FIELDS}


def with_policy_pin(props: dict, pin: dict) -> dict:
    """Return approval front matter that records ``pin`` after approved_at_utc.

    An earlier pin is dropped first, so an empty pin leaves the bytes the
    note had before approvals recorded a pin.
    """
    result = {}
    for key, value in without_policy_pin(props).items():
        result[key] = value
        if key == "approved_at_utc":
            result.update(pin)
    return result


def approval_preflight(docs: Path, record: dict,
                       collect_errors: list[str]) -> tuple[list[str], dict, dict, bool]:
    """Run every check atomic approval runs before it writes.

    Returns the findings beyond the collect errors, the preserved approved
    sources, the policy pin and whether the backlog is already approved.
    """
    findings = approval_readiness_findings(record)
    already_approved = (record.get("backlog") or {}).get("props", {}).get("status") == "approved"
    if not already_approved:
        findings.extend(requirement_coverage_findings(record))
    preserved, pin = {}, {}
    if not collect_errors and not findings:
        if already_approved:
            findings.extend(approval_findings(record, docs))
            _preserved, preserve_errors = preserved_approval_sources(
                record, docs, allow_new_approvals=True,
            )
            findings.extend(preserve_errors)
        else:
            preserved, preserve_errors = preserved_approval_sources(record, docs)
            findings.extend(preserve_errors)
            pin, pin_errors = policy_pin(docs)
            findings.extend(pin_errors)
            if not pin_errors:
                findings.extend(review_pin_findings(record, docs, pin, preserved))
                findings.extend(size_exception_approval_findings(record, docs))
    return findings, preserved, pin, already_approved


def approve(args) -> int:
    docs = docs_root(args.docs)
    # Experience receipt validation is expensive but immutable during this
    # preflight. Reuse both candidate and Experience compiler results here;
    # each later post-write read opens a fresh session so it cannot reuse
    # stale receipt data after the approval transition mutates Markdown.
    with stage_package.candidate_session(), experience_validation_session():
        record, errors = collect(docs)
    findings, preserved, pin, already_approved = approval_preflight(docs, record, errors)
    errors = sorted(set(errors + findings))
    if errors:
        print(json.dumps({"ok": False, "errors": errors}, indent=2,
                         ensure_ascii=False, sort_keys=True))
        return 1
    if already_approved:
        print(json.dumps({
            "ok": True, "approved_at_utc": record["backlog"]["props"]["approved_at_utc"],
            "package_hash": record["backlog"]["props"]["package_hash"],
            "files": len(package_paths(record, docs)),
        }, indent=2, ensure_ascii=False, sort_keys=True))
        return 0
    snapshot = snapshot_tree(docs)
    now = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    try:
        reviews = [docs / latest(record["backlog_reviews"])["path"]]
        reviews += [docs / latest(epic["reviews"])["path"] for epic in record["epics"]]
        pinned = {docs / record["backlog"]["path"], *reviews}
        # A round no compiler step has seen under the policy is pinned now;
        # every other round keeps the pin it recorded when it was written.
        first_seen = {docs / review["path"] for review in draft_review_rounds(record)
                      if not recorded_pin(review["props"])} if pin else set()
        transition_paths = [docs / record["backlog"]["path"]]
        transition_paths += [docs / epic["path"] for epic in record["epics"]]
        transition_paths += reviews
        transition_paths += [docs / story["test_plan"]
                             for story in record["stories"]]
        for path in sorted(set(transition_paths)):
            if path in preserved:
                continue
            props, body = parse_front_matter(path)
            status_tag(props, "approved")
            props["approved_at_utc"] = now
            props.pop("source_hash", None)
            props.pop("package_hash", None)
            if path in pinned:
                # The root records the approval's pin. A review keeps the pin
                # of the policy it ran under, whose backlog switch values the
                # approval matched, and takes the approval's when it has none.
                own = recorded_pin(props) if path != docs / record["backlog"]["path"] else {}
                props = with_policy_pin(props, own or pin)
            path.write_bytes(front_matter(props, body).encode("utf-8"))

        with stage_package.candidate_session(), experience_validation_session():
            refreshed, close_errors = collect(docs)
        if close_errors:
            raise ApprovalFailure("; ".join(close_errors))
        render_backlog_navigation(refreshed, docs, preserved=set(preserved))

        with stage_package.candidate_session(), experience_validation_session():
            refreshed, close_errors = collect(docs)
        if close_errors:
            raise ApprovalFailure("; ".join(close_errors))
        paths = package_paths(refreshed, docs)
        for path in paths:
            if path in preserved:
                continue
            props, body = parse_front_matter(path)
            props["approved_at_utc"] = now
            props.pop("source_hash", None)
            props.pop("package_hash", None)
            if path in first_seen and path not in pinned:
                props = with_policy_pin(props, pin)
            path.write_bytes(front_matter(props, body).encode("utf-8"))
        for path in paths:
            if path in preserved:
                continue
            props, body = parse_front_matter(path)
            props["source_hash"] = digest(path)
            path.write_bytes(front_matter(props, body).encode("utf-8"))
        root_path = docs / refreshed["backlog"]["path"]
        props, body = parse_front_matter(root_path)
        props["package_hash"] = package_digest(docs, paths)
        root_path.write_bytes(front_matter(props, body).encode("utf-8"))

        with stage_package.candidate_session(), experience_validation_session():
            refreshed, close_errors = collect(docs)
        close_errors.extend(approval_findings(refreshed, docs))
        if close_errors:
            raise ApprovalFailure("; ".join(sorted(set(close_errors))))
        render(refreshed, docs)
        with stage_package.candidate_session(), experience_validation_session():
            final_record, close_errors = collect(docs)
        close_errors.extend(approval_findings(final_record, docs))
        if close_errors:
            raise ApprovalFailure("; ".join(sorted(set(close_errors))))
        if any(path.read_bytes() != original for path, original in preserved.items()):
            raise ApprovalFailure("an unchanged approved source was modified during approval")
    except Exception as exc:
        restore_tree(docs, snapshot)
        print(json.dumps({"ok": False,
                          "errors": [f"approval rolled back: {exc}"]},
                         indent=2, ensure_ascii=False, sort_keys=True))
        return 1
    print(json.dumps({
        "ok": True, "approved_at_utc": now,
        "package_hash": final_record["backlog"]["props"]["package_hash"],
        "files": len(package_paths(final_record, docs)),
    }, indent=2, ensure_ascii=False, sort_keys=True))
    return 0


def begin_revision(args) -> int:
    """Open one incremental backlog revision without touching frozen stories.

    Delivery-aware freeze inputs are supplied by the future coordinator as a
    JSON snapshot. This offline compiler only validates the interface shape and
    records the new root/review revision; it never invents live Git state.
    """
    docs = docs_root(args.docs)
    record, errors = collect(docs, historical_inputs=True, prior_universe=True)
    errors.extend(approval_findings(record, docs))
    if errors:
        print(json.dumps({"ok": False, "errors": sorted(set(errors))}, indent=2,
                         ensure_ascii=False, sort_keys=True))
        return 1
    snapshot = {}
    if args.delivery_snapshot:
        try:
            snapshot = json.loads(Path(args.delivery_snapshot).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            print(json.dumps({"ok": False, "errors": [f"invalid delivery snapshot: {exc}"]}, indent=2), file=sys.stderr)
            return 1
        if not isinstance(snapshot, dict):
            print(json.dumps({"ok": False, "errors": ["delivery snapshot must be an object"]}, indent=2), file=sys.stderr)
            return 1
        for key in ("active_story_ids", "delivered_story_ids", "cancelled_story_ids"):
            if key in snapshot and (not isinstance(snapshot[key], list)
                                    or any(not isinstance(value, str) for value in snapshot[key])):
                print(json.dumps({"ok": False, "errors": [f"{key} must be a list of story ids"]}, indent=2), file=sys.stderr)
                return 1
    backlog_path = docs / record["backlog"]["path"]
    root_props, root_body = parse_front_matter(backlog_path)
    absent = list(getattr(args, "absent_input", []) or [])
    if absent and args.planning_mode != "requirement":
        print("backlog_compile: --absent-input requires Requirement mode", file=sys.stderr)
        return 2
    if args.planning_mode == "manual" and (args.requirement_ref or len(args.input_ref) < 4):
        print(json.dumps({
            "ok": False,
            "errors": [
                "manual revision needs BA, Solution, Design, one application "
                "and its exact zero-or-more Experience process --input-ref "
                "values, with no Requirement"
            ],
        }, indent=2), file=sys.stderr)
        return 2
    if args.planning_mode == "requirement" and not args.requirement_ref:
        print(json.dumps({"ok": False, "errors": [
            "requirement revision needs --requirement-ref; --input-ref pins only the "
            "stages the Requirement marks not_applicable"
        ]}, indent=2), file=sys.stderr)
        return 2
    input_bindings: list[str] = []
    if args.planning_mode == "manual":
        with stage_package.candidate_session():
            input_bindings, binding_errors = resolve_manual_input_bindings(
                docs, list(args.input_ref), "backlog/backlog.md")
            if binding_errors:
                print(json.dumps({"ok": False, "errors": binding_errors},
                                 indent=2, ensure_ascii=False), file=sys.stderr)
                return 1
    if not stage_package.paths_are_committed(package_paths(record, docs)):
        print(json.dumps({"ok": False, "errors": [
            "approved backlog sources must be byte-exact in committed HEAD before beginning a revision"
        ]}, indent=2), file=sys.stderr)
        return 1
    if args.planning_mode == "requirement":
        # Untouched stages carry this backlog's previous bindings forward.
        input_bindings, binding_errors = requirement_input_bindings(
            docs, args.requirement_ref, values(root_props, "input_bindings"),
            list(args.input_ref), "backlog/backlog.md", absent_stages=absent)
        if not binding_errors:
            candidate_props = {
                "planning_mode": "requirement", "requirement_ref": args.requirement_ref,
                "input_bindings": input_bindings,
            }
            if absent:
                candidate_props.update(input_contract=backlog_contract()["applicable_inputs"]["contract"],
                                       absent_input_stages=absent)
            _mode, _refs, binding_errors = planning_package_findings(
                docs, candidate_props, "backlog/backlog.md")
        if binding_errors:
            print(json.dumps({"ok": False, "errors": sorted(set(binding_errors))},
                             indent=2, ensure_ascii=False), file=sys.stderr)
            return 1
    old_revision = int(root_props.get("revision", 0) or 0)
    revision = old_revision + 1
    status_tag(root_props, "draft")
    root_props["revision"] = revision
    root_props["planning_mode"] = args.planning_mode
    root_props.pop("requirement_ref", None)
    root_props.pop("input_package_refs", None)
    root_props.pop("input_bindings", None)
    root_props.pop("input_contract", None)
    root_props.pop("absent_input_stages", None)
    if absent:
        root_props["input_contract"] = backlog_contract()["applicable_inputs"]["contract"]
        root_props["absent_input_stages"] = absent
    if args.planning_mode == "requirement":
        root_props["requirement_ref"] = args.requirement_ref
    root_props["input_bindings"] = input_bindings
    for key in ("approved_at_utc", "source_hash", "package_hash"):
        root_props.pop(key, None)
    # The Process Policy pin belongs to the approval stamp it follows.
    root_props = without_policy_pin(root_props)

    latest_review = latest(record["backlog_reviews"])
    next_round = int(latest_review["props"].get("round", 0) or 0) + 1
    review_props = without_policy_pin(latest_review["props"])
    backlog_title = str(root_props.get("title", DEFAULT_BACKLOG_TITLE))
    review_title = f"Backlog review round {next_round} for {backlog_title}"
    review_props["title"] = review_title
    review_props["round"] = next_round
    review_props["status"] = "draft"
    review_props["aliases"] = [f"BACKLOG-REVIEW-{next_round:03d}"]
    for key in ("approved_at_utc", "source_hash", "verdict"):
        review_props.pop(key, None)
    review_props["tags"] = [
        tag for tag in values(review_props, "tags") if not tag.startswith("status/")
    ] + ["status/draft"]
    # The new round records the Process Policy in force as it is written.
    review_props.update(round_pin(docs))
    review_body_text = revision_review_body(latest_review, review_title, backlog_title, revision,
                                            backlog_review_sections(args.planning_mode))
    review_path = docs / "backlog" / "reviews" / f"round-{next_round}-backlog-review.md"
    # Navigation may touch every package note, home and the map. Snapshot only
    # those owned paths so rollback cannot erase unrelated concurrent work.
    touched = set(package_paths(record, docs)) | {
        review_path, docs / "home.md", docs / "maps" / "backlog.md",
    }
    try:
        originals = {path: path.read_bytes() if path.exists() else None
                     for path in touched}
        missing_dirs = {parent for path in touched for parent in path.parents
                        if parent != docs and docs in parent.parents and not parent.exists()}
    except OSError as exc:
        print(json.dumps({"ok": False, "errors": [f"revision snapshot failed: {exc}"]},
                         indent=2, ensure_ascii=False, sort_keys=True))
        return 1
    try:
        backlog_path.write_bytes(front_matter(root_props, root_body).encode("utf-8"))
        review_path.write_bytes(front_matter(review_props, review_body_text).encode("utf-8"))
        refreshed, render_errors = collect(docs, review_inputs=True, revision_inputs=True)
        render_errors.extend(review_coverage_findings(refreshed, docs))
        if render_errors:
            raise RuntimeError("; ".join(sorted(set(render_errors))))
        render_backlog_navigation(refreshed, docs)
    except (OSError, ValueError, RuntimeError) as exc:
        restore_errors = []
        for path, original in originals.items():
            try:
                if original is None:
                    if path.exists():
                        path.unlink()
                elif not path.is_file() or path.read_bytes() != original:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(original)
            except OSError as restore_exc:
                restore_errors.append(f"could not restore {path.relative_to(docs)}: {restore_exc}")
        for directory in sorted(missing_dirs, key=lambda path: len(path.parts), reverse=True):
            try:
                directory.rmdir()
            except OSError:
                pass
        label = "revision rollback incomplete" if restore_errors else "revision rolled back"
        print(json.dumps({"ok": False, "errors": [f"{label}: {exc}", *restore_errors]}, indent=2,
                         ensure_ascii=False, sort_keys=True))
        return 1
    result = {
        "ok": True, "revision": revision, "review_round": next_round,
        "frozen_story_ids": sorted(set(snapshot.get("active_story_ids", []))
                                    | set(snapshot.get("delivered_story_ids", []))),
        "cancelled_story_ids": sorted(set(snapshot.get("cancelled_story_ids", []))),
        "backlog": str(backlog_path), "review": str(review_path),
    }
    if refreshed.get("transition_findings"):
        result["transition_findings"] = refreshed["transition_findings"]
    print(json.dumps(result, indent=2, ensure_ascii=False, sort_keys=True))
    return 0


