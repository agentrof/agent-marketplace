def statement_of(space: Space, id_value: str) -> str:
    info = space.ids[id_value]
    row = info["row"]
    for column in ("statement", "criterion", "question", "ruling", "finding"):
        if column in row:
            return row[column]
    return ""


def id_sort_key(id_value: str):
    m = NAMESPACED_ID_RE.fullmatch(id_value)
    if m:
        return (m.group(1), m.group(2), int(m.group(3)))
    return ("ZZ", "ZZZZ", 0)


def node_rollup(space: Space, node_rel: str) -> str:
    ranks = []
    for rel in space.docs:
        if not doc_in_node(space, rel, node_rel):
            continue
        status = doc_status(space.docs[rel])
        if status == "superseded":
            continue
        ranks.append(STATUS_RANK.get(status, 0))
    if not ranks:
        return "draft"
    for name, rank in STATUS_RANK.items():
        if rank == min(ranks):
            return name
    return "draft"


def foundation_approved(space: Space) -> bool:
    return all(doc_status(space.docs[n]) == "approved"
               for n in root_file_rels(space.schema)
               if n in space.docs)


def node_buildable(space: Space, node_rel: str) -> bool:
    probe = run_gate_checks_collect(space, node_rel)
    return foundation_approved(space) and not probe


def run_gate_checks_collect(space: Space, node_rel: str) -> list[Finding]:
    collected: list[Finding] = []
    run_gate_checks(space, collected, node_rel)
    return [f for f in collected if f.severity == "error"]


def cited_by_map(space: Space) -> dict[str, list[str]]:
    cited: dict[str, list[str]] = {}
    for ac_id in sorted((i for i in space.ids
                         if space.ids[i]["kind"] == "AC"), key=id_sort_key):
        cites = space.ids[ac_id]["row"].get("cites", "")
        for m in NAMESPACED_ID_RE.finditer(cites):
            cited.setdefault(m.group(0), []).append(ac_id)
    return cited


def render_views(space: Space, warnings: list[Finding]) -> dict[str, str]:
    """Pure function of the authored tree (plus stable warnings): returns
    {relpath under _generated: content}."""
    docs_sorted = sorted(space.docs)
    cited = cited_by_map(space)
    vault_prefix = ""
    if space.vault_root is not None:
        try:
            vault_prefix = space.root.resolve().relative_to(
                space.vault_root.resolve()).as_posix() + "/"
        except ValueError:
            vault_prefix = ""
    space_rel = space_overview_rel(space.schema)
    title = str(space.docs.get(space_rel).fm.get("title", "")) \
        if space_rel in space.docs else ""
    stable = [w for w in warnings
              if w.severity == "warning" and w.check != "aging"]
    # The volume family (check id 'thresholds') is the advisory class:
    # split proposals, grouped in status.md, never listed as plain
    # warnings in the index.
    advisories = [w for w in stable if w.check == "thresholds"]
    stable_warnings = [w for w in stable if w.check != "thresholds"]

    lines = [GENERATED_MARKER, f"# Index: {title}", ""]
    lines.append(f"Foundation approved: {'yes' if foundation_approved(space) else 'no'}")
    lines.append(f"Space status: {node_rollup(space, '')}")
    lines += ["", "## Nodes", "",
              "| node | code | status | buildable | docs |",
              "|---|---|---|---|---|"]
    for node_rel in sorted(space.nodes):
        count = sum(1 for r in space.docs if space.docs[r].node == node_rel)
        lines.append(
            f"| {node_rel or '(root)'} | {space.nodes[node_rel]} |"
            f" {node_rollup(space, node_rel)} |"
            f" {'yes' if node_buildable(space, node_rel) else 'no'} | {count} |")
    lines += ["", "## Documents", "",
              "| doc | type | status | summary |",
              "|---|---|---|---|"]
    for rel in docs_sorted:
        doc = space.docs[rel]
        summary = ""
        for h_idx, level, _text in doc.headings:
            if level == 1:
                for i in range(h_idx + 1, len(doc.lines) + 1):
                    candidate = doc.lines[i - 1].strip()
                    if candidate.startswith("#"):
                        break
                    if candidate:
                        summary = candidate.replace("|", "\\|")
                        break
                break
        cell = (f"[[{vault_prefix}{rel[:-3]}\\|{rel}]]" if vault_prefix
                else f"[{rel}]({'../' + rel})")
        lines.append(f"| {cell} | {doc.doc_type} |"
                     f" {doc_status(doc)} | {summary} |")
    if stable_warnings:
        lines += ["", "## Warnings", ""]
        for w in sorted(stable_warnings, key=lambda f: (f.path, f.line, f.check)):
            lines.append(f"- {w.path}:{w.line} [{w.check}] {w.message}")
    index_md = "\n".join(lines) + "\n"

    lines = [GENERATED_MARKER, f"# Registry: {title}", "", "## Codes", "",
             "| code | node |", "|---|---|"]
    for node_rel in sorted(space.nodes, key=lambda n: (space.nodes[n], n)):
        if space.nodes[node_rel]:
            lines.append(f"| {space.nodes[node_rel]} | {node_rel or '(root)'} |")
    for kind, heading in (("BR", "Business Rules"), ("AC", "Acceptance Criteria"),
                          ("AS", "Assumptions"), ("DEC", "Decisions"),
                          ("CH", "Challenge Findings")):
        ids = sorted((i for i in space.ids if space.ids[i]["kind"] == kind),
                     key=id_sort_key)
        if not ids:
            continue
        lines += ["", f"## {heading}", ""]
        if kind == "BR":
            lines += ["| id | statement | status | doc | cited_by |", "|---|---|---|---|---|"]
            for i in ids:
                info = space.ids[i]
                lines.append(f"| {i} | {statement_of(space, i).replace('|', chr(92) + '|')} |"
                             f" {info['row'].get('status', '')} | {info['doc']} |"
                             f" {', '.join(cited.get(i, []))} |")
        else:
            lines += ["| id | statement | status | doc |", "|---|---|---|---|"]
            for i in ids:
                info = space.ids[i]
                status = info["row"].get("status", info["row"].get("severity", ""))
                lines.append(f"| {i} | {statement_of(space, i).replace('|', chr(92) + '|')} |"
                             f" {status} | {info['doc']} |")
    registry_md = "\n".join(lines) + "\n"

    registry = {"schema_version": space.schema["schema_version"],
                "codes": {space.nodes[n]: (n or "(root)")
                          for n in space.nodes if space.nodes[n]},
                "ids": {}}
    for i in sorted(space.ids, key=id_sort_key):
        info = space.ids[i]
        statement = statement_of(space, i)
        registry["ids"][i] = {
            "kind": info["kind"],
            "doc": info["doc"],
            "row_status": info["row"].get("status",
                                          info["row"].get("severity", "")),
            "doc_status": doc_status(space.docs[info["doc"]]),
            "statement": statement,
            "statement_sha256": hashlib.sha256(statement.encode("utf-8")).hexdigest(),
            "cited_by": cited.get(i, []),
        }
    registry_json = json.dumps(registry, indent=2, sort_keys=True) + "\n"

    inbound: dict[str, list[str]] = {}
    for rel in docs_sorted:
        doc = space.docs[rel]
        edges = []
        for _lineno, _text, target in doc.links:
            clean = target.split("#", 1)[0]
            if not clean or target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            edges.append((doc.abs_path.parent / clean).resolve())
        for _lineno, _embed, target, _anchor, _alias in doc.wikilinks:
            if target and space.vault_root is not None:
                edges.append((space.vault_root / (target + ".md")).resolve())
        for resolved in edges:
            try:
                target_rel = resolved.relative_to(space.root.resolve()).as_posix()
            except ValueError:
                continue
            if target_rel in space.docs and target_rel != rel:
                inbound.setdefault(target_rel, [])
                if rel not in inbound[target_rel]:
                    inbound[target_rel].append(rel)
    lines = [GENERATED_MARKER, f"# Backlinks: {title}", ""]
    for rel in docs_sorted:
        sources = sorted(inbound.get(rel, []))
        if not sources:
            continue
        lines.append(f"## {rel}")
        lines += [f"- {s}" for s in sources]
        lines.append("")
    backlinks_md = "\n".join(lines).rstrip("\n") + "\n"

    lines = [GENERATED_MARKER, f"# Status: {title}", "", "## Documents by status", "",
             "| type | draft | in_review | approved | superseded |",
             "|---|---|---|---|---|"]
    for type_name in sorted(space.schema["doc_types"]):
        counts = {s: 0 for s in space.schema["statuses"]}
        for rel in docs_sorted:
            if space.docs[rel].doc_type == type_name:
                status = doc_status(space.docs[rel])
                if status in counts:
                    counts[status] += 1
        if sum(counts.values()):
            lines.append(f"| {type_name} | {counts['draft']} | {counts['in_review']} |"
                         f" {counts['approved']} | {counts['superseded']} |")
    lines += ["", "## Challenge coverage", "",
              "| node | rounds | last_verdict | open_blocking |",
              "|---|---|---|---|"]
    for node_rel in content_nodes(space):
        records = [d for d in space.docs.values()
                   if d.doc_type == "challenge_record" and d.node == node_rel
                   and str(d.fm.get("review_scope")) == "domain"]
        last = latest_record(space, node_rel, "domain")
        open_blocking = 0
        if last is not None:
            for i, info in space.ids.items():
                if info["doc"] == last.rel and info["kind"] == "CH" \
                        and info["row"].get("severity") == "blocking":
                    open_blocking += 1
        lines.append(f"| {node_rel or '(root)'} | {len(records)} |"
                     f" {last.fm.get('verdict') if last else ''} | {open_blocking} |")
    if advisories:
        lines += ["", "## Advisories: split proposals", "",
                  "Proposals, not instructions: a domain or space splits only",
                  "on explicit owner approval, asked through the",
                  "AskUserQuestion popup; a declined proposal is recorded as a",
                  "deferral row in the node's open questions.", ""]
        for w in sorted(advisories, key=lambda f: (f.path, f.line, f.check)):
            lines.append(f"- {w.path}:{w.line} [{w.check}] {w.message}")
    status_md = "\n".join(lines) + "\n"

    groups = {"open": [], "deferred": [], "answered": []}
    for i in sorted((x for x in space.ids if space.ids[x]["kind"] == "OQ"),
                    key=id_sort_key):
        info = space.ids[i]
        status = info["row"].get("status", "")
        if status in groups:
            groups[status].append(i)
    lines = [GENERATED_MARKER, f"# Open Questions: {title}", ""]
    for group, heading in (("open", "Open"), ("deferred", "Deferred"),
                           ("answered", "Answered (last 20)")):
        ids = groups[group]
        if group == "answered":
            ids = ids[-20:]
        if not ids:
            continue
        lines += [f"## {heading}", "",
                  "| id | question | doc | opened_on | note |", "|---|---|---|---|---|"]
        for i in ids:
            info = space.ids[i]
            row = info["row"]
            lines.append(f"| {i} | {row.get('question', '').replace('|', chr(92) + '|')} |"
                         f" {info['doc']} | {row.get('opened_on', '')} |"
                         f" {row.get('note', '').replace('|', chr(92) + '|')} |")
        lines.append("")
    questions_md = "\n".join(lines).rstrip("\n") + "\n"

    return {"index.md": index_md, "registry.md": registry_md,
            "registry.json": registry_json, "backlinks.md": backlinks_md,
            "status.md": status_md, "open-questions.md": questions_md}


def freshness_findings(space: Space, warnings: list[Finding]) -> list[Finding]:
    rendered = render_views(space, warnings)
    findings: list[Finding] = []
    gen_dir = space.root / GENERATED_DIR
    for name, content in rendered.items():
        on_disk = gen_dir / name
        if not on_disk.is_file() or \
                on_disk.read_text(encoding="utf-8", errors="replace") != content:
            findings.append(Finding(
                "error", f"{GENERATED_DIR}/{name}", 1, "generated_freshness",
                "generated view is stale or missing",
                "run the render subcommand"))
    return findings


