def index_path_for(tree: dict) -> str:
    parent = tree["path"].rstrip("/").rsplit("/", 1)[0]
    return f"{parent}/decision-log.md"


def escape_pipe(text: str) -> str:
    return text.replace("|", "\\|")


def render_decision_index(vault: Vault, tree: dict) -> str:
    notes = decision_notes(vault, tree)
    rows = []
    extra = tree.get("extra_column", "territory")
    for note in sorted(
            notes,
            key=lambda n: int((decision_id(tree, n) or "X-0").split("-")[-1])
            if decision_id(tree, n) else 0):
        rec_id = decision_id(tree, note) or note.rel
        target = note.rel[:-3]
        superseded = dict(note.fm_targets).get("superseded_by", "")
        superseded_cell = (
            f"[[{superseded}\\|{(vault.notes.get(superseded + '.md') or note).fm.get('title', superseded)}]]"
            if superseded else "")
        rows.append(
            f"| [[{target}\\|{rec_id}]] "
            f"| {escape_pipe(str(note.fm.get('title', '')))} "
            f"| {note.fm.get('status', '')} "
            f"| {escape_pipe(str(note.fm.get(extra, '')))} "
            f"| {note.fm.get('decided_at', '')} "
            f"| {escape_pipe(str(note.fm.get('revisit_trigger', '')))} "
            f"| {superseded_cell} |")
    header = (f"{GENERATED_INDEX_MARKER}\n\n# Decision Log\n\n"
              f"| id | title | status | {extra} | decided "
              f"| revisit trigger | superseded by |\n"
              f"|---|---|---|---|---|---|---|\n")
    return header + "\n".join(rows) + ("\n" if rows else "")


def cmd_render_decisions(args, policy: dict) -> int:
    vault = build_vault(args.vault.resolve(), policy)
    for tree_name, tree in sorted(policy.get("decision_trees", {}).items()):
        if not tree.get("render_index", True):
            continue  # this tree renders no index by policy
        notes = decision_notes(vault, tree)
        numbers: dict[str, str] = {}
        for note in notes:
            rec_id = decision_id(tree, note)
            if rec_id is None:
                continue
            number = rec_id.split("-")[-1]
            if number in numbers:
                print(f"vault_check: refuse to render '{tree_name}':"
                      f" duplicate id number {number}"
                      f" ({numbers[number]} vs {note.rel})", file=sys.stderr)
                return 1
            numbers[number] = note.rel
        if not notes:
            continue
        index_rel = index_path_for(tree)
        path = vault.root / index_rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_decision_index(vault, tree), encoding="utf-8")
        print(f"vault_check: rendered {index_rel} ({len(notes)} records)")
    return 0


def restamp(note_path: Path, stamps: dict[str, str],
            status: str | None) -> None:
    """Rewrite scalar frontmatter values and the status/ tag in one write."""
    text = note_path.read_text(encoding="utf-8")
    lines = text.splitlines()
    out: list[str] = []
    in_fm = False
    fm_done = False
    in_tags = False
    pending = dict(stamps)
    for line in lines:
        stripped = line.strip()
        if not fm_done and stripped == "---":
            if in_fm:
                for key, value in pending.items():
                    out.append(f"{key}: {value}")
                pending.clear()
                fm_done = True
            else:
                in_fm = True
            out.append(line)
            continue
        if in_fm and not fm_done:
            if in_tags and stripped.startswith("- "):
                if status and stripped[2:].strip().startswith("status/"):
                    indent = line[:len(line) - len(line.lstrip())]
                    out.append(f"{indent}- status/{status.replace('_', '-')}")
                else:
                    out.append(line)
                continue
            in_tags = False
            key = stripped.partition(":")[0].strip()
            if key in pending and ":" in stripped:
                out.append(f"{key}: {pending.pop(key)}")
                continue
            if re.match(r"^tags:\s*$", stripped):
                in_tags = True
        out.append(line)
    note_path.write_text("\n".join(out) + ("\n" if text.endswith("\n") else ""),
                         encoding="utf-8")


def cmd_stamp_decision(args, policy: dict) -> int:
    root = args.vault.resolve()
    vault = build_vault(root, policy)
    note_rel = args.note.replace("\\", "/")
    note = vault.notes.get(note_rel)
    tree = note_decision_tree(policy, note_rel)
    if note is None or tree is None:
        print(f"vault_check: '{args.note}' is not a decision note",
              file=sys.stderr)
        return 2
    if tree_is_glob(tree):
        print("vault_check: this decision tree is governed by the analysis"
              " compiler; approve through ba_compile.py approve",
              file=sys.stderr)
        return 2
    stamps = {"status": args.status, "decided_at": utc_today()}
    if args.supersedes:
        old_rel = args.supersedes.replace("\\", "/")
        old = vault.notes.get(old_rel)
        if old is None:
            print(f"vault_check: supersedes target '{old_rel}' not found",
                  file=sys.stderr)
            return 2
        stamps["supersedes"] = f"\"[[{old_rel[:-3]}]]\""
        restamp(old.path,
                {"status": "superseded",
                 "superseded_by": f"\"[[{note_rel[:-3]}]]\""},
                "superseded")
    restamp(note.path, stamps, args.status)
    print(f"vault_check: stamped {note_rel} status={args.status}")
    return cmd_render_decisions(args, policy)


