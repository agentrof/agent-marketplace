    def assert_role_files(self, config: dict, *, inherit: bool = False,
                          fallen: tuple = ()) -> dict:
        rows = role_settings.resolve(self.market.map, config, "codex")
        files = self.role_files()
        self.assertEqual(set(files), set(self.tiers))
        for role, text in files.items():
            with self.subTest(role=role):
                self.assertEqual(codex_settings(text), self.expected(
                    rows[role], follows=inherit or rows[role]["model"] in fallen))
        return rows

    def test_class_models_and_role_classes_set_the_role_files(self):
        market = self.market
        other = market.other_model("codex", HIGH)
        effort = market.non_default("codex", HIGH, model=other)
        config = {"class_models": {"codex": {HIGH: {"model": other, "effort": effort},
                                            MEDIUM: {"model": "session"}},
                                  "claude": {HIGH: {"model": "session"}}},
                  "role_classes": {MOVED: MEDIUM}}
        self.project.write_config(**config)
        report = self.generated("apply", "--scope", "local")
        rows = self.assert_role_files(config)
        self.assertEqual(rows[MOVED]["model"], "session")
        self.assertEqual(report["roles"], {role: {**row} for role, row in rows.items()})
        self.assertEqual(report["class_map"][HIGH],
                         {"model": other, "model_source": "config", "effort": effort,
                          "effort_source": "config"})
        self.assertEqual(report["class_map"][MEDIUM]["model"], "session")
        self.assertEqual(set(report["class_map"]), set(TIERS))
        self.assertTrue(report["restart_required"])
        self.assertIn("next spawn", report["notice"])
        again = self.generated("apply", "--scope", "local")
        self.assertEqual((again["changes"], again["written"], again["notice"]), ([], [], ""))
        self.project.write_config()
        restored = self.generated("apply", "--scope", "local")
        package = role_settings.resolve(market.map, {}, "codex")
