def doc_status(doc: Doc) -> str:
    return str(doc.fm.get("status", ""))


def parse_iso_date(value: str) -> date | None:
    try:
        return date.fromisoformat(value)
    except ValueError:
        return None


def utc_today() -> date:
    """This module's single clock read; every date this compiler writes
    or judges derives from it."""
    return datetime.now(timezone.utc).date()


def id_references(doc: Doc) -> list[tuple[int, str, str | None, bool]]:
    """All id references in a doc: (line, id, link_target or None, is_wiki).
    A wikilink whose alias is a bare id is an id citation; table id-column
    declarations are excluded (they are mints)."""
    refs: list[tuple[int, str, str | None, bool]] = []
    mint_lines = {}
    for table in doc.tables:
        for lineno, cells in table.rows:
            mint_lines.setdefault(lineno, set())
            if cells and "id" in table.columns:
                mint_lines[lineno].add(cells[table.columns.index("id")]
                                       if len(cells) > table.columns.index("id") else "")
    for idx, line in enumerate(doc.lines, start=1):
        if idx < doc.fm_end or idx in doc.fenced:
            continue
        scrubbed = INLINE_CODE_RE.sub(" ", line)
        for m in LINK_RE.finditer(scrubbed):
            text, target = m.group(1), m.group(2)
            if NAMESPACED_ID_RE.fullmatch(text) or BARE_ID_RE.fullmatch(text):
                refs.append((idx, text, target, False))
        for m in WIKILINK_RE.finditer(scrubbed):
            target, _anchor, alias = split_wikilink(m.group("inner"))
            if NAMESPACED_ID_RE.fullmatch(alias) or BARE_ID_RE.fullmatch(alias):
                refs.append((idx, alias, target, True))
        remaining = WIKILINK_RE.sub(" ", LINK_RE.sub(" ", scrubbed))
        for m in list(NAMESPACED_ID_RE.finditer(remaining)) + \
                list(BARE_ID_RE.finditer(remaining)):
            token = m.group(0)
            if token in mint_lines.get(idx, set()):
                continue
            refs.append((idx, token, None, False))
    return refs


def run_checks(space: Space, base: list[Finding], gate: bool = False,
               gate_node: str = "", today: date | None = None) -> list[Finding]:
    schema = space.schema
    findings = list(base)
    today = today or utc_today()

    def err(path, line, check, message, fix):
        findings.append(Finding("error", path, line, check, message, fix))

    def warn(path, line, check, message, fix):
        findings.append(Finding("warning", path, line, check, message, fix))

    statuses = schema["statuses"]
    fm_common = schema["frontmatter"]

    for rel in sorted(space.docs):
        doc = space.docs[rel]
        spec = schema["doc_types"][doc.doc_type]

        required = list(fm_common["required"]) + list(spec["extra_frontmatter"]["required"])
        allowed = set(required) | set(fm_common["optional"])
        for key in required:
            if key not in doc.fm:
                err(rel, 1, "frontmatter_schema",
                    f"missing frontmatter key '{key}'",
                    "the type's required keys are fixed by the schema")
        for key in doc.fm:
            if key not in allowed:
                warn(rel, 1, "frontmatter_schema",
                     f"unknown frontmatter key '{key}'",
                     "only schema-declared keys carry meaning")

        status = doc_status(doc)
        if status not in statuses:
            err(rel, 1, "status_legality",
                f"status '{status}' not in {statuses}",
                "use the schema's status enum")
        if status == "approved" and "approved_at" not in doc.fm:
            err(rel, 1, "status_legality",
                "approved doc is missing approved_at",
                "stamp approved_at: YYYY-MM-DD at the gate")
        if status != "approved" and "approved_at" in doc.fm:
            err(rel, 1, "status_legality",
                "approved_at present on a non-approved doc",
                "approved_at exists exactly when status is approved")
        if status == "superseded" and "superseded_by" not in doc.fm:
            err(rel, 1, "status_legality",
                "superseded doc is missing superseded_by",
                "name the successor documents")
        if "approved_at" in doc.fm:
            stamp = parse_iso_date(str(doc.fm["approved_at"])) \
                if DATE_RE.match(str(doc.fm["approved_at"])) else None
            if stamp is None:
                err(rel, 1, "status_legality",
                    "approved_at is not a YYYY-MM-DD calendar date",
                    "dates are ISO calendar dates; the approve verb stamps"
                    " them")
            elif stamp > today:
                err(rel, 1, "future_dates",
                    f"approved_at {doc.fm['approved_at']} is in the future",
                    "stamps come from the clock: ba_compile.py approve, or"
                    " paste pmo_cli.py now --date output")

        h1s = [h for h in doc.headings if h[1] == 1]
        if len(h1s) != 1:
            err(rel, 1, "required_sections",
                f"doc has {len(h1s)} H1 headings, expected exactly 1",
                "one H1 per document, matching its title")
        for token in spec["required_sections"]:
            if token not in doc.sections:
                err(rel, 1, "required_sections",
                    f"missing section '{token}'",
                    f"add an H2 carrying <!-- sec: {token} -->")

        cap = schema["summary_max_lines"].get(doc.doc_type,
                                              schema["summary_max_lines"]["default"])
        cap_key = ("summary_max_lines_space" if doc.doc_type == "space"
                   else "summary_max_lines_default")
        if doc.summary_lines > cap:
            err(rel, 1, "summary_caps",
                f"head summary is {doc.summary_lines} lines (cap {cap}"
                f"{limit_provenance(schema, cap_key)})",
                "the summary between the H1 and the first H2 is capped")

        for idx, line in enumerate(doc.lines, start=1):
            if EM_DASH in line:
                err(rel, idx, "content_bans", "em dash character found",
                    "replace with a hyphen, comma, or rewrite")
            if idx not in doc.fenced and line.lstrip().startswith("#") \
                    and heading_has_emoji(line):
                err(rel, idx, "content_bans", "emoji in heading",
                    "headings are plain text")
            if ABSOLUTE_PATH_RE.search(line):
                err(rel, idx, "content_bans", "absolute or home path found",
                    "workspace docs use relative paths only")

        for lineno, _text, target in doc.links:
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            clean = target.split("#", 1)[0]
            if not clean:
                continue
            resolved = (doc.abs_path.parent / clean).resolve()
            if space.vault_root is not None:
                try:
                    resolved.relative_to(space.vault_root.resolve())
                except ValueError:
                    pass
                else:
                    err(rel, lineno, "dead_links",
                        f"vault-internal citation uses a markdown link: {target}",
                        "cite vault content as a vault-absolute wikilink"
                        " (vault_check.py migrate rewrites this class)")
                    continue
            if not resolved.exists():
                err(rel, lineno, "dead_links",
                    f"link target does not resolve: {target}",
                    "fix the path or restore the target")
        for lineno, embed, target, _anchor, _alias in doc.wikilinks:
            if not target or space.vault_root is None:
                continue
            if target.split("/")[0] == GENERATED_DIR \
                    or f"/{GENERATED_DIR}/" in target:
                err(rel, lineno, "dead_links",
                    f"authored doc links into {GENERATED_DIR}/",
                    "authored docs never depend on generated views")
                continue
            candidate = (space.vault_root
                         / (target if embed else target + ".md"))
            if not candidate.exists():
                err(rel, lineno, "dead_links",
                    f"unresolved wikilink target: {target}",
                    "targets are vault-absolute paths from the vault root")

        for lineno, id_value, target, is_wiki in id_references(doc):
            info = space.ids.get(id_value)
            if target is not None:
                if info is None:
                    err(rel, lineno, "id_links",
                        f"link cites unknown id {id_value}",
                        "cite only declared ids")
                else:
                    owner = (space.root / info["doc"]).resolve()
                    if is_wiki:
                        resolved = ((space.vault_root / (target + ".md"))
                                    .resolve()
                                    if space.vault_root is not None else None)
                    else:
                        clean = target.split("#", 1)[0]
                        resolved = (doc.abs_path.parent / clean).resolve()
                    if resolved != owner:
                        err(rel, lineno, "id_links",
                            f"{id_value} link targets {target}, but the id is"
                            f" declared in {info['doc']}",
                            "an id link targets its owning document")
            else:
                in_table = any(any(lineno == ln for ln, _ in t.rows)
                               for t in doc.tables)
                if in_table:
                    if info is None:
                        err(rel, lineno, "id_links",
                            f"cell cites unknown id {id_value}",
                            "cite only declared ids")
                elif info is None or info["doc"] != rel:
                    err(rel, lineno, "id_links",
                        f"bare id {id_value} in prose",
                        "cite ids as links to their owning doc; bare ids are"
                        " legal only in the owning doc and in table cells")

        for kind in schema["doc_types"][doc.doc_type]["mints"]:
            row_schema = schema["row_schemas"][kind.lower()]
            enum = row_schema["status_enum"]
            for id_value, info in space.ids.items():
                if info["doc"] != rel or info["kind"] != kind:
                    continue
                row = info["row"]
                if enum and row.get("status", "") not in enum:
                    err(rel, info["line"], "row_schema",
                        f"{id_value} status '{row.get('status', '')}' not in {enum}",
                        "row statuses use the schema enum")
                if "opened_on" in row:
                    stamp = parse_iso_date(row["opened_on"]) \
                        if DATE_RE.match(row["opened_on"]) else None
                    if stamp is None:
                        err(rel, info["line"], "row_schema",
                            f"{id_value} opened_on is not a YYYY-MM-DD date",
                            "stamp the date the row was opened from the"
                            " clock: paste pmo_cli.py now --date output")
                    elif stamp > today:
                        err(rel, info["line"], "future_dates",
                            f"{id_value} opened_on {row['opened_on']} is in"
                            " the future",
                            "stamps come from the clock: paste pmo_cli.py"
                            " now --date output")
                    elif row.get("status") == "open":
                        age = (today - stamp).days
                        limit = schema["thresholds"]["open_row_age_days_warn"]
                        if age > limit:
                            warn(rel, info["line"], "aging",
                                 f"{id_value} has been open for {age} days"
                                 f" (warn at {limit}"
                                 f"{limit_provenance(schema, 'open_row_age_days_warn')})",
                                 "force it to an answer or defer it explicitly"
                                 " with a revisit trigger")
                if kind == "AC":
                    cite_ids = re.findall(r"\b[A-Z]{2,3}-[A-Z0-9]{2,4}-\d{3,}\b",
                                          row.get("cites", ""))
                    br_cites = [c for c in cite_ids if c.startswith("BR-")]
                    if not br_cites:
                        err(rel, info["line"], "row_schema",
                            f"{id_value} cites no business rule",
                            "every criterion cites the BR ids it exercises")
                    if not row.get("verify", "").strip():
                        err(rel, info["line"], "row_schema",
                            f"{id_value} has an empty verify cell",
                            "every criterion states how it is verified")

        if status == "approved":
            for id_value, info in space.ids.items():
                if info["doc"] != rel:
                    continue
                if info["row"].get("status") == "open":
                    err(rel, info["line"], "approval_preconditions",
                        f"approved doc holds open row {id_value}",
                        "answer, confirm, strike or defer every open row"
                        " before approval")

        if doc.doc_type == "challenge_record":
            check_challenge_record(space, doc, findings)

    check_semantic_links(space, findings)
    check_identifier_language(space, findings)
    check_thresholds(space, findings, warn)
    check_br_citations(space, findings, gate=gate, gate_node=gate_node)

    if gate:
        run_gate_checks(space, findings, gate_node)
    return findings


def check_challenge_record(space: Space, doc: Doc, findings: list[Finding]) -> None:
    schema = space.schema
    rel = doc.rel

    def err(line, message, fix):
        findings.append(Finding("error", rel, line, "challenge_record", message, fix))

    scope = str(doc.fm.get("review_scope", ""))
    if scope not in schema["row_enums"]["challenge_review_scope"]:
        err(1, f"review_scope '{scope}' not in enum", "domain or space")
    verdict = str(doc.fm.get("verdict", ""))
    if verdict not in schema["row_enums"]["challenge_verdict"]:
        err(1, f"verdict '{verdict}' not in enum", "converged or continue")
    round_no = doc.fm.get("round")
    max_rounds = schema["challenge"]["max_rounds"]
    rounds_prov = limit_provenance(schema, "challenge_max_rounds")
    rounds_note = f" (max_rounds{rounds_prov})" if rounds_prov else ""
    if not isinstance(round_no, int) or not 1 <= round_no <= max_rounds:
        err(1, f"round '{round_no}' outside 1..{max_rounds}{rounds_note}",
            "the loop is capped; residue goes to the gate as open questions")
        round_no = None
    name = Path(rel).name
    m = (space_round_file_re(schema).match(name) if scope == "space"
         else round_file_re(schema).match(name))
    if not m:
        expected = round_file_name(schema, scope, "N")
        err(1, f"filename '{name}' does not match its review_scope '{scope}'",
            f"round records here are named {expected} (schema-driven)")
    elif round_no is not None and int(m.group(1)) != round_no:
        err(1, f"filename round {m.group(1)} disagrees with frontmatter round"
            f" {round_no}", "the filename carries the round number")
    if scope == "space" and doc.node != "":
        err(1, "space-scope record outside the space root",
            "space rounds live in the root reviews/ folder")

    blocking = 0
    dispositions = schema["row_enums"]["ch_disposition"]
    severities = schema["row_enums"]["ch_severity"]
    for id_value, info in space.ids.items():
        if info["doc"] != rel or info["kind"] != "CH":
            continue
        row = info["row"]
        if row.get("severity", "") not in severities:
            err(info["line"], f"{id_value} severity '{row.get('severity', '')}'"
                f" not in {severities}", "the challenger's verdict, never downgraded")
        if row.get("severity") == "blocking":
            blocking += 1
        disposition = row.get("disposition", "").strip()
        if disposition not in dispositions:
            err(info["line"], f"{id_value} disposition '{disposition}' not in"
                f" {dispositions}", "triage disposes every finding")
        elif disposition != "rejected" and not row.get("targets", "").strip():
            err(info["line"], f"{id_value} disposition '{disposition}' names no"
                " target ids", "covered/fix/assumption/question cite what resolves them")
        elif disposition == "rejected" and not row.get("targets", "").strip():
            err(info["line"], f"{id_value} rejection carries no reason",
                "a rejection states its reason in the targets cell")
    if verdict == "converged" and blocking:
        err(1, f"verdict is converged but the round holds {blocking} blocking"
            " finding(s)", "converged means zero blocking findings this round")
    if doc.fm.get("locked") is True and doc_status(doc) != "approved":
        err(1, "locked record is not approved",
            "closing a round approves and locks it in the same write")
    if doc_status(doc) == "approved" and doc.fm.get("locked") is not True:
        err(1, "closed (approved) record is not locked",
            "set locked: true in the closing write; audit history is immutable")


def check_identifier_language(space: Space, findings: list[Finding]) -> None:
    """Identifier positions carry ASCII machine-safe names regardless of
    the configured language axes: schema-registered table columns must
    match the naming block's identifier format, and erDiagram or
    stateDiagram identifier lines must be ASCII (text after ':' labels
    and inside double quotes is free output_language content)."""
    naming = space.schema.get("naming")
    if not naming:
        return
    id_re = re.compile(naming["identifier_format"])
    for entry in naming.get("identifier_columns", []):
        for rel in sorted(space.docs):
            doc = space.docs[rel]
            if doc.doc_type != entry["doc_type"]:
                continue
            for table in doc.tables:
                if table.section != entry["section"]:
                    continue
                column = entry["column"]
                if column not in table.columns:
                    findings.append(Finding(
                        "error", rel, table.header_line, "identifier_shape",
                        f"table in section '{entry['section']}' carries no"
                        f" '{column}' column",
                        "the identifier column is fixed; see the space"
                        " standard"))
                    continue
                col_idx = table.columns.index(column)
                for lineno, cells in table.rows:
                    value = cells[col_idx].strip("`") if col_idx < len(cells) else ""
                    if not value and entry.get("allow_empty"):
                        continue
                    if not id_re.fullmatch(value):
                        findings.append(Finding(
                            "error", rel, lineno, "identifier_shape",
                            f"field name '{value}' is not an ASCII snake_case"
                            f" identifier ({naming['identifier_format']})",
                            "technical names are written in the"
                            " terminology_language (default English) as ASCII"
                            " snake_case; glossary.md carries the"
                            " business-term to technical-name mapping"))

    for rel in sorted(space.docs):
        doc = space.docs[rel]
        for start, end, info in doc.fences:
            if not info.startswith("mermaid"):
                continue
            kind = ""
            in_note = False
            for idx in range(start + 1, end):
                line = doc.lines[idx - 1].strip()
                if not line:
                    continue
                if not kind:
                    if line.startswith("erDiagram"):
                        kind = "erDiagram"
                    elif line.startswith("stateDiagram"):
                        kind = "stateDiagram"
                    else:
                        break
                    continue
                if line.startswith("%%"):
                    continue
                if in_note:
                    if line.startswith("end note"):
                        in_note = False
                    continue
                if line.startswith("note") and ":" not in line:
                    in_note = True
                    continue
                residue = re.sub(r'"[^"]*"', "", line).split(":", 1)[0]
                if not residue.isascii():
                    token = next(
                        (w for w in residue.split() if not w.isascii()),
                        residue.strip())
                    findings.append(Finding(
                        "error", rel, idx, "diagram_identifiers",
                        f"non-ASCII identifier '{token}' in a {kind} diagram",
                        "erDiagram entities/attributes and stateDiagram"
                        " states are terminology_language names in ASCII;"
                        " localized wording belongs after ':' labels or in"
                        " prose, with the mapping in glossary.md"))


def check_semantic_links(space: Space, findings: list[Finding]) -> None:
    for rel in sorted(space.docs):
        doc = space.docs[rel]
        for key, wanted in (("governs", ("process", "entity")),
                            ("verifies", ("process", "entity", "integration"))):
            targets = doc.fm.get(key)
            if not isinstance(targets, list):
                continue
            if not targets:
                findings.append(Finding("error", rel, 1, "semantic_links",
                                        f"{key} list is empty",
                                        f"name at least one target document"))
            for target in targets:
                value = str(target)
                if not (value.startswith("[[") and value.endswith("]]")):
                    findings.append(Finding(
                        "error", rel, 1, "semantic_links",
                        f"{key} value is not a quoted vault-absolute"
                        f" wikilink: {value}",
                        "relation values are quoted wikilinks; they draw the"
                        " graph edges the vault exists to show"))
                    continue
                inner, _, _ = split_wikilink(value[2:-2])
                resolved = ((space.vault_root / (inner + ".md")).resolve()
                            if space.vault_root is not None else None)
                try:
                    target_rel = (resolved.relative_to(
                        space.root.resolve()).as_posix()
                        if resolved is not None else None)
                except ValueError:
                    target_rel = None
                target_doc = space.docs.get(target_rel) if target_rel else None
                if target_doc is None:
                    findings.append(Finding("error", rel, 1, "semantic_links",
                                            f"{key} target does not resolve: {target}",
                                            "point at an existing document"))
                elif target_doc.doc_type not in wanted:
                    findings.append(Finding("error", rel, 1, "semantic_links",
                                            f"{key} target {target} is a"
                                            f" {target_doc.doc_type}",
                                            f"{key} points at {' or '.join(wanted)} docs"))

    for node_rel in sorted(space.nodes):
        overview_rel = node_overview_rel(space.schema, node_rel)
        overview = space.docs.get(overview_rel)
        if overview is None:
            continue
        linked = set()
        for _lineno, _text, target in overview.links:
            clean = target.split("#", 1)[0]
            resolved = (overview.abs_path.parent / clean).resolve()
            try:
                linked.add(resolved.relative_to(space.root.resolve()).as_posix())
            except ValueError:
                pass
        for _lineno, _embed, target, _anchor, _alias in overview.wikilinks:
            if not target or space.vault_root is None:
                continue
            resolved = (space.vault_root / (target + ".md")).resolve()
            try:
                linked.add(resolved.relative_to(space.root.resolve()).as_posix())
            except ValueError:
                pass
        prefix = f"{node_rel}/" if node_rel else ""
        children = [r for r in space.nodes
                    if r.startswith(f"{prefix}domains/") and
                    r.count("/") == (node_rel.count("/") + 2 if node_rel else 1)]
        for child in sorted(children):
            child_overview = node_overview_rel(space.schema, child)
            if child_overview in space.docs and child_overview not in linked:
                findings.append(Finding(
                    "error", overview_rel, 1, "semantic_links",
                    f"domain_map does not link child domain {child}",
                    "the overview's domain map links every direct child"))
        own_processes = [r for r in space.docs
                         if space.docs[r].node == node_rel
                         and space.docs[r].doc_type == "process"]
        for proc in sorted(own_processes):
            if proc not in linked:
                findings.append(Finding(
                    "error", overview_rel, 1, "semantic_links",
                    f"process_map does not link {proc}",
                    "the overview's process map links every process it owns"))


def check_thresholds(space: Space, findings: list[Finding], warn) -> None:
    th = space.schema["thresholds"]
    space_rel = space_overview_rel(space.schema)
    total_docs = len(space.docs)
    total_bytes = sum(len("\n".join(d.lines).encode("utf-8"))
                      for d in space.docs.values())
    if total_docs > th["space_docs_warn"]:
        warn(space_rel, 1, "thresholds",
             f"split proposal: space holds {total_docs} docs (warn at"
             f" {th['space_docs_warn']}"
             f"{limit_provenance(space.schema, 'space_docs_warn')})",
             "propose splitting the topic into multiple spaces; a space split"
             " needs explicit owner approval")
    if total_bytes > th["space_bytes_warn"]:
        warn(space_rel, 1, "thresholds",
             f"split proposal: space totals {total_bytes} bytes (warn at"
             f" {th['space_bytes_warn']}"
             f"{limit_provenance(space.schema, 'space_bytes_warn')})",
             "a split proposal: review the decomposition; snapshot size"
             " follows space size")

    for node_rel in sorted(space.nodes):
        own = [d for d in space.docs.values() if d.node == node_rel]
        direct = [d for d in own if d.doc_type not in
                  ("space", "domain", "challenge_record")]
        overview_rel = node_overview_rel(space.schema, node_rel)
        if len(direct) > th["node_direct_docs_warn"]:
            warn(overview_rel, 1, "thresholds",
                 f"split proposal: node owns {len(direct)} content docs (warn at"
                 f" {th['node_direct_docs_warn']}"
                 f"{limit_provenance(space.schema, 'node_direct_docs_warn')})",
                 "a split proposal: offer a child domain through the"
                 " AskUserQuestion popup; splits need explicit owner"
                 " approval")
        rule_sets = [d for d in own if d.doc_type == "rule_set"]
        if len(rule_sets) > th["rule_sets_per_node_warn"]:
            warn(overview_rel, 1, "thresholds",
                 f"split proposal: node owns {len(rule_sets)} rule sets (warn at"
                 f" {th['rule_sets_per_node_warn']}"
                 f"{limit_provenance(space.schema, 'rule_sets_per_node_warn')})",
                 "a split proposal: offer a child domain through the"
                 " AskUserQuestion popup; splits need explicit owner"
                 " approval")
        active_br = sum(1 for i in space.ids.values()
                        if i["kind"] == "BR" and i["row"].get("status") == "active"
                        and space.docs[i["doc"]].node == node_rel)
        if active_br > th["active_br_per_node_warn"]:
            warn(overview_rel, 1, "thresholds",
                 f"split proposal: node holds {active_br} active business rules"
                 f" (warn at"
                 f" {th['active_br_per_node_warn']}"
                 f"{limit_provenance(space.schema, 'active_br_per_node_warn')})",
                 "a split proposal: offer a child domain through the"
                 " AskUserQuestion popup; splits need explicit owner"
                 " approval")
        for d in own:
            if d.doc_type == "process" and len(d.lines) > th["process_doc_lines_warn"]:
                warn(d.rel, 1, "thresholds",
                     f"split proposal: process doc is {len(d.lines)} lines (warn at"
                     f" {th['process_doc_lines_warn']}"
                     f"{limit_provenance(space.schema, 'process_doc_lines_warn')})",
                     "a split proposal: offer a split by workflow stage or"
                     " variant; owner approval required")
            if d.doc_type == "rule_set":
                count = sum(1 for i in space.ids.values()
                            if i["doc"] == d.rel and i["kind"] == "BR"
                            and i["row"].get("status") == "active")
                if count > th["rules_per_set_warn"]:
                    warn(d.rel, 1, "thresholds",
                         f"split proposal: rule set holds {count} active rules (warn at"
                         f" {th['rules_per_set_warn']}"
                         f"{limit_provenance(space.schema, 'rules_per_set_warn')})",
                         "a split proposal: offer a split by governed target;"
                         " owner approval required")
            if d.doc_type == "acceptance_set":
                count = sum(1 for i in space.ids.values()
                            if i["doc"] == d.rel and i["kind"] == "AC"
                            and i["row"].get("status") == "active")
                if count > th["criteria_per_set_warn"]:
                    warn(d.rel, 1, "thresholds",
                         f"split proposal: acceptance set holds {count} active criteria"
                         f" (warn at {th['criteria_per_set_warn']}"
                         f"{limit_provenance(space.schema, 'criteria_per_set_warn')})",
                         "a split proposal: offer a split by flow (main versus"
                         " exceptions); owner approval required")

        processes = [d for d in own if d.doc_type == "process"]
        if len(processes) >= 2:
            entity_links: dict[str, set] = {}
            for proc in processes:
                touched = set()
                for _l, _t, target in proc.links:
                    clean = target.split("#", 1)[0]
                    resolved = (proc.abs_path.parent / clean).resolve()
                    try:
                        target_rel = resolved.relative_to(space.root.resolve()).as_posix()
                    except ValueError:
                        continue
                    tdoc = space.docs.get(target_rel)
                    if tdoc is not None and tdoc.doc_type == "entity":
                        touched.add(target_rel)
                entity_links[proc.rel] = touched
            groups = [{"procs": {proc_rel}, "entities": set(touched)}
                      for proc_rel, touched in sorted(entity_links.items())]
            changed = True
            while changed:
                changed = False
                for a in range(len(groups)):
                    for b in range(a + 1, len(groups)):
                        if groups[a]["entities"] & groups[b]["entities"]:
                            groups[a]["procs"] |= groups[b]["procs"]
                            groups[a]["entities"] |= groups[b]["entities"]
                            del groups[b]
                            changed = True
                            break
                    if changed:
                        break
            real = [g for g in groups if g["entities"]]
            if len(real) >= 2 and all(len(g["procs"]) >= 2 for g in real):
                warn(overview_rel, 1, "thresholds",
                     "split proposal: node's processes touch disjoint"
                     " entity clusters",
                     "the clusters may be separate domains; offer the"
                     " split, owner approval required")


def check_br_citations(space: Space, findings: list[Finding],
                       gate: bool, gate_node: str) -> None:
    cited: set[str] = set()
    for id_value, info in space.ids.items():
        if info["kind"] != "AC":
            continue
        for m in NAMESPACED_ID_RE.finditer(info["row"].get("cites", "")):
            cited.add(m.group(0))
    for id_value in sorted(space.ids):
        info = space.ids[id_value]
        if info["kind"] != "BR" or info["row"].get("status") != "active":
            continue
        if id_value in cited:
            continue
        in_scope = doc_in_node(space, info["doc"], gate_node)
        severity = "error" if gate and in_scope else "warning"
        findings.append(Finding(
            severity, info["doc"], info["line"], "br_uncited",
            f"{id_value} is cited by no acceptance criterion",
            "every active rule is exercised by at least one criterion"))


def doc_in_node(space: Space, rel: str, node_rel: str) -> bool:
    if node_rel == "":
        return True
    doc = space.docs.get(rel)
    if doc is None:
        return False
    return doc.node == node_rel or doc.node.startswith(node_rel + "/")


def content_nodes(space: Space) -> list[str]:
    result = []
    for node_rel in sorted(space.nodes):
        own = [d for d in space.docs.values()
               if d.node == node_rel and d.doc_type in
               ("process", "entity", "rule_set", "acceptance_set", "integration")]
        if own:
            result.append(node_rel)
    return result


def latest_record(space: Space, node_rel: str, scope: str) -> Doc | None:
    best: Doc | None = None
    best_round = 0
    for doc in space.docs.values():
        if doc.doc_type != "challenge_record" or doc.node != node_rel:
            continue
        if str(doc.fm.get("review_scope", "")) != scope:
            continue
        round_no = doc.fm.get("round")
        if isinstance(round_no, int) and round_no > best_round:
            best, best_round = doc, round_no
    return best


def record_satisfies_gate(space: Space, record: Doc | None) -> str | None:
    """Return None when the record satisfies the gate, else the reason."""
    max_rounds = space.schema["challenge"]["max_rounds"]
    rounds_prov = limit_provenance(space.schema, "challenge_max_rounds")
    rounds_note = f" (max_rounds{rounds_prov})" if rounds_prov else ""
    if record is None:
        return "no challenge record exists"
    if record.fm.get("locked") is not True:
        return f"{record.rel} is not closed (locked)"
    if str(record.fm.get("verdict")) != "converged" \
            and record.fm.get("round") != max_rounds:
        return (f"{record.rel} is not converged and is not the final round"
                f" {max_rounds}{rounds_note}")
    return None


def run_gate_checks(space: Space, findings: list[Finding], gate_node: str) -> None:
    def err(path, line, message, fix):
        findings.append(Finding("error", path, line, "gate_approval", message, fix))

    for name in root_file_rels(space.schema):
        doc = space.docs.get(name)
        if doc is None:
            continue
        if doc_status(doc) != "approved":
            err(name, 1, f"foundation doc is {doc_status(doc)}, not approved",
                "the foundation gate precedes every domain gate")

    for rel in sorted(space.docs):
        doc = space.docs[rel]
        if not doc_in_node(space, rel, gate_node):
            continue
        spec = space.schema["doc_types"][doc.doc_type]
        if spec["gate_blocking"] and doc_status(doc) not in ("approved", "superseded"):
            err(rel, 1, f"gate-blocking doc is {doc_status(doc)}, not approved",
                "approve or supersede every gate-blocking doc in the subtree")

    subtree_nodes = [n for n in content_nodes(space)
                     if gate_node == "" or n == gate_node
                     or n.startswith(gate_node + "/")]
    for node_rel in subtree_nodes:
        overview = node_overview_rel(space.schema, node_rel)
        reason = record_satisfies_gate(space, latest_record(space, node_rel, "domain"))
        if reason:
            err(overview, 1, f"challenge gate unsatisfied: {reason}",
                "run the challenge loop and close a converged (or final) round")

    has_domains = len(space.nodes) > 1
    if gate_node == "" and has_domains:
        reason = record_satisfies_gate(space, latest_record(space, "", "space"))
        if reason:
            err(space_overview_rel(space.schema), 1,
                f"space-level challenge gate unsatisfied: {reason}",
                "run the cross-domain round before closing the space")

    for folder, type_name in (("processes", "process"), ("rules", "rule_set"),
                              ("acceptance", "acceptance_set")):
        exists = any(doc_in_node(space, rel, gate_node)
                     and space.docs[rel].doc_type == type_name
                     for rel in space.docs)
        if not exists:
            anchor = node_overview_rel(space.schema, gate_node)
            err(anchor, 1, f"subtree holds no {type_name} document",
                "the distributed brief contract requires processes, rules"
                " and acceptance criteria")

    if gate_node:
        for rel in sorted(space.docs):
            doc = space.docs[rel]
            if not doc_in_node(space, rel, gate_node):
                continue
            for _lineno, id_value, _target, _is_wiki in id_references(doc):
                info = space.ids.get(id_value)
                if info is None or doc_in_node(space, info["doc"], gate_node):
                    continue
                owner = space.docs[info["doc"]]
                if doc_status(owner) != "approved":
                    err(rel, _lineno,
                        f"cites {id_value} whose owning doc {info['doc']} is"
                        f" {doc_status(owner)}",
                        "cross-domain citation closure: cited owners are approved")


