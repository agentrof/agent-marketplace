def normalize_backlog_map_aliases(path: Path, backlog_title: str) -> None:
    """Remove map aliases that conflict with the canonical backlog title."""
    if not path.is_file():
        return
    props, body = parse_front_matter(path)
    aliases = values(props, "aliases")
    retained = [
        alias for alias in aliases
        if alias.casefold() not in {"backlog", backlog_title.casefold()}
    ]
    if retained:
        props["aliases"] = retained
    else:
        props.pop("aliases", None)
    body = re.sub(
        r"\[\[backlog/backlog(?:\|[^\]\n]+)?\]\]",
        f"[[backlog/backlog|{backlog_title}]]",
        body,
    )
    updated = front_matter(props, body)
    if updated != path.read_text(encoding="utf-8"):
        path.write_bytes(updated.encode("utf-8"))


def write_generated(path: Path, content: bytes) -> None:
    """Avoid filesystem churn without caching any validation result."""
    if not path.is_file() or path.read_bytes() != content:
        path.write_bytes(content)


