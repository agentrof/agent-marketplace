def story_classification_findings(props: dict, path: str, contract: dict) -> list[str]:
    """Validate the optional impact classifications a story declares.

    A story with neither a classification nor its reason is unknown for it and
    checks as before; a reason alone is a half-written classification. One it
    declares takes a declared value and a concrete reason.
    """
    errors = []
    for key, spec in sorted(contract["optional_story_classifications"].items()):
        if key not in props:
            if spec["reason"] in props:
                errors.append(f"{path} {spec['reason']} needs {key}")
            continue
        value, reason = props[key], props.get(spec["reason"])
        if value not in spec["values"]:
            errors.append(f"{path} {key} must be {' or '.join(spec['values'])},"
                          f" not {value or '(missing)'}")
        if not isinstance(reason, str) or not meaningful_text(reason):
            errors.append(f"{path} {key} needs a concrete {spec['reason']}")
    return errors


def scenario_blocks(body: str) -> list[tuple[str, str]]:
    matches = list(re.finditer(
        r"^##\s+([A-Z][A-Z0-9]*-[0-9]{2,}-TS-[0-9]{3})\s*$",
        body, flags=re.MULTILINE))
    result = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(body)
        result.append((match.group(1), body[match.end():end]))
    return result


def scenario_fields(block: str) -> tuple[dict[str, str], list[str]]:
    fields: dict[str, str] = {}
    duplicates: list[str] = []
    active = ""
    for raw in block.splitlines():
        match = re.match(r"^-\s+([A-Za-z_]+):\s*(.*)$", raw)
        if match:
            key, value = match.group(1), match.group(2).strip()
            if key in fields:
                duplicates.append(key)
            fields[key] = value
            active = key
            continue
        nested = re.match(r"^\s{2,}-\s+(.+?)\s*$", raw)
        if nested and active == "source_refs":
            fields[active] = (fields[active] + ", " + nested.group(1)).strip(", ")
    return fields, duplicates


def source_ref_values(raw: str) -> tuple[list[str], bool]:
    matches = re.findall(r"\[\[[^\[\]\n]+\]\]", raw)
    residue = raw
    for value in matches:
        residue = residue.replace(value, "", 1)
    return matches, not residue.replace(",", "").strip()


def ref_identity(value: str) -> tuple[str, str, str] | None:
    return split_wikilink(value)


def scenario_findings(docs: Path, body: str, story_id: str,
                      criteria: list[str], evidence: list[str],
                      work_kind: str, path: str,
                      scaffolds: list[str] | None = None) -> tuple[list[str], list[str]]:
    """Validate a test plan; ``scaffolds`` receives untouched stub findings."""
    errors: list[str] = []
    stubs = errors if scaffolds is None else scaffolds
    for candidate in re.findall(
        r"(?im)^##\s+(\S+-ts-\S+)\s*$", body
    ):
        if re.fullmatch(
                r"[A-Z][A-Z0-9]*-[0-9]{2,}-TS-[0-9]{3}", candidate
        ) is None:
            errors.append(
                f"{path} has malformed scenario-like heading: {candidate}"
            )
    blocks = scenario_blocks(body)
    ids = [item[0] for item in blocks]
    if not ids:
        return [f"{path} needs at least one scenario heading"], []
    if len(ids) != len(set(ids)):
        errors.append(f"{path} has duplicate scenario ids")
    criterion_set = {identity for value in criteria
                     if (identity := ref_identity(value)) is not None}
    evidence_set = {identity for value in evidence
                    if (identity := ref_identity(value)) is not None}
    covered: set[tuple[str, str, str]] = set()
    for scenario_id, block in blocks:
        if not scenario_id.startswith(f"{story_id}-TS-"):
            errors.append(f"{path} scenario {scenario_id} does not belong to {story_id}")
        fields, duplicates = scenario_fields(block)
        for duplicate in sorted(set(duplicates)):
            errors.append(f"{path} scenario {scenario_id} repeats {duplicate}")
        required_fields = [
            "category", "target", "automation", "source_refs",
            "Given", "When", "Then",
        ]
        for field in required_fields:
            if not fields.get(field, "").strip():
                errors.append(f"{path} scenario {scenario_id} is missing {field}")
        for field, sentinel in SCENARIO_STUBS.items():
            if normalized_text(fields.get(field, "")) == normalized_text(
                    sentinel):
                stubs.append(
                    f"{path} scenario {scenario_id} has an untouched "
                    f"{field} stub"
                )
        automation = fields.get("automation", "").lower()
        if automation and automation not in {"required", "manual"}:
            errors.append(f"{path} scenario {scenario_id} has invalid automation value")
        if automation == "required" and not fields.get("automation_target", "").strip():
            errors.append(f"{path} scenario {scenario_id} is missing automation_target")
        if "rows" in fields and not ROWS_RE.fullmatch(fields["rows"]):
            errors.append(f"{path} scenario {scenario_id} rows must be a positive integer")
        if "row_split" in fields and fields["row_split"] not in ROW_SPLITS:
            errors.append(f"{path} scenario {scenario_id} row_split must be one of {', '.join(ROW_SPLITS)}")
        target = fields.get("automation_target", "").strip()
        if target and (target.startswith("/") or ".." in Path(target).parts
                       or any(char.isspace() for char in target)):
            errors.append(f"{path} scenario {scenario_id} has invalid automation_target")
        source_values, clean = source_ref_values(fields.get("source_refs", ""))
        if fields.get("source_refs", "") and not clean:
            errors.append(f"{path} scenario {scenario_id} source_refs must contain only wikilinks")
        if len(source_values) != len(set(source_values)):
            errors.append(f"{path} scenario {scenario_id} repeats source_refs")
        for source in source_values:
            identity = ref_identity(source)
            label = f"{path} scenario {scenario_id} source_ref"
            if identity in criterion_set:
                validate_criterion_ref(docs, source, label, errors)
            elif identity in evidence_set and work_kind in {"defect", "technical"}:
                validate_evidence_ref(docs, source, label, errors)
            else:
                read_link(docs, source, label, errors)
                errors.append(
                    f"{path} scenario {scenario_id} cites planning source "
                    f"absent from its story: {source}"
                )
                continue
            if identity is not None:
                covered.add(identity)
    for source in (criteria if work_kind == "feature" else criteria + evidence):
        if ref_identity(source) not in covered:
            errors.append(f"{path} does not map planning source {source} to a scenario")
    errors.extend(scenario_coverage_findings(body, ids, path, scaffolds))
    return errors, ids


def scenario_coverage_findings(body: str, scenario_ids: list[str],
                               path: str,
                               scaffolds: list[str] | None = None) -> list[str]:
    rows, errors = structured_table(
        section(body, "Coverage Classes"),
        ("class", "disposition", "scenario_refs", "reason"),
        path, "Coverage Classes",
    )
    stubs = errors if scaffolds is None else scaffolds
    stub_rows = False
    by_class: dict[str, dict[str, str]] = {}
    known_scenarios = set(scenario_ids)
    classified_scenarios: set[str] = set()
    for number, row in enumerate(rows, 1):
        class_name = row["class"]
        if class_name in by_class:
            errors.append(f"{path} repeats coverage class: {class_name}")
        by_class[class_name] = row
        if class_name not in SCENARIO_COVERAGE_CLASSES:
            errors.append(f"{path} has unknown coverage class: {class_name or number}")
        disposition = row["disposition"]
        if disposition not in {"covered", "not_applicable"}:
            errors.append(f"{path} coverage class {class_name or number} has invalid disposition: {disposition or '(missing)'}")
            continue
        raw_refs = row["scenario_refs"]
        refs = [] if raw_refs in {"", "-"} else [
            value.strip() for value in raw_refs.split(",") if value.strip()
        ]
        if len(refs) != len(set(refs)):
            errors.append(f"{path} coverage class {class_name or number} repeats scenario_refs")
        unknown = sorted(set(refs) - known_scenarios)
        if unknown:
            errors.append(f"{path} coverage class {class_name or number} cites unknown scenarios: {', '.join(unknown)}")
        if disposition == "covered" and not refs:
            errors.append(f"{path} covered class {class_name or number} needs scenario_refs")
        if disposition == "covered":
            classified_scenarios.update(set(refs) & known_scenarios)
        if disposition == "not_applicable":
            if refs:
                errors.append(f"{path} not_applicable class {class_name or number} must not cite scenarios")
            if not meaningful_text(row["reason"]):
                stub = normalized_text(row["reason"]) == normalized_text(COVERAGE_REASON_STUB)
                stub_rows = stub_rows or stub
                (stubs if stub else errors).append(
                    f"{path} not_applicable class {class_name or number} needs a concrete reason")
    missing = sorted(set(SCENARIO_COVERAGE_CLASSES) - set(by_class))
    if missing:
        errors.append(f"{path} is missing coverage classes: {', '.join(missing)}")
    unclassified = sorted(known_scenarios - classified_scenarios)
    if unclassified:
        # The stub table classifies nothing; while one of its rows is left,
        # classifying the scenarios is still pending writer work.
        (stubs if stub_rows else errors).append(
            f"{path} scenarios are not classified by Coverage Classes: "
            + ", ".join(unclassified)
        )
    return errors


