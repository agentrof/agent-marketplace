def split_agent(text: str) -> tuple[list[str], str]:
    """Return an agent file's frontmatter lines and its body."""
    end = text.index("\n---\n", 4)
    return text[4:end].splitlines(), text[end + 5:]


def field_lines(lines: list[str], *keys: str) -> list[str]:
    return [line for line in lines if line.split(":", 1)[0] in keys]


def stamp(package: Path, role: str, setting: dict) -> str:
    """The header line of a role rendered by ``package`` with ``setting``: its
    version, its source digest and the digest of its resolved model and effort."""
    version = load(package / ".agent-marketplace-package.json")["version"]
    digest = hashlib.sha256((package / "agents" / f"{role}.md").read_bytes()).hexdigest()
    settings = hashlib.sha256(json.dumps(
        {"model": setting["model"], "effort": setting["effort"]},
        sort_keys=True).encode("utf-8")).hexdigest()
    return (f"# Rendered from {PLUGIN} {version} agents/{role}.md sha256:{digest}"
            f" settings sha256:{settings}")


