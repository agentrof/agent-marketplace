def _format_re(fmt: str) -> re.Pattern:
    pattern = re.escape(fmt).replace(re.escape("{n}"), r"(\d+)")
    return re.compile(f"^{pattern}$")


def round_file_re(schema: dict) -> re.Pattern:
    return _format_re(schema["challenge"]["round_file_format"])


