#!/usr/bin/env python3
"""Compiler and checker for business-analysis spaces.

An analysis space is one topic folder under workspace/docs/business-analysis/:
a tree of typed, cross-linked markdown documents (the authored source of
truth) plus machine-generated views under _generated/. This script is the
single mechanical authority over that structure. It contains zero document
taxonomy of its own: every doc type, section token, id kind, row schema and
threshold comes from the shipped schema data file
(skills/business-analysis/data/space-schema.json).

Subcommands:
  init          create a new space skeleton
  stub          create one born-compliant typed document
  check         structural validation; --gate approval adds the gate rules
  render        (re)generate the _generated/ views deterministically
  resolve       map ids to owning docs, statuses and statement hashes
  verify-import validate a backlog import's criterion ids against the space

Stdlib only. Exit 0 on success, 1 on findings/violations, 2 on usage.
Finding format mirrors tools/validate.py: SEVERITY path:line [check]
message | Fix: remediation, sorted by (path, line, check).
"""

