def render_agents_md(claude_md_text: str) -> str:
    """Derive templates/AGENTS.md from templates/CLAUDE.md.

    The @-import lines are a Claude Code memory mechanism; the prose
    directive that duplicates each import stays, so the derived file loses
    no instruction.
    """
    lines = [l for l in claude_md_text.splitlines() if not l.startswith("@")]
    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.rstrip("\n") + "\n"


def render_matrix_block(config: dict) -> str:
    rows = config.get("docs", {}).get("matrix_rows", [])
    lines = [
        MATRIX_START,
        "| Capability | Claude Code | Cursor | Codex CLI |",
        "|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row.get('capability', '')} | {row.get('claude_code', '')} |"
            f" {row.get('cursor', '')} | {row.get('codex', '')} |"
        )
    lines.append(MATRIX_END)
    return "\n".join(lines)


def inject_matrix(existing_text: str, block: str) -> str:
    pattern = re.compile(
        re.escape(MATRIX_START) + r".*?" + re.escape(MATRIX_END), re.DOTALL
    )
    if pattern.search(existing_text):
        return pattern.sub(block, existing_text, count=1)
    return existing_text.rstrip("\n") + "\n\n" + block + "\n"


# ---------------------------------------------------------------------------
# Render everything
# ---------------------------------------------------------------------------


def render_all(root: Path, config: dict) -> dict[str, str]:
    """Return relpath -> exact file content for every generated artifact.

    docs/harnesses.md is span-managed and handled separately (see
    matrix drift helpers); it does not appear in this map.
    """
    rendered: dict[str, str] = {}
    harnesses = config["harnesses"]
    source_marketplace = _read_json(root / ".claude-plugin" / "marketplace.json")

    for harness_id in sorted(harnesses):
        harness = harnesses[harness_id]
        if harness_id == "cursor":
            rendered[harness["marketplace_path"]] = dumps_json(
                render_cursor_marketplace(source_marketplace))
        elif harness_id == "codex":
            rendered[harness["marketplace_path"]] = dumps_json(
                render_codex_marketplace(source_marketplace))

    for plugin in plugin_dirs(root):
        source_manifest = _read_json(plugin / ".claude-plugin" / "plugin.json")
        source_hooks_path = plugin / "hooks" / "hooks.json"
        source_hooks = _read_json(source_hooks_path) if source_hooks_path.is_file() else {}
        has_hooks = bool(source_hooks.get("hooks"))
        prefix = f"plugins/{plugin.name}"

        for harness_id in sorted(harnesses):
            harness = harnesses[harness_id]
            fmt = harness.get("agent_format", "markdown")

            if harness_id == "cursor":
                manifest = render_cursor_plugin_manifest(plugin, source_manifest, harness, has_hooks)
            else:
                manifest = render_codex_plugin_manifest(plugin, source_manifest, harness, has_hooks)
            rendered[f"{prefix}/{harness['plugin_manifest_path']}"] = dumps_json(manifest)

            if has_hooks:
                hooks_out = render_hooks(source_hooks, harness, harness_id)
                rendered[f"{prefix}/{harness['hooks_manifest']}"] = dumps_json(hooks_out)

            for agent in agent_files(plugin):
                fm, body = parse_frontmatter(agent.read_text(encoding="utf-8"))
                if fmt == "markdown":
                    content = render_cursor_agent(fm, body, harness, harness_id)
                    rendered[f"{prefix}/{harness['agents_dir']}/{agent.stem}.md"] = content
                elif fmt == "toml":
                    content = render_toml_agent(fm, body, harness, harness_id)
                    name = fm.get("name", agent.stem)
                    rendered[f"{prefix}/{harness['agents_dir']}/{name}.toml"] = content

            for sdir in skill_dirs(plugin):
                if "skill_policy_file" not in harness:
                    continue
                fm, _ = parse_frontmatter((sdir / "SKILL.md").read_text(encoding="utf-8"))
                policy = render_skill_policy(fm, harness, harness_id)
                if policy is not None:
                    rendered[
                        f"{prefix}/skills/{sdir.name}/{harness['skill_policy_file']}"
                    ] = policy

        claude_md = plugin / "templates" / "CLAUDE.md"
        if claude_md.is_file():
            rendered[f"{prefix}/templates/AGENTS.md"] = render_agents_md(
                claude_md.read_text(encoding="utf-8"))

    runtime = config.get("runtime")
    if runtime and runtime.get("path"):
        runtime_path = Path(runtime["path"])
        if (root / runtime_path.parent.parent).is_dir():
            payload = {k: v for k, v in runtime.items() if k != "path"}
            rendered[runtime["path"]] = dumps_json(payload)

    return rendered


# ---------------------------------------------------------------------------
# Generated-scope predicate (consumed by the validator's walkers)
# ---------------------------------------------------------------------------


def generated_roots(config: dict) -> list[str]:
    """Directory prefixes (relative to a plugin dir or the repo root) that
    the renderer owns exclusively; used for orphan scanning and for the
    validator's is_generated predicate."""
    roots: list[str] = []
    for harness in config["harnesses"].values():
        roots.append(harness["plugin_manifest_path"].split("/")[0])
        roots.append(harness["agents_dir"].split("/")[0])
        roots.append(harness["hooks_manifest"].split("/")[0])
        roots.append(harness["marketplace_path"].split("/")[0])
    return sorted(set(roots))


def is_generated(root: Path, config: dict, path: Path) -> bool:
    """True when path is a generated artifact (never content-scanned;
    proven by renderer construction plus byte-drift equality instead)."""
    try:
        relparts = path.relative_to(root).parts
    except ValueError:
        return False
    if not relparts:
        return False
    roots = set(generated_roots(config))
    if relparts[0] in roots:
        return True
    if relparts[0] == "plugins" and len(relparts) >= 3:
        if relparts[2] in roots:
            return True
        if (len(relparts) >= 5 and relparts[2] == "skills"
                and relparts[4] == "agents"):
            return True
        if relparts[2] == "templates" and relparts[-1] == "AGENTS.md":
            return True
        runtime = config.get("runtime", {})
        if runtime.get("path") and path == root / runtime["path"]:
            return True
    return False


# ---------------------------------------------------------------------------
# Drift and writing
# ---------------------------------------------------------------------------


def _orphan_scan_dirs(root: Path, config: dict) -> list[Path]:
    dirs: list[Path] = []
    roots = generated_roots(config)
    for name in roots:
        candidate = root / name
        if candidate.is_dir():
            dirs.append(candidate)
    for plugin in plugin_dirs(root):
        for name in roots:
            candidate = plugin / name
            if candidate.is_dir():
                dirs.append(candidate)
        for sdir in skill_dirs(plugin):
            candidate = sdir / "agents"
            if candidate.is_dir():
                dirs.append(candidate)
    return dirs


def diff(root: Path, config: dict, rendered: dict[str, str] | None = None) -> list[tuple[str, str]]:
    """Return [(relpath, reason)] where reason is missing | stale | orphan."""
    if rendered is None:
        rendered = render_all(root, config)
    problems: list[tuple[str, str]] = []
    for relpath, content in sorted(rendered.items()):
        target = root / relpath
        if not target.is_file():
            problems.append((relpath, "missing"))
        elif target.read_text(encoding="utf-8") != content:
            problems.append((relpath, "stale"))
    rendered_paths = {root / rp for rp in rendered}
    for scan_dir in _orphan_scan_dirs(root, config):
        for path in sorted(p for p in scan_dir.rglob("*") if p.is_file()):
            if path not in rendered_paths:
                problems.append((path.relative_to(root).as_posix(), "orphan"))
    doc = root / HARNESSES_DOC_RELPATH
    block = render_matrix_block(config)
    if not doc.is_file():
        problems.append((HARNESSES_DOC_RELPATH, "missing"))
    else:
        text = doc.read_text(encoding="utf-8")
        if inject_matrix(text, block) != text:
            problems.append((HARNESSES_DOC_RELPATH, "stale"))
    return sorted(set(problems))


def write_all(root: Path, config: dict) -> list[str]:
    """Write every artifact; idempotent. Returns relpaths written/changed."""
    rendered = render_all(root, config)
    changed: list[str] = []
    for relpath, content in sorted(rendered.items()):
        target = root / relpath
        if target.is_file() and target.read_text(encoding="utf-8") == content:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        changed.append(relpath)
    rendered_paths = {root / rp for rp in rendered}
    for scan_dir in _orphan_scan_dirs(root, config):
        for path in sorted(p for p in scan_dir.rglob("*") if p.is_file()):
            if path not in rendered_paths:
                path.unlink()
                changed.append(path.relative_to(root).as_posix() + " (removed)")
    doc = root / HARNESSES_DOC_RELPATH
    block = render_matrix_block(config)
    if not doc.is_file():
        doc.parent.mkdir(parents=True, exist_ok=True)
        skeleton = HARNESSES_DOC_SKELETON.format(start=MATRIX_START, end=MATRIX_END)
        doc.write_text(inject_matrix(skeleton, block), encoding="utf-8")
        changed.append(HARNESSES_DOC_RELPATH)
    else:
        text = doc.read_text(encoding="utf-8")
        new_text = inject_matrix(text, block)
        if new_text != text:
            doc.write_text(new_text, encoding="utf-8")
            changed.append(HARNESSES_DOC_RELPATH)
    return changed
