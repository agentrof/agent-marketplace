def has_cycle(graph: dict[str, set[str]]) -> bool:
    visiting: set[str] = set()
    visited: set[str] = set()

    def walk(node: str) -> bool:
        if node in visiting:
            return True
        if node in visited:
            return False
        visiting.add(node)
        if any(walk(target) for target in graph.get(node, set())):
            return True
        visiting.remove(node)
        visited.add(node)
        return False

    return any(walk(node) for node in graph)


def round_number(path: Path, props: dict, suffix: str, errors: list[str]) -> int:
    match = re.fullmatch(rf"round-([0-9]+)-{suffix}\.md", path.name)
    expected = int(match.group(1)) if match else 0
    actual = props.get("round")
    if not isinstance(actual, int) or actual != expected or expected < 1:
        errors.append(f"{path.as_posix()} round must match its filename")
    return expected


@stage_package.candidate_session()
@experience_validation_session()
def collect(docs: Path, *, historical_inputs: bool = False,
            review_inputs: bool = False, revision_inputs: bool = False,
            prior_universe: bool = False) -> tuple[dict, list[str]]:
    """Validate sources; input discovery may precede authored review findings.

    ``record["scaffold_findings"]`` names the returned errors that exist only
    because a placeholder the stub verbs write is still untouched.
    ``record["advisory_findings"]`` names what is reported but never returned
    as an error: the empty last section of a story approved before the
    compiler read that section above the navigation.
    ``prior_universe`` judges criterion coverage against the BA universe of the
    last committed backlog approval, as begin-revision's intake check does: a
    criterion approved upstream since then is the revision's work, never a
    reason to refuse opening it. Every other reader, Delivery's historical read
    included, judges coverage against the current approved universe.
    """
    contract = backlog_contract()
    root = docs / "backlog"
    errors: list[str] = []
    scaffolds: list[str] = []
    advisories: list[str] = []
    record = {"backlog": None, "backlog_reviews": [], "epics": [],
              "stories": [], "test_plans": [], "epic_reviews": [],
              "scaffold_findings": [], "advisory_findings": []}
    root_note = root / "backlog.md"
    if not root_note.is_file():
        return record, ["backlog/backlog.md is missing"]
    props, root_body = parse_front_matter(root_note)
    if props.get("type") != "backlog":
        errors.append("backlog/backlog.md must have type: backlog")
    if props.get("owner_role") != "product_owner":
        errors.append("backlog/backlog.md owner_role must be product_owner")
    errors.extend(status_findings(props, "backlog", "backlog/backlog.md",
                                  contract))
    if "assignee" in props:
        errors.append("backlog/backlog.md must not contain assignee")
    planning_mode, input_refs, planning_errors = planning_package_findings(
        docs, props, "backlog/backlog.md", allow_historical=historical_inputs)
    errors.extend(planning_errors)
    record["backlog"] = {"path": root_note.relative_to(docs).as_posix(),
                         "id": note_id(props, "BACKLOG"), "props": props,
                         "body": root_body, "planning_mode": planning_mode,
                         "input_package_refs": input_refs}

    rounds: set[int] = set()
    reviews_dir = root / "reviews"
    for path in sorted(reviews_dir.glob("round-*-backlog-review.md")):
        review_props, body = parse_front_matter(path)
        rel = path.relative_to(docs).as_posix()
        if review_props.get("type") != "backlog-review":
            errors.append(f"{rel} must have type: backlog-review")
        if review_props.get("owner_role") != "product_owner":
            errors.append(f"{rel} owner_role must be product_owner")
        errors.extend(status_findings(review_props, "backlog-review", rel,
                                      contract))
        if "assignee" in review_props:
            errors.append(f"{rel} must not contain assignee")
        review_round = round_number(path, review_props, "backlog-review", errors)
        if review_round in rounds:
            errors.append(f"backlog review round {review_round} is duplicated")
        rounds.add(review_round)
        record["backlog_reviews"].append({"path": rel, "props": review_props,
                                          "body": body,
                                          "id": note_id(review_props, path.stem),
                                          "round": review_round})
    if not review_inputs:
        errors.extend(review_completion_findings(
            docs, record["backlog_reviews"], contract["required_backlog_review_sections"], contract))

    epics_root = root / "epics"
    for epic_dir in sorted(epics_root.iterdir() if epics_root.is_dir() else []):
        if not epic_dir.is_dir() or epic_dir.name.startswith("_"):
            continue
        if not SLUG_RE.fullmatch(epic_dir.name):
            errors.append(f"invalid epic folder name: {epic_dir.name}")
            continue
        epic_path = epic_dir / "epic.md"
        if not epic_path.is_file():
            errors.append(f"{epic_path.relative_to(docs)} is missing")
            continue
        epic_props, epic_body = parse_front_matter(epic_path)
        epic_rel = epic_path.relative_to(docs).as_posix()
        epic_id = note_id(epic_props, epic_dir.name.upper())
        if not ID_RE.fullmatch(epic_id):
            errors.append(f"{epic_rel} has invalid id: {epic_id}")
        if epic_props.get("type") != "epic":
            errors.append(f"{epic_rel} must have type: epic")
        if epic_props.get("owner_role") != "product_owner":
            errors.append(f"{epic_rel} owner_role must be product_owner")
        errors.extend(status_findings(epic_props, "epic", epic_rel, contract))
        if not str(epic_props.get("goal", "")).strip():
            errors.append(f"{epic_rel} needs a goal")
        elif normalized_text(epic_props.get("goal")) == normalized_text(
                EPIC_GOAL_STUB):
            scaffolds.append(f"{epic_rel} has an untouched goal stub")
        if "assignee" in epic_props:
            errors.append(f"{epic_rel} must not contain assignee")
        epic = {"path": epic_rel, "folder": epic_dir.name, "id": epic_id,
                "props": epic_props, "body": epic_body, "stories": [],
                "reviews": []}
        epic_rounds: set[int] = set()
        for review in sorted((epic_dir / "reviews").glob("round-*-epic-review.md")):
            review_props, review_body_text = parse_front_matter(review)
            review_rel = review.relative_to(docs).as_posix()
            if review_props.get("type") != "epic-review":
                errors.append(f"{review_rel} must have type: epic-review")
            if review_props.get("owner_role") != "product_owner":
                errors.append(f"{review_rel} owner_role must be product_owner")
            errors.extend(status_findings(review_props, "epic-review",
                                          review_rel, contract))
            if "assignee" in review_props:
                errors.append(f"{review_rel} must not contain assignee")
            review_round = round_number(review, review_props, "epic-review", errors)
            if review_round in epic_rounds:
                errors.append(f"{epic_id} review round {review_round} is duplicated")
            epic_rounds.add(review_round)
            item = {"path": review_rel, "props": review_props,
                    "body": review_body_text,
                    "id": note_id(review_props, review.stem),
                    "round": review_round}
            epic["reviews"].append(item)
            record["epic_reviews"].append(item | {"epic_id": epic_id})
        if not review_inputs:
            errors.extend(review_completion_findings(
                docs, epic["reviews"], contract["required_epic_review_sections"], contract))

        stories_root = epic_dir / "stories"
        for story_dir in sorted(stories_root.iterdir() if stories_root.is_dir() else []):
            if not story_dir.is_dir() or story_dir.name.startswith("_"):
                continue
            if not SLUG_RE.fullmatch(story_dir.name):
                errors.append(f"invalid story folder name: {story_dir.name}")
                continue
            story_path = story_dir / "story.md"
            test_path = story_dir / "test-plan.md"
            if not story_path.is_file():
                errors.append(f"{story_path.relative_to(docs)} is missing")
                continue
            story_props, story_body = parse_front_matter(story_path)
            story_rel = story_path.relative_to(docs).as_posix()
            story_id = note_id(story_props, story_dir.name.upper())
            if not ID_RE.fullmatch(story_id):
                errors.append(f"{story_rel} has invalid id: {story_id}")
            if story_props.get("type") != "story":
                errors.append(f"{story_rel} must have type: story")
            errors.extend(status_findings(story_props, "story", story_rel,
                                          contract))
            if "assignee" in story_props:
                errors.append(f"{story_rel} must not contain assignee")
            for key in ("scope", "priority", "priority_reason", "owner_role"):
                if not str(story_props.get(key, "")).strip():
                    errors.append(f"{story_rel} needs {key}")
            errors.extend(required_section_findings(
                story_body, contract["required_story_sections"], story_rel))
            for title in navigation_only_sections(
                    story_body, contract["required_story_sections"]):
                finding = f"{story_rel} required section is empty: {title}"
                # A story approved before this check keeps its approval: its
                # empty section is advisory until the story is revised.
                if approval_stamp_findings(story_path, docs):
                    errors.append(finding)
                else:
                    advisories.append(f"{finding}; advisory until the approved story is revised")
            # Navigation has no heading and extends the last section, which
            # is Delivery Notes in a stubbed story.
            authored_body = story_body.split(NAV_MARKER, 1)[0]
            for key, sentinel in STORY_STUBS.items():
                actual = story_props.get(key, "") if key in {
                    "scope", "priority_reason"
                } else section(authored_body, key)
                if normalized_text(actual) == normalized_text(sentinel):
                    finding = f"{story_rel} has an untouched {key} stub"
                    # The navigation once hid this stub from the check, so a
                    # story approved before keeps its approval: the stub is
                    # advisory until the story is revised, as an empty last
                    # section is.
                    if key == "Delivery Notes" and not approval_stamp_findings(story_path, docs):
                        advisories.append(f"{finding}; advisory until the approved story is revised")
                    else:
                        scaffolds.append(finding)

            owner = str(story_props.get("owner_role", ""))
            owners = set(contract["story_owner_roles"])
            supporters = values(story_props, "supporting_roles")
            allowed_supporters = set(contract["story_supporting_roles"])
            if owner and owner not in owners:
                errors.append(f"{story_rel} has invalid owner_role: {owner}")
            if len(supporters) != len(set(supporters)):
                errors.append(f"{story_rel} has duplicate supporting_roles")
            if owner in supporters:
                errors.append(f"{story_rel} repeats owner_role in supporting_roles")
            for role in supporters:
                if role not in allowed_supporters:
                    errors.append(f"{story_rel} has invalid supporting_role: {role}")
            errors.extend(story_classification_findings(story_props, story_rel, contract))
            responsibilities = section(story_body, "Implementation Responsibilities")
            if normalized_text(RESPONSIBILITY_STUB) in normalized_text(
                    responsibilities):
                scaffolds.append(
                    f"{story_rel} has an untouched implementation "
                    "responsibility stub"
                )
            for role in [owner] + supporters:
                if role and not re.search(rf"(?m)^-\s+{re.escape(role)}\s*:\s*\S", responsibilities):
                    errors.append(f"{story_rel} does not assign an implementation responsibility to {role}")

            criteria = values(story_props, "criterion_refs")
            experience = values(story_props, "experience_refs")
            evidence = values(story_props, "related_to")
            dependencies = values(story_props, "depends_on")
            design_refs = values(story_props, "uses_design")
            constraint_refs = values(story_props, "constrained_by")
            work_kind = str(story_props.get("work_kind", ""))
            implements = values(story_props, "implements")
            planning_mode = str(record["backlog"].get("planning_mode", ""))
            current_revision = int(record["backlog"]["props"].get("revision", 1) or 1)
            introduced = int(story_props.get("introduced_in_revision", 0) or 0)
            origin_mode = str(story_props.get("origin_mode", ""))
            if planning_mode and introduced == current_revision:
                if origin_mode != planning_mode:
                    errors.append(f"{story_rel} origin_mode must match current planning_mode")
                if planning_mode == "manual" and implements:
                    errors.append(f"{story_rel} manual planning must not declare implements")
                if planning_mode == "requirement":
                    root_requirement = str(record["backlog"]["props"].get("requirement_ref", ""))
                    errors.extend(implements_findings(story_props, story_rel, root_requirement))
            elif planning_mode and (introduced <= 0 or not (
                    origin_mode or record["backlog"]["props"].get("legacy_contract"))):
                # Historical records stay readable, but every new contract
                # record identifies its intake without rewriting history. A
                # story stubbed under the legacy contract has no mode to name.
                errors.append(f"{story_rel} needs origin_mode and introduced_in_revision")
            if work_kind not in WORK_KINDS:
                errors.append(f"{story_rel} work_kind must be feature, defect, or technical")
            for key, refs in (("criterion_refs", criteria),
                              ("experience_refs", experience),
                              ("uses_design", design_refs),
                              ("constrained_by", constraint_refs),
                              ("depends_on", dependencies)):
                if len(refs) != len(set(refs)):
                    errors.append(f"{story_rel} has duplicate {key}")
            if work_kind == "feature" and not criteria:
                errors.append(f"{story_rel} needs criterion_refs")
            if work_kind == "feature" and not experience:
                errors.append(f"{story_rel} needs experience_refs")
            if work_kind == "feature" and not design_refs:
                errors.append(f"{story_rel} needs uses_design")
            if work_kind == "feature" and not any(
                    split_wikilink(value)
                    and split_wikilink(value)[0].startswith("solution-design/")
                    for value in constraint_refs):
                errors.append(
                    f"{story_rel} feature work needs a solution-design "
                    "constrained_by reference"
                )
            if work_kind in {"defect", "technical"}:
                errors.extend(evidence_findings(docs, story_props, story_rel))
            for value in criteria:
                validate_criterion_ref(docs, value, f"{story_rel} criterion_ref", errors)
            for value in experience:
                if planning_mode:
                    validate_experience_ref(
                        docs, value, f"{story_rel} experience_ref", errors,
                        require_current=(
                            not historical_inputs and introduced == current_revision
                        ),
                    )
                else:
                    validate_upstream_ref(
                        docs, value, f"{story_rel} experience_ref",
                        ("experience-design/",), set(),
                        errors)
            for key, roots, types in (
                ("uses_design", ("design-system/",), {"design-master", "page-override"}),
                ("constrained_by", ("solution-design/", "system-architecture/"), set()),
            ):
                for value in values(story_props, key):
                    validate_upstream_ref(docs, value, f"{story_rel} {key}",
                                          roots, types, errors)

            derives = link_targets(docs, story_props, "derives_from",
                                   f"{story_rel} derives_from", errors)
            if derives != [epic_rel.removesuffix(".md")]:
                errors.append(f"{story_rel} must derive exactly from {epic_rel}")

            dependency_targets = link_targets(
                docs, story_props, "depends_on", f"{story_rel} depends_on", errors)
            reason_targets = dependency_reason_targets(
                docs, story_body, story_rel, errors)
            if set(dependency_targets) != reason_targets:
                missing = sorted(set(dependency_targets) - reason_targets)
                extra = sorted(reason_targets - set(dependency_targets))
                if missing:
                    errors.append(f"{story_rel} dependencies missing reasons: {', '.join(missing)}")
                if extra:
                    errors.append(f"{story_rel} dependency reasons are not declared: {', '.join(extra)}")

            test_props: dict = {}
            test_body = ""
            ids: list[str] = []
            if not test_path.is_file():
                errors.append(f"{test_path.relative_to(docs)} is missing")
            else:
                test_props, test_body = parse_front_matter(test_path)
                test_rel = test_path.relative_to(docs).as_posix()
                if test_props.get("type") != "test-plan":
                    errors.append(f"{test_rel} must have type: test-plan")
                errors.extend(status_findings(test_props, "test-plan", test_rel,
                                              contract))
                if test_props.get("owner_role") != "qa_engineer":
                    errors.append(f"{test_rel} owner_role must be qa_engineer")
                if "assignee" in test_props:
                    errors.append(f"{test_rel} must not contain assignee")
                expected_story_target = story_rel.removesuffix(".md")
                test_derives = link_targets(docs, test_props, "derives_from",
                                            f"{test_rel} derives_from", errors)
                test_verifies = link_targets(docs, test_props, "verifies",
                                             f"{test_rel} verifies", errors)
                if test_derives != [expected_story_target]:
                    errors.append(f"{test_rel} must derive exactly from {story_rel}")
                if test_verifies != [expected_story_target]:
                    errors.append(f"{test_rel} must verify exactly {story_rel}")
                scenario_errors, ids = scenario_findings(
                    docs, test_body, story_id, criteria, evidence,
                    work_kind, test_rel, scaffolds)
                errors.extend(scenario_errors)
            story = {
                "path": story_rel,
                "test_plan": test_path.relative_to(docs).as_posix(),
                "folder": story_dir.name, "id": story_id,
                "epic_id": epic_id, "props": story_props,
                "body": story_body, "test_props": test_props,
                "test_body": test_body, "scenario_ids": ids,
                "criteria": criteria, "experience_refs": experience,
                "work_kind": work_kind,
                "implements": implements,
                "dependency_targets": dependency_targets,
            }
            epic["stories"].append(story)
            record["stories"].append(story)
            record["test_plans"].append({
                "path": story["test_plan"], "story_id": story_id,
                "props": test_props, "scenario_ids": ids,
            })
        if not epic["stories"]:
            errors.append(f"{epic_rel} has no stories")
        if not epic["reviews"]:
            errors.append(f"{epic_rel} has no epic review")
        record["epics"].append(epic)

    if not record["epics"]:
        errors.append("backlog/epics must contain at least one epic")
    if not record["backlog_reviews"]:
        errors.append("backlog/reviews must contain a cross-epic backlog review")
    epic_ids = [epic["id"] for epic in record["epics"]]
    story_ids = [story["id"] for story in record["stories"]]
    if len(epic_ids) != len(set(epic_ids)):
        errors.append("epic ids must be unique")
    if len(story_ids) != len(set(story_ids)):
        errors.append("story ids must be unique across epics")

    story_by_target = {story["path"].removesuffix(".md"): story
                       for story in record["stories"]}
    graph: dict[str, set[str]] = {}
    for story in record["stories"]:
        dependencies: set[str] = set()
        for target in story["dependency_targets"]:
            target_story = story_by_target.get(target)
            if target_story is None:
                errors.append(f"{story['id']} depends on unknown story target {target}")
                continue
            declared = next((value for value in values(story["props"], "depends_on")
                             if split_wikilink(value)
                             and split_wikilink(value)[0] == target), "")
            alias = split_wikilink(declared)[2] if declared else ""
            if alias != target_story["id"]:
                errors.append(f"{story['id']} dependency alias must be {target_story['id']}: {target}")
            dependencies.add(target_story["id"])
        graph[story["id"]] = dependencies
    if has_cycle(graph):
        errors.append("story dependency graph contains a cycle")

    if not review_inputs:
        errors.extend(review_coverage_findings(record, docs))
    errors.extend(global_criterion_coverage_findings(
        record, docs, prior_universe=prior_universe, revision_inputs=revision_inputs))
    if historical_inputs and {"input_contract", "absent_input_stages"}.intersection(record["backlog"]["props"]):
        errors.extend(backlog_input_policy.historical_absence_findings(docs, record))
    record["scaffold_findings"] = sorted(set(scaffolds))
    record["advisory_findings"] = sorted(set(advisories))
    return record, sorted(set(errors) | set(scaffolds))


def latest(items: list[dict]) -> dict | None:
    return max(items, key=lambda item: item["round"]) if items else None


def dependency_edges(stories: list[dict], same_epic: bool | None,
                     record: dict) -> set[str]:
    by_target = {story["path"].removesuffix(".md"): story
                 for story in record["stories"]}
    edges = set()
    for story in stories:
        for target in story["dependency_targets"]:
            dependency = by_target.get(target)
            if dependency is None:
                continue
            is_same = dependency["epic_id"] == story["epic_id"]
            if same_epic is None or is_same == same_epic:
                edges.add(f"{story['id']} -> {dependency['id']}")
    return edges


def review_coverage_findings(record: dict, docs: Path) -> list[str]:
    errors: list[str] = []
    root_review = latest(record["backlog_reviews"])
    if root_review is not None:
        expected_parent = {record["backlog"]["path"].removesuffix(".md")}
        parent_targets = link_targets(
            docs, root_review["props"], "derives_from",
            f"{root_review['path']} derives_from", errors)
        actual_parent = set(parent_targets)
        if len(parent_targets) != len(actual_parent):
            errors.append(f"{root_review['path']} has duplicate derives_from links")
        if actual_parent != expected_parent:
            errors.append(f"{root_review['path']} must derive exactly from backlog/backlog.md")
        expected_epics = {epic["path"].removesuffix(".md")
                          for epic in record["epics"]}
        epic_targets = link_targets(
            docs, root_review["props"], "related_to",
            f"{root_review['path']} related_to", errors)
        actual_epics = set(epic_targets)
        if len(epic_targets) != len(actual_epics):
            errors.append(f"{root_review['path']} has duplicate related_to links")
        if actual_epics != expected_epics:
            errors.append(f"{root_review['path']} related_to set does not exactly cover every epic")
        expected_edges = dependency_edges(record["stories"], False, record)
        edge_values = values(root_review["props"], "dependency_refs")
        actual_edges = set(edge_values)
        if len(edge_values) != len(actual_edges):
            errors.append(f"{root_review['path']} has duplicate dependency_refs")
        if actual_edges != expected_edges:
            errors.append(f"{root_review['path']} dependency_refs do not exactly cover cross-epic dependencies")

    for epic in record["epics"]:
        review = latest(epic["reviews"])
        if review is None:
            continue
        expected_parent = {epic["path"].removesuffix(".md")}
        parent_targets = link_targets(
            docs, review["props"], "derives_from",
            f"{review['path']} derives_from", errors)
        actual_parent = set(parent_targets)
        if len(parent_targets) != len(actual_parent):
            errors.append(f"{review['path']} has duplicate derives_from links")
        if actual_parent != expected_parent:
            errors.append(f"{review['path']} must derive exactly from {epic['path']}")
        expected_targets = {
            target for story in epic["stories"]
            for target in (story["path"].removesuffix(".md"),
                           story["test_plan"].removesuffix(".md"))
        }
        verified_targets = link_targets(
            docs, review["props"], "verifies",
            f"{review['path']} verifies", errors)
        actual_targets = set(verified_targets)
        if len(verified_targets) != len(actual_targets):
            errors.append(f"{review['path']} has duplicate verifies links")
        if actual_targets != expected_targets:
            errors.append(f"{review['path']} verifies set does not exactly cover every story and test plan")
        expected_scenarios = {scenario for story in epic["stories"]
                              for scenario in story["scenario_ids"]}
        scenario_values = values(review["props"], "scenario_refs")
        actual_scenarios = set(scenario_values)
        if len(scenario_values) != len(actual_scenarios):
            errors.append(f"{review['path']} has duplicate scenario_refs")
        if actual_scenarios != expected_scenarios:
            errors.append(f"{review['path']} scenario_refs do not exactly cover every scenario")
        expected_edges = dependency_edges(epic["stories"], True, record)
        edge_values = values(review["props"], "dependency_refs")
        actual_edges = set(edge_values)
        if len(edge_values) != len(actual_edges):
            errors.append(f"{review['path']} has duplicate dependency_refs")
        if actual_edges != expected_edges:
            errors.append(f"{review['path']} dependency_refs do not exactly cover intra-epic dependencies")
    return errors


def global_criterion_coverage_findings(record: dict, docs: Path, *,
                                     prior_universe: bool = False,
                                     revision_inputs: bool = False) -> list[str]:
    errors: list[str] = []
    covered = {
        key for story in record["stories"]
        for value in story["criteria"]
        if (key := criterion_key(value))
    }
    root_review = latest(record["backlog_reviews"])
    deferred: dict[str, dict] = {}
    if root_review is not None:
        deferred, findings = deferred_criteria(
            docs, root_review["body"], root_review["path"]
        )
        errors.extend(findings)
    scopes = values(record["backlog"]["props"], "analysis_scopes")
    if scopes:
        universe, scope_errors = scoped_ba_universe(docs, scopes)
        errors.extend(scope_errors)
    else:
        # Requirement Flow selects the BA universe for feature work. Evidence
        # only defect/technical slices do not inherit every historical BA
        # criterion merely because an approved registry exists.
        has_feature_story = any(
            story["work_kind"] == "feature" for story in record["stories"]
        )
        universe = approved_ba_universe(docs, errors) if has_feature_story else {}
        if not universe:
            universe = {key: {} for key in covered}
    prior = prior_approved_universe(docs) if prior_universe or revision_inputs else None
    if prior_universe and prior is not None:
        universe = {key: entry for key, entry in universe.items() if key in prior}
    unknown_covered = sorted(covered - set(universe))
    if unknown_covered:
        errors.append("story criterion_refs contain values outside the approved BA universe: "
                      + ", ".join(unknown_covered))
    unknown_deferred = sorted(set(deferred) - set(universe))
    if unknown_deferred:
        errors.append("Deferred Criteria contains values outside the approved BA universe: "
                      + ", ".join(unknown_deferred))
    overlap = sorted(covered & set(deferred))
    if overlap:
        errors.append("criteria cannot be both story-covered and deferred: "
                      + ", ".join(overlap))
    uncovered = sorted(set(universe) - covered - set(deferred))
    if revision_inputs and prior is not None and record["backlog"]["props"].get("status") == "draft":
        additions = sorted(set(uncovered) - prior)
        if additions:
            record["transition_findings"] = [
                "new approved BA criteria/rules require story coverage or explicit deferral: "
                + ", ".join(additions)]
            uncovered = sorted(set(uncovered) - set(additions))
    if uncovered:
        errors.append("approved BA criteria/rules are neither story-covered nor deferred: "
                      + ", ".join(uncovered))
    return errors


def review_completion_findings(docs: Path, reviews: list[dict], sections: list[str],
                               contract: dict) -> list[str]:
    errors = []
    current = latest(reviews)
    for review in reviews:
        if review is not current and review["props"].get("status") != "approved" and not (
                review["props"].get("source_hash") or review["props"].get("approved_at_utc")):
            continue
        errors.extend(review_section_findings(review["body"], sections, review["path"], docs))
        errors.extend(accepted_minor_findings(docs, review["body"], review["path"], contract))
        errors.extend(review_loop_record(docs, review["body"], review["path"], review["props"]))
        errors.extend(recheck_closure_record(docs, review["body"], review["path"], review["props"]))
        if review is current and review["props"].get("status") != "approved":
            errors.extend(review_verdict_findings(review))
    return errors


REVIEW_VERDICTS = ("approved", "changes_requested")


def review_verdict_findings(review: dict) -> list[str]:
    """Check the verdict field of the review being written.

    Atomic approval reads only this field, so an empty one under a concluded
    Verdict section, or an approved one under a changes_requested status,
    would otherwise refuse only after the owner approved the package.
    """
    props, path = review["props"], review["path"]
    verdict = str(props.get("verdict") or "")
    conclusion = re.search(r"(?m)^Conclusion \[Verdict\]:\s*(\S.+?)\s*$",
                           section(review["body"], "Verdict"))
    concluded = (conclusion is not None and meaningful_text(conclusion.group(1))
                 and not generic_review_text(conclusion.group(1)))
    errors = []
    if verdict and verdict not in REVIEW_VERDICTS:
        errors.append(f"{path} verdict must be approved or changes_requested")
    elif concluded and not verdict:
        errors.append(f"{path} concludes its Verdict section but its verdict field is empty;"
                      " record the reader's verdict")
    if verdict == "approved" and props.get("status") == "changes_requested":
        errors.append(f"{path} verdict approved contradicts status changes_requested;"
                      " set status draft, approval stamps approved")
    return errors


def historical_unapproved_review_paths(record: dict, docs: Path) -> set[Path]:
    groups = [record["backlog_reviews"], *(epic["reviews"] for epic in record["epics"])]
    return {docs / review["path"] for reviews in groups for review in reviews
            if review is not latest(reviews) and review["props"].get("status") != "approved"
            and not (review["props"].get("source_hash") or review["props"].get("approved_at_utc"))}


def package_paths(record: dict, docs: Path) -> list[Path]:
    relatives = [record["backlog"]["path"]]
    relatives += [review["path"] for review in record["backlog_reviews"]]
    for epic in record["epics"]:
        relatives.append(epic["path"])
        relatives += [review["path"] for review in epic["reviews"]]
        for story in epic["stories"]:
            relatives.extend([story["path"], story["test_plan"]])
    return [docs / rel for rel in sorted(set(relatives))]


def approval_readiness_findings(record: dict) -> list[str]:
    errors: list[str] = []
    root_review = latest(record["backlog_reviews"])
    if root_review is None or root_review["props"].get("verdict") != "approved":
        errors.append("latest cross-epic backlog review verdict is not approved")
    elif root_review["props"].get("status") == "changes_requested":
        errors.append("latest cross-epic backlog review still requests changes")
    for epic in record["epics"]:
        review = latest(epic["reviews"])
        if review is None or review["props"].get("verdict") != "approved":
            errors.append(f"{epic['id']} latest epic review verdict is not approved")
        elif review["props"].get("status") == "changes_requested":
            errors.append(f"{epic['id']} latest epic review still requests changes")
        for story in epic["stories"]:
            if story["props"].get("status") != "planned":
                errors.append(f"{story['id']} must remain planned at backlog approval")
    return sorted(set(errors))


def requirement_coverage_findings(record: dict) -> list[str]:
    """Require the row that reports this approval's Requirement as incorporated.

    requirement_compile.requirement_incorporated reads the latest approved root
    review: the Requirement counts as incorporated only when a row there names
    every Story that implements it. With no such Story it cannot count, and no
    row is required.
    """
    backlog = record.get("backlog") or {}
    requirement = str(backlog.get("props", {}).get("requirement_ref", ""))
    review = latest(record["backlog_reviews"])
    if backlog.get("planning_mode") != "requirement" or review is None:
        return []
    implementing = sorted(story["id"] for story in record["stories"]
                          if requirement_compile.implements_requirement(story["implements"], requirement))
    if not implementing:
        return []
    path = review["path"]
    if REQUIREMENT_COVERAGE in headings(review["body"]):
        rows, errors = structured_table(section(review["body"], REQUIREMENT_COVERAGE),
                                        REQUIREMENT_COVERAGE_COLUMNS, path, REQUIREMENT_COVERAGE)
    else:
        rows, errors = [], [f"{path} is missing required section: {REQUIREMENT_COVERAGE}"]
    matching = [row for row in rows if row["requirement"] == requirement]
    if len(matching) > 1:
        errors.append(f"{path} {REQUIREMENT_COVERAGE} repeats {requirement}")
    elif not matching or sorted(filter(None, re.split(r"[\s,]+", matching[0]["story_ids"]))) != implementing:
        errors.append(f"{path} {REQUIREMENT_COVERAGE} needs one {requirement} row whose story_ids"
                      f" are exactly the Stories that implement it: {', '.join(implementing)}")
    return errors


def approval_stamp_findings(path: Path, docs: Path) -> list[str]:
    props, _body = parse_front_matter(path)
    rel = path.relative_to(docs).as_posix()
    errors = []
    timestamp = props.get("approved_at_utc")
    if not isinstance(timestamp, str) or not timestamp:
        errors.append(f"{rel} approved_at_utc is missing")
    else:
        try:
            parsed = datetime.fromisoformat(timestamp.replace("Z", "+00:00"))
            offset = parsed.utcoffset()
        except ValueError:
            offset = None
        if offset is None or offset.total_seconds() != 0:
            errors.append(f"{rel} approved_at_utc is not a UTC timestamp")
    if props.get("source_hash") != digest(path):
        errors.append(f"{rel} approved source_hash is stale")
    return errors


def git_object_id(project: Path, name: str) -> str | None:
    """Return the object id that a name resolves to, or None when Git cannot resolve it.

    Git resolves a full object id to itself whatever the refs hold, so a name
    that resolved to itself is not resolved again; HEAD and every other name
    are resolved on every call.
    """
    key = ("object-id", project.resolve(), name)
    if key in _GIT_OBJECT_READS:
        return name
    resolved = subprocess.run(
        ["git", "--no-replace-objects", "rev-parse", "--verify", name],
        cwd=project, capture_output=True, check=False,
    )
    if resolved.returncode:
        return None
    object_id = resolved.stdout.decode("ascii").strip()
    if object_id == name:
        _GIT_OBJECT_READS[key] = object_id
    return object_id


def committed_approval_sources(project: Path, docs: Path, commit: str = "HEAD") -> dict[Path, bytes]:
    """Read the backlog at one pinned HEAD, with object IDs as batch input.

    Each commit is read once per process. Its dict is kept for each given
    project path, which the dict's paths start with, and every call returns a
    new copy.
    """
    head = git_object_id(project, commit)
    if head is None:
        return {}
    prefix = (docs / "backlog").relative_to(project).as_posix()
    repository = project.resolve()
    read = ("tree-sources", repository, head, prefix)
    if read not in _GIT_OBJECT_READS:
        _GIT_OBJECT_READS[read] = committed_tree_sources(project, head, prefix)
    paths = ("approval-sources", repository, head, prefix, project)
    if paths not in _GIT_OBJECT_READS:
        _GIT_OBJECT_READS[paths] = {project / relative: content
                                    for relative, content in _GIT_OBJECT_READS[read].items()}
    return dict(_GIT_OBJECT_READS[paths])


def committed_tree_sources(project: Path, head: str, prefix: str) -> dict[str, bytes]:
    """Read every regular file under a prefix at one commit object id, by repository path."""
    listing = subprocess.run(
        ["git", "--no-replace-objects", "--literal-pathspecs", "ls-tree", "-r", "-z",
         head, "--", prefix],
        cwd=project, capture_output=True, check=False,
    )
    if listing.returncode:
        raise ValueError("committed backlog approval inventory is unreadable")
    selected = {}
    for row in listing.stdout.split(b"\0"):
        if not row:
            continue
        fields, raw = row.split(b"\t", 1)
        mode, kind, oid = fields.split(b" ")
        if mode not in {b"100644", b"100755"}:
            raise ValueError("committed backlog approval contains a non-regular file")
        if kind == b"blob":
            selected[raw.decode("utf-8", errors="surrogateescape")] = oid
    if not selected:
        return {}
    objects = subprocess.run(
        ["git", "--no-replace-objects", "cat-file", "--batch"],
        cwd=project, capture_output=True, check=False,
        input=b"".join(oid + b"\n" for oid in selected.values()),
    )
    if objects.returncode:
        raise ValueError("committed backlog approval objects are unreadable")
    offset = 0
    sources = {}
    for path, oid in selected.items():
        end = objects.stdout.index(b"\n", offset)
        actual, kind, size_text = objects.stdout[offset:end].split(b" ")
        size = int(size_text)
        start = end + 1
        offset = start + size + 1
        if actual != oid or kind != b"blob" or size < 0 or objects.stdout[start + size:offset] != b"\n":
            raise ValueError("committed backlog approval batch response is invalid")
        sources[path] = objects.stdout[start:start + size]
    if offset != len(objects.stdout):
        raise ValueError("committed backlog approval batch has trailing data")
    return sources


def history_project(docs: Path) -> Path | None:
    return next((parent for parent in (docs, *docs.parents)
                 if (parent / ".git").exists()), None)


def history_listing(project: Path, commit: str, relative: str) -> list[bytes] | None:
    """Return the tree rows of one path at one commit, or None when Git cannot list it."""
    object_id = git_object_id(project, commit)
    if object_id is None:
        return None
    key = ("listing", project.resolve(), object_id, relative)
    if key not in _GIT_OBJECT_READS:
        listing = subprocess.run(
            ["git", "--no-replace-objects", "--literal-pathspecs", "ls-tree", "-z",
             object_id, "--", relative], cwd=project, capture_output=True, check=False)
        if listing.returncode:
            return None
        _GIT_OBJECT_READS[key] = tuple(row for row in listing.stdout.split(b"\0") if row)
    return list(_GIT_OBJECT_READS[key])


def history_blob(project: Path, commit: str, relative: str) -> bytes | None:
    rows = history_listing(project, commit, relative)
    if rows is None or len(rows) != 1:
        return None
    fields, name = rows[0].split(b"\t", 1)
    mode, kind, oid = fields.split(b" ")
    if mode not in {b"100644", b"100755"} or kind != b"blob" or name != relative.encode("utf-8"):
        return None
    key = ("blob", project.resolve(), oid)
    if key not in _GIT_OBJECT_READS:
        shown = subprocess.run(["git", "--no-replace-objects", "cat-file", "blob", oid.decode("ascii")],
                               cwd=project, capture_output=True, check=False)
        if shown.returncode:
            return None
        _GIT_OBJECT_READS[key] = shown.stdout
    return _GIT_OBJECT_READS[key]


def approved_history_sources(project: Path, docs: Path, commit: str) -> dict[Path, bytes] | None:
    """Prove the complete committed approval boundary before using its sources."""
    def read():
        sources = committed_approval_sources(project, docs, commit)
        root = sources.get(docs / "backlog/backlog.md")
        if root is None:
            return None
        props, _body = parse_front_matter_text(root.decode("utf-8"))
        if props.get("status") != "approved" or props.get("source_hash") != digest_text(root.decode("utf-8")):
            return None
        canonical_paths = re.compile(
            r"backlog/(?:backlog\.md|reviews/round-[0-9]+-backlog-review\.md|"
            r"epics/[^/]+/(?:epic\.md|reviews/round-[0-9]+-epic-review\.md|"
            r"stories/[^/]+/(?:story|test-plan)\.md))")
        notes = {}
        for path, content in sources.items():
            relative = path.relative_to(docs).as_posix()
            if not canonical_paths.fullmatch(relative):
                continue
            text = content.decode("utf-8")
            note_props, _body = parse_front_matter_text(text)
            notes[path] = (text, note_props)
        groups = {}
        for path, (_text, note_props) in notes.items():
            if note_props.get("type") in {"backlog-review", "epic-review"}:
                errors = []
                number = round_number(path, note_props, note_props["type"], errors)
                if errors:
                    return None
                groups.setdefault(path.parent, []).append({"path": path.relative_to(docs).as_posix(),
                                                            "props": note_props, "round": number})
        group_record = {"backlog_reviews": [], "epics": [{"reviews": reviews} for reviews in groups.values()]}
        historical = historical_unapproved_review_paths(group_record, docs)
        manifest = {}
        for path, (text, note_props) in notes.items():
            relative = path.relative_to(docs).as_posix()
            expected_status = "planned" if path.name == "story.md" else "approved"
            if path in historical:
                errors = status_findings(note_props, note_props["type"], relative, backlog_contract())
                if errors:
                    return None
            else:
                if note_props.get("status") != expected_status:
                    return None
                if note_props.get("source_hash") != digest_text(text) or not note_props.get("approved_at_utc"):
                    return None
            manifest[relative] = digest_text(text)
        payload = json.dumps(manifest, sort_keys=True, ensure_ascii=False,
                             separators=(",", ":")).encode("utf-8")
        if props.get("package_hash") != "sha256:" + hashlib.sha256(payload).hexdigest():
            return None
        return sources
    try:
        return session_read(("approved-history", project, docs, commit), read)
    except (OSError, ValueError, UnicodeError):
        return None


def history_commits(project: Path, path: Path, needle: str = "") -> list[str]:
    command = ["git", "--no-replace-objects", "--literal-pathspecs", "log", "--format=%H"]
    if needle:
        command.extend(["-S", needle])
    command.extend(["--", path.relative_to(project).as_posix()])
    result = subprocess.run(command, cwd=project, capture_output=True, text=True, check=False)
    commits = result.stdout.split() if not result.returncode else []
    # %H prints full object ids, which git_object_id would resolve to themselves.
    repository = project.resolve()
    _GIT_OBJECT_READS.update({("object-id", repository, commit): commit for commit in commits})
    return commits


def historical_source_approval(docs: Path, target: str, label: str, status: str) -> bool:
    """An unchanged committed Story/Test Plan keeps its approved evidence history.

    The target is a superseded Solution Design or System Architecture note; under
    system-architecture/ only decisions carry that status. It counts when the
    commit that approved the Story's or Test Plan's exact bytes held it approved
    or accepted.
    """
    if status != "superseded" or not target.startswith(("solution-design/", "system-architecture/")):
        return False
    owner = docs / label.split(" ", 1)[0]
    if not owner.is_file() or owner.name not in {"story.md", "test-plan.md"}:
        return False
    props, _body = parse_front_matter(owner)
    if props.get("status") not in {"planned", "approved"} or approval_stamp_findings(owner, docs):
        return False
    project = history_project(docs)
    if project is None:
        return False
    def read():
        head = session_read(("head-approvals", project, docs),
                            lambda: committed_approval_sources(project, docs)).get(owner)
        if head is None or canonical_text(head.decode("utf-8")) != canonical(owner):
            return False
        for commit in history_commits(project, owner, str(props["source_hash"])):
            sources = approved_history_sources(project, docs, commit)
            original = sources.get(owner) if sources else None
            if original is None or digest_text(original.decode("utf-8")) != props["source_hash"]:
                continue
            source = history_blob(project, commit, (docs / f"{target}.md").relative_to(project).as_posix())
            if source is None:
                continue
            historical_props, _body = parse_front_matter_text(source.decode("utf-8"))
            if historical_props.get("status") in {"approved", "accepted"}:
                return True
        return False
    try:
        return session_read(("historical-source", docs, owner, target), read)
    except (OSError, ValueError, UnicodeError):
        return False


def prior_approved_universe(docs: Path) -> set[str] | None:
    """Read the BA universe at the last hash-verified committed backlog approval."""
    project = history_project(docs)
    if project is None:
        return None
    def read():
        for commit in history_commits(project, docs / "backlog/backlog.md"):
            sources = approved_history_sources(project, docs, commit)
            if sources is None:
                continue
            prior = set()
            for path in sorted((docs / "business-analysis").glob("*/_generated/registry.json")):
                relative = path.relative_to(project).as_posix()
                if history_listing(project, commit, relative) == []:
                    # A topic registry created after that approval approved nothing then.
                    continue
                content = history_blob(project, commit, relative)
                if content is None:
                    return None
                registry = json.loads(content.decode("utf-8"))
                ids = registry.get("ids", {})
                if not isinstance(ids, dict):
                    return None
                for identifier, entry in ids.items():
                    if isinstance(entry, dict) and entry.get("doc_status") == "approved" and entry.get("row_status", "active") == "active":
                        prior.add(f"{path.parent.parent.name}:{identifier}")
            return prior
        return None
    try:
        return session_read(("prior-universe", docs), read)
    except (OSError, ValueError, UnicodeError):
        return None


def preserved_approval_sources(
    record: dict, docs: Path, *, allow_new_approvals: bool = False,
) -> tuple[dict[Path, bytes], list[str]]:
    """Keep intact approvals; an existing review can only change in a new round."""
    reviews = {docs / review["path"] for review in record["backlog_reviews"]}
    reviews.update(docs / review["path"] for epic in record["epics"] for review in epic["reviews"])
    project = next((parent for parent in (docs, *docs.parents) if (parent / ".git").exists()), None)
    preserved, errors = {}, []
    committed = {}
    historical = historical_unapproved_review_paths(record, docs)
    if project is not None:
        try:
            committed = committed_approval_sources(project, docs)
        except (OSError, ValueError) as exc:
            errors.append(str(exc))
        for path, original in committed.items():
            relative = path.relative_to(project).as_posix()
            if path in reviews or not re.fullmatch(
                r"(?:reviews/round-[0-9]+-backlog-review|epics/[^/]+/reviews/round-[0-9]+-epic-review)\.md",
                path.relative_to(docs / "backlog").as_posix(),
            ):
                continue
            try:
                head_props, _body = parse_front_matter_text(original.decode("utf-8"))
            except UnicodeError:
                errors.append(f"{relative} committed review approval is unreadable")
                continue
            if head_props.get("source_hash") or head_props.get("approved_at_utc"):
                errors.append(f"{relative} prior review approval was removed or renamed")
    for path in package_paths(record, docs):
        props, _body = parse_front_matter(path)
        stamped = bool(props.get("source_hash") or props.get("approved_at_utc"))
        head = committed.get(path)
        try:
            head_props = parse_front_matter_text(head.decode("utf-8"))[0] if head is not None else {}
        except UnicodeError:
            errors.append(f"{path.relative_to(docs).as_posix()} committed approval source is unreadable")
            continue
        head_stamped = bool(head_props.get("source_hash") or head_props.get("approved_at_utc"))
        if path in reviews and (head_stamped or (stamped and not allow_new_approvals)):
            if not head_stamped or head != path.read_bytes():
                errors.append(f"{path.relative_to(docs).as_posix()} prior review approval must remain byte-exact in HEAD; create a new review round")
            errors.extend(approval_stamp_findings(path, docs))
        if path in historical:
            preserved[path] = path.read_bytes()
            continue
        unchanged = (
            props.get("source_hash") == head_props.get("source_hash")
            and props.get("approved_at_utc") == head_props.get("approved_at_utc")
        )
        if stamped and unchanged and not approval_stamp_findings(path, docs) and (
            props.get("status") in {"approved", "planned"} or path in reviews
        ):
            preserved[path] = path.read_bytes()
    return preserved, sorted(set(errors))


def approval_findings(record: dict, docs: Path) -> list[str]:
    errors: list[str] = []
    if record["backlog"]["props"].get("status") != "approved":
        errors.append("backlog status is not approved")
    root_review = latest(record["backlog_reviews"])
    if root_review is None or root_review["props"].get("status") != "approved":
        errors.append("latest cross-epic backlog review is not approved")
    for epic in record["epics"]:
        if epic["props"].get("status") != "approved":
            errors.append(f"{epic['id']} epic is not approved")
        review = latest(epic["reviews"])
        if review is None or review["props"].get("status") != "approved":
            errors.append(f"{epic['id']} latest epic review is not approved")
        for story in epic["stories"]:
            if story["props"].get("status") != "planned":
                errors.append(f"{story['id']} must remain planned at backlog approval")
            if story["test_props"].get("status") != "approved":
                errors.append(f"{story['id']} test plan is not approved")
    paths = package_paths(record, docs)
    historical = historical_unapproved_review_paths(record, docs)
    for path in paths:
        if path not in historical:
            errors.extend(approval_stamp_findings(path, docs))
    expected_package = package_digest(docs, paths)
    if record["backlog"]["props"].get("package_hash") != expected_package:
        errors.append("backlog approved package_hash is stale")
    return sorted(set(errors))


