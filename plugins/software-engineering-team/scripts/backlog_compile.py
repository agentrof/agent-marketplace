def planning_source_status_and_type(docs: Path, target: str, label: str,
                                    errors: list[str]) -> tuple[str, str]:
    path = docs / f"{target}.md"
    status, type_name = note_status_and_type(path)
    if target != "solution-design/landscape":
        return status, type_name
    props, _body = parse_front_matter(path)
    raw_version = props.get("topology_contract_version", 0)
    if (isinstance(raw_version, bool)
            or not isinstance(raw_version, (int, str))
            or not re.fullmatch(r"[+-]?\d+", str(raw_version))):
        errors.append(f"{label} Solution topology_contract_version must be an integer")
        return "", type_name
    version = int(raw_version)
    if version < 3:
        # Preserve the existing document-status contract for legacy notes.
        return status, type_name
    if type_name != "landscape":
        errors.append(f"{label} canonical Solution package must have type: landscape")
        return "", type_name
    receipt, package_errors = stage_package.verify(
        docs, "solution-design", target,
        require_strict_current=True, require_committed=True)
    errors.extend(f"{label}: {error}" for error in package_errors)
    return (str(receipt["status"]) if receipt and not package_errors else ""), type_name


def validate_criterion_ref(docs: Path, value: str, label: str,
                           errors: list[str]) -> tuple[str, str, str] | None:
    parsed = read_link(docs, value, label, errors)
    if parsed is None:
        return None
    target, _anchor, alias = parsed
    identity = BA_ID_RE.fullmatch(alias)
    if identity is None:
        errors.append(f"{label} alias must be <space>:<AC-or-BR-id>: {alias}")
        return parsed
    space = identity.group("space")
    criterion_id = identity.group("id")
    prefix = f"business-analysis/{space}/"
    if not target.startswith(prefix):
        errors.append(f"{label} target does not belong to BA space {space}: {target}")
        return parsed
    registry_path = docs / "business-analysis" / space / "_generated" / "registry.json"
    try:
        registry = session_read(
            ("ba-registry", registry_path),
            lambda: json.loads(registry_path.read_text(encoding="utf-8")),
        )
        entry = (registry.get("ids") or {}).get(criterion_id)
    except (OSError, json.JSONDecodeError):
        entry = None
    if not isinstance(entry, dict):
        errors.append(f"{label} criterion is absent from approved BA registry: {alias}")
        return parsed
    expected = prefix + str(entry.get("doc", ""))
    if expected.removesuffix(".md") != target:
        errors.append(f"{label} criterion {alias} belongs to {expected}, not {target}")
    if entry.get("doc_status") != "approved":
        errors.append(f"{label} criterion owner is not approved: {alias}")
    status, type_name = note_status_and_type(docs / f"{target}.md")
    if status != "approved" or type_name not in {"acceptance-set", "rule-set"}:
        errors.append(f"{label} must target an approved acceptance-set or rule-set: {target}")
    return parsed


def validate_upstream_ref(docs: Path, value: str, label: str,
                          roots: tuple[str, ...], allowed_types: set[str],
                          errors: list[str]) -> tuple[str, str, str] | None:
    parsed = read_link(docs, value, label, errors)
    if parsed is None:
        return None
    target, _anchor, _alias = parsed
    if not target.startswith(roots):
        errors.append(f"{label} targets the wrong vault subtree: {target}")
        return parsed
    status, type_name = planning_source_status_and_type(docs, target, label, errors)
    if status != "approved" and not historical_source_approval(docs, target, label, status):
        errors.append(f"{label} target is not approved: {target}")
    if allowed_types and type_name not in allowed_types:
        errors.append(f"{label} targets unsupported type {type_name}: {target}")
    return parsed


def planning_package_findings(
    docs: Path, props: dict, path: str, *, allow_historical: bool = False,
) -> tuple[str, list[str], list[str]]:
    """Validate the optional Requirement/manual planning contract.

    Existing backlog packages may omit ``planning_mode`` while they are being
    authored. Once declared, the mode makes the upstream package boundary
    explicit and fail-closed.
    """
    mode = str(props.get("planning_mode", "")).strip().casefold()
    errors: list[str] = []
    absent = values(props, "absent_input_stages")
    absence_declared = bool({"input_contract", "absent_input_stages"}.intersection(props))
    if absence_declared and mode != "requirement":
        errors.append(f"{path} absent inputs are supported only in Requirement mode")
    refs = values(props, "input_package_refs")
    if mode not in {"", "manual", "requirement"}:
        errors.append(f"{path} planning_mode must be manual or requirement")
        return mode, refs, errors
    if not mode:
        if props.get("status") == "approved" or props.get("legacy_contract"):
            # Read-only historical backlog packages remain inspectable. Their
            # first begin-revision must select a modern intake mode.
            return mode, refs, errors
        errors.append(f"{path} planning_mode is mandatory for a new or revised backlog")
        return mode, refs, errors
    if mode == "manual":
        if props.get("requirement_ref") or props.get("implements"):
            errors.append(f"{path} manual planning must not declare a Requirement")
        bindings = values(props, "input_bindings")
        if bindings:
            rows, binding_errors = verify_input_bindings(
                docs, bindings, path, allow_historical=allow_historical)
            errors.extend(binding_errors)
            refs = [reference for _stage, reference, _digest in rows]
            expected = grouped_input_references(rows)
        else:
            # Mode-bearing historical packages remain readable. New manual
            # packages must carry compiler-owned hash bindings.
            if props.get("status") == "approved" or props.get("legacy_contract"):
                expected = {}
                for value in refs:
                    target = value[2:-2].split("|", 1)[0] if value.startswith("[[") and value.endswith("]]" ) else value
                    stage = manual_stage_for_ref(target)
                    if not stage:
                        errors.append(f"{path} input package targets an unsupported subtree: {target}")
                        continue
                    expected.setdefault(stage, []).append(target)
                    _receipt, verify_errors = stage_package.verify(docs, stage, target,
                                                                    require_committed=True,
                                                                    allow_historical=allow_historical)
                    errors.extend(f"{path} input package: {error}"
                                  for error in verify_errors)
            else:
                expected = {}
                errors.append(f"{path} manual planning needs compiler-owned input_bindings")
        errors.extend(input_family_findings(
            expected, docs, path, "manual", allow_historical=allow_historical))
    elif mode == "requirement":
        requirement_path = None
        requirement_receipts: dict[str, list[tuple[str, str]]] = {}
        requirement = str(props.get("requirement_ref", "")).strip()
        if not requirement:
            errors.append(f"{path} requirement planning needs requirement_ref")
        elif not re.fullmatch(r"REQ-[0-9]{3,}", requirement):
            errors.append(f"{path} requirement_ref must be REQ-###")
        else:
            requirement_paths = sorted((docs / "requirements").glob(
                f"req-{int(requirement[4:]):03d}-*.md"))
            if len(requirement_paths) != 1:
                errors.append(f"{path} requirement_ref is not uniquely resolvable: {requirement}")
            else:
                requirement_path = requirement_paths[0]
                status, type_name = note_status_and_type(requirement_paths[0])
                if type_name != "requirement" or status != "approved":
                    errors.append(f"{path} requirement_ref is not an approved Requirement: {requirement}")
                else:
                    if not allow_historical:
                        routing = requirement_route.route(docs, requirement)
                        if routing.get("action") != "backlog":
                            errors.append(f"{path} Requirement is not ready for backlog: {routing.get('action', 'requirement')}")
                    try:
                        req_props, req_body = requirement_compile.split_note(requirement_paths[0])
                        results = requirement_compile.stage_results(req_body)
                        for stage, disposition, _refs, _why in requirement_compile.impact_rows(req_body):
                            if disposition == "not_applicable":
                                continue
                            receipts = results.get(stage, [])
                            requirement_receipts[stage] = sorted(
                                (str(result_ref), str(result_hash)) for result_ref, result_hash in receipts)
                            if stage != "experience-design" and len(receipts) != 1:
                                errors.append(f"{path} Requirement {stage} needs exactly one receipt")
                            if stage == "experience-design" and not requirement_compile.valid_experience_receipt_refs(
                                    [row[0] for row in receipts], docs,
                                    allow_historical=allow_historical):
                                errors.append(
                                    f"{path} Requirement experience-design needs one application plus its exact process receipts, "
                                    "or only the application when it is verified empty"
                                )
                            for result_ref, result_hash in receipts:
                                _receipt, verify_errors = stage_package.verify(
                                    docs, stage, result_ref, result_hash,
                                    require_committed=True,
                                    allow_historical=allow_historical)
                                errors.extend(f"{path} Requirement {stage} receipt: {error}" for error in verify_errors)
                    except (OSError, ValueError) as exc:
                        errors.append(f"{path} cannot read Requirement Stage Results: {exc}")
        # The backlog pins every input family itself. A Requirement binds only
        # the stages it changes or reuses; the rest would otherwise go unpinned.
        bindings = values(props, "input_bindings")
        if bindings:
            rows, binding_errors = verify_input_bindings(
                docs, bindings, path, allow_historical=allow_historical)
            errors.extend(binding_errors)
            refs = [reference for _stage, reference, _digest in rows]
            errors.extend(input_family_findings(
                grouped_input_references(rows), docs, path, "requirement",
                allow_historical=allow_historical, absent_stages=absent))
            if absence_declared:
                try:
                    errors.extend(f"{path} {error}" for error in backlog_input_policy.absence_findings(
                        docs, props, requirement_path, {stage for stage, _ref, _hash in rows},
                        backlog_contract()["applicable_inputs"], allow_historical=allow_historical))
                except (OSError, ValueError) as exc:
                    errors.append(f"{path} absent input evidence is unreadable: {exc}")
            for stage, receipts in requirement_receipts.items():
                bound = sorted((reference, digest) for bound_stage, reference, digest in rows
                               if bound_stage == stage)
                if bound != receipts:
                    errors.append(f"{path} {stage} input binding must equal {requirement} Stage Results")
        elif not (props.get("status") == "approved" or props.get("legacy_contract")):
            errors.append(f"{path} requirement planning needs compiler-owned input_bindings")
        if absence_declared and not bindings:
            errors.append(f"{path} absent inputs still require approved BA and Solution bindings")
    return mode, refs, errors


INPUT_STAGES = ("business-analysis", "solution-design", "design-system", "experience-design")


def verify_input_bindings(docs: Path, bindings: list[str], path: str, *,
                          allow_historical: bool = False) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Parse compiler-owned stage|ref|sha256 bindings and verify each receipt."""
    rows: list[tuple[str, str, str]] = []
    errors: list[str] = []
    for binding in bindings:
        stage, separator, remainder = binding.partition("|")
        reference, separator2, digest = remainder.partition("|")
        if (not separator or not separator2 or not reference
                or not digest.startswith("sha256:")):
            errors.append(f"{path} input_binding must be stage|exact-ref|sha256")
            continue
        if stage not in INPUT_STAGES:
            errors.append(f"{path} input_binding has unsupported stage {stage}")
            continue
        rows.append((stage, reference, digest))
        _receipt, verify_errors = stage_package.verify(
            docs, stage, reference, digest, require_committed=True,
            require_strict_current=not allow_historical,
            allow_historical=allow_historical)
        errors.extend(f"{path} input binding: {error}" for error in verify_errors)
    return rows, errors


def grouped_input_references(rows: list[tuple[str, str, str]]) -> dict[str, list[str]]:
    grouped: dict[str, list[str]] = {}
    for stage, reference, _digest in rows:
        grouped.setdefault(stage, []).append(reference)
    return grouped


def input_family_findings(expected: dict[str, list[str]], docs: Path, path: str,
                          mode: str, *, allow_historical: bool = False,
                          absent_stages: list[str] | tuple[str, ...] = ()) -> list[str]:
    """Require one BA, Solution and Design package plus one complete Experience set."""
    errors = []
    for stage, references in expected.items():
        if stage != "experience-design" and len(references) != 1:
            errors.append(f"{path} {mode} planning needs exactly one {stage} input package")
            continue
        if stage == "experience-design" and not requirement_compile.valid_experience_receipt_refs(
                references, docs, allow_historical=allow_historical):
            errors.append(
                f"{path} {mode} planning needs one Experience application plus its exact process packages, "
                "or only the application when it is verified empty"
            )
    missing = sorted(set(INPUT_STAGES) - set(expected) - set(absent_stages))
    if missing:
        errors.append(f"{path} {mode} planning is missing input packages: {', '.join(missing)}")
    return errors


def manual_stage_for_ref(reference: str) -> str:
    if reference.startswith("business-analysis/"):
        return "business-analysis"
    if reference == "solution-design/landscape":
        return "solution-design"
    if reference == "design-system/MASTER":
        return "design-system"
    if re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*@r[1-9][0-9]*", reference):
        return "experience-design"
    return ""


def resolve_manual_input_bindings(docs: Path, raw_refs: list[str],
                                  label: str) -> tuple[list[str], list[str]]:
    """Resolve user selections once and persist only exact receipt hashes."""
    errors: list[str] = []
    rows: list[tuple[str, str, str]] = []
    for raw in raw_refs:
        target = raw.strip()
        if target.startswith("[[") and target.endswith("]]" ):
            target = target[2:-2].split("|", 1)[0].split("#", 1)[0]
        stage = manual_stage_for_ref(target)
        if not stage:
            errors.append(f"{label} input package targets an unsupported subtree: {target}")
            continue
        receipt, verify_errors = stage_package.verify(docs, stage, target,
                                                       require_committed=True,
                                                       require_strict_current=True)
        errors.extend(f"{label} input package: {error}" for error in verify_errors)
        if receipt is not None and not verify_errors:
            rows.append((stage, str(receipt["result_ref"]), str(receipt["package_hash"])))
    grouped: dict[str, list[tuple[str, str, str]]] = {}
    for row in rows:
        grouped.setdefault(row[0], []).append(row)
    for stage in ("business-analysis", "solution-design", "design-system"):
        if len(grouped.get(stage, [])) != 1:
            errors.append(f"{label} manual planning needs exactly one {stage} input package")
    experience_refs = [row[1] for row in grouped.get("experience-design", [])]
    if not requirement_compile.valid_experience_receipt_refs(
            experience_refs, docs):
        errors.append(
            f"{label} manual planning needs one Experience application plus its exact process packages, "
            "or only the application when it is verified empty"
        )
    if len(rows) != len(set(rows)):
        errors.append(f"{label} input package selection contains duplicates")
    return [f"{stage}|{ref}|{digest}" for stage, ref, digest in sorted(rows)], sorted(set(errors))


def requirement_input_bindings(docs: Path, requirement_ref: str, carried: list[str],
                               declared: list[str], label: str, *,
                               absent_stages: list[str] | tuple[str, ...] = ()) -> tuple[list[str], list[str]]:
    """Pin all four input families for a Requirement-mode backlog.

    Stages the Requirement changes or reuses bind its Stage Results receipts.
    A stage it marks not_applicable keeps the backlog's previous binding or
    takes an explicitly declared --input-ref, so a Requirement that does not
    touch a package never leaves the backlog unpinned against it.
    """
    if not re.fullmatch(r"REQ-[0-9]{3,}", requirement_ref):
        return [], [f"{label} requirement_ref must be REQ-###"]
    paths = sorted((docs / "requirements").glob(f"req-{int(requirement_ref[4:]):03d}-*.md"))
    if len(paths) != 1:
        return [], [f"{label} requirement_ref is not uniquely resolvable: {requirement_ref}"]
    try:
        _props, body = requirement_compile.split_note(paths[0])
        results = requirement_compile.stage_results(body)
        dispositions = {stage: disposition for stage, disposition, _refs, _why
                        in requirement_compile.impact_rows(body)}
    except (OSError, ValueError) as exc:
        return [], [f"{label} cannot read Requirement Stage Results: {exc}"]
    errors: list[str] = []
    declared_rows: list[tuple[str, str, str]] = []
    for raw in declared:
        target = raw.strip()
        if target.startswith("[[") and target.endswith("]]"):
            target = target[2:-2].split("|", 1)[0].split("#", 1)[0]
        stage = manual_stage_for_ref(target)
        if not stage:
            errors.append(f"{label} input package targets an unsupported subtree: {target}")
            continue
        if dispositions.get(stage) != "not_applicable":
            errors.append(f"{label} --input-ref may pin only a stage {requirement_ref} marks "
                          f"not_applicable; {stage} binds its Stage Results")
            continue
        receipt, verify_errors = stage_package.verify(docs, stage, target,
                                                       require_committed=True,
                                                       require_strict_current=True)
        errors.extend(f"{label} input package: {error}" for error in verify_errors)
        if receipt is not None and not verify_errors:
            declared_rows.append((stage, str(receipt["result_ref"]), str(receipt["package_hash"])))
    carried_rows = []
    for binding in carried:
        stage, _separator, remainder = binding.partition("|")
        reference, _separator, digest = remainder.partition("|")
        carried_rows.append((stage, reference, digest))
    rows: list[tuple[str, str, str]] = []
    for stage in INPUT_STAGES:
        if stage in absent_stages:
            if dispositions.get(stage) != "not_applicable":
                errors.append(f"{label} {stage} cannot be absent unless not_applicable")
            if any(row[0] == stage for row in [*carried_rows, *declared_rows]) or results.get(stage):
                errors.append(f"{label} {stage} has an existing binding and cannot become absent")
            continue
        if dispositions.get(stage, "not_applicable") != "not_applicable":
            rows.extend((stage, str(reference), str(digest))
                        for reference, digest in results.get(stage, []))
            continue
        chosen = ([row for row in declared_rows if row[0] == stage]
                  or [row for row in carried_rows if row[0] == stage])
        if not chosen:
            errors.append(f"{label} requirement planning needs an input binding for {stage}, "
                          f"which {requirement_ref} marks not_applicable; pass --input-ref")
        rows.extend(chosen)
    return [f"{stage}|{ref}|{digest}" for stage, ref, digest in sorted(set(rows))], sorted(set(errors))


def validate_experience_ref(docs: Path, value: str, label: str,
                            errors: list[str], *, require_current: bool = True) -> None:
    """Resolve a living ``experience:ID@rN`` ref through current or history."""
    match = re.fullmatch(
        r"([a-z0-9]+(?:-[a-z0-9]+)*):(JRN|FLW|SCR|STA|TRN)-[0-9]{3,}@r([1-9][0-9]*)",
        value,
    )
    if match is None:
        errors.append(f"{label} must be an exact <experience>:<stable-id>@rN reference")
        return
    identifier = match.group(1)
    stable_id = value.split(":", 1)[1].split("@", 1)[0]
    revision = int(match.group(3))
    experience_root = docs / "experience-design"
    if require_current:
        try:
            _application, application_findings = current_experience_application(
                experience_root
            )
        except (ImportError, OSError, ValueError) as exc:
            errors.append(f"{label} canonical application cannot be verified: {exc}")
            return
        if application_findings:
            errors.extend(
                f"{label} canonical application: {finding}"
                for finding in application_findings
            )
            return
    try:
        import experience_compile
        package = experience_compile.resolve_package(experience_root, identifier)
    except (ImportError, ValueError) as exc:
        errors.append(f"{label} owning Experience is not uniquely resolvable: {identifier} ({exc})")
        return
    if package is None:
        errors.append(f"{label} owning Experience is not uniquely resolvable: {identifier}")
        return
    try:
        props, _body = parse_front_matter(package / "experience.md")
    except OSError as exc:
        errors.append(f"{label} owning Experience registry is missing: {exc}")
        return
    if require_current:
        try:
            registry, findings = current_experience_package(package)
        except (OSError, ValueError) as exc:
            errors.append(f"{label} owning Experience registry is missing: {exc}")
            return
        if findings:
            errors.extend(
                f"{label} owning Experience: {finding}" for finding in findings
            )
            return
        current_owner = (
            props.get("status") == "approved" and identifier == package.name
        )
        current_records = [
            item for item in registry.get("records", [])
            if isinstance(item, dict)
            and item.get("id") == stable_id
            and item.get("revision") == revision
        ] if current_owner else []
        if (not current_owner
                or props.get("registry_hash") != registry.get("registry_hash")):
            errors.append(f"{label} owning Experience is not approved/current")
            return
        if len(current_records) != 1 or current_records[0].get("record_state") != "active":
            errors.append(f"{label} does not resolve to one active effective record")
        return
    if not stage_package.historical_package_tree_is_regular(package):
        errors.append(
            f"{label} owning Experience history contains an unsafe path alias"
        )
        return
    try:
        import experience_application_check
        application_rows, application_findings = session_read(
            ("application-ledger", experience_root),
            lambda: experience_application_check.verified_application_ledger(
                experience_root,
            ),
        )
    except (ImportError, OSError, ValueError) as exc:
        errors.append(f"{label} application history cannot be verified: {exc}")
        return
    if application_findings:
        errors.extend(
            f"{label} application history: {finding}"
            for finding in application_findings
        )
        return
    published_by_ref: dict[str, str] = {}
    for application in application_rows:
        for package_row in application.get("packages", []):
            if not isinstance(package_row, dict):
                continue
            result_ref = str(package_row.get("result_ref", ""))
            package_hash = str(package_row.get("package_hash", ""))
            if (
                result_ref in published_by_ref
                and published_by_ref[result_ref] != package_hash
            ):
                errors.append(
                    f"{label} application history reuses a process receipt with "
                    "conflicting immutable hashes"
                )
                return
            published_by_ref[result_ref] = package_hash
    published = set(published_by_ref.items())
    current_revision = props.get("revision")
    if type(current_revision) is not int or current_revision < 1:
        errors.append(f"{label} owning Experience has an invalid revision")
        return
    history, history_findings = session_read(
        ("process-ledger", package, current_revision),
        lambda: experience_compile.validate_process_ledger(
            package, current_revision,
        ),
    )
    if history_findings:
        errors.extend(f"{label} owning Experience history: {finding}"
                      for finding in history_findings)
        return
    registries = list(history)
    if props.get("status") == "approved":
        try:
            current, current_findings = session_read(
                ("stale-input-package", package),
                lambda: experience_compile.compile_package(
                    package, True, allow_stale_inputs=True,
                ),
            )
        except (OSError, ValueError) as exc:
            errors.append(f"{label} owning Experience registry is missing: {exc}")
            return
        if current_findings:
            errors.extend(
                f"{label} owning Experience: {finding}"
                for finding in current_findings
            )
            return
        registries.append(current)
    record_receipts = [
        receipt for receipt in registries
        if receipt.get("experience_id") == identifier
        and (
            f"{identifier}@r{receipt.get('package_revision')}",
            receipt.get("package_hash"),
        ) in published
        and any(
            isinstance(item, dict)
            and item.get("id") == stable_id
            and item.get("revision") == revision
            for item in receipt.get("records", [])
        )
    ]
    if not record_receipts:
        errors.append(f"{label} does not resolve through approved Experience history")
        return


def headings(body: str) -> set[str]:
    return {match.group(1).strip() for match in
            re.finditer(r"^##\s+(.+?)\s*$", body, flags=re.MULTILINE)}


def raw_section(body: str, title: str) -> str:
    """Return a section's text as written, its first line's indentation kept."""
    match = re.search(rf"^##\s+{re.escape(title)}\s*$", body,
                      flags=re.MULTILINE)
    if not match:
        return ""
    following = re.search(r"^##\s+", body[match.end():], flags=re.MULTILINE)
    end = match.end() + following.start() if following else len(body)
    return body[match.end():end]


def section(body: str, title: str) -> str:
    return raw_section(body, title).strip()


def required_section_findings(body: str, required: list[str], path: str) -> list[str]:
    present = headings(body)
    errors = [f"{path} is missing required section: {title}"
              for title in required if title not in present]
    for title in required:
        if title in present and not section(body, title):
            errors.append(f"{path} required section is empty: {title}")
    return errors


def navigation_only_sections(body: str, required: list[str]) -> list[str]:
    """Return the required sections whose only text is the navigation block.

    Navigation has no heading of its own, so section() reads it as the body of
    the last section, and required_section_findings never sees that section as
    empty.
    """
    return [title for title in required
            if (content := section(body, title)) and not content.split(NAV_MARKER, 1)[0].strip()]


def meaningful_text(value: str) -> bool:
    normalized = re.sub(r"\s+", " ", value).strip().casefold()
    if (not normalized or normalized in REVIEW_PLACEHOLDERS
            or re.search(r"<!--\s*todo\b|\b(?:todo|tbd)\s*:", normalized)):
        return False
    words = re.findall(r"[^\W_]+", normalized, flags=re.UNICODE)
    return (REVIEW_PLACEHOLDER_RE.fullmatch(normalized) is None
            and len(words) >= 5)


def normalized_text(value: object) -> str:
    return re.sub(r"\s+", " ", str(value)).strip().casefold()


def generic_review_text(value: str) -> bool:
    """Reject a generic verdict, not a concrete sentence containing one."""
    normalized = re.sub(r"\s+", " ", value).strip()
    normalized = re.sub(r"\[\[[^\[\]\n]+\]\]", "", normalized).strip()
    normalized = re.sub(
        r"^(?:says|states|records(?: that)?)\s+", "", normalized,
        flags=re.IGNORECASE,
    )
    return GENERIC_REVIEW_RE.fullmatch(normalized) is not None


def review_section_findings(body: str, required: list[str], path: str,
                            docs: Path) -> list[str]:
    errors = required_section_findings(body, required, path)
    for title in required:
        content = section(body, title)
        if title == "Deferred Criteria":
            continue
        evidence = re.search(
            rf"(?m)^Evidence \[{re.escape(title)}\]:\s*(\S.+?)\s*$",
            content,
        )
        conclusion = re.search(
            rf"(?m)^Conclusion \[{re.escape(title)}\]:\s*(\S.+?)\s*$",
            content,
        )
        if (evidence is None or not meaningful_text(evidence.group(1))
                or generic_review_text(evidence.group(1))):
            errors.append(
                f"{path} review section needs section-specific "
                f"Evidence [{title}]"
            )
        else:
            links = re.findall(r"\[\[[^\[\]\n]+\]\]", INLINE_CODE_RE.sub("", evidence.group(1)))
            if not links:
                errors.append(
                    f"{path} review Evidence must cite a vault note: {title}"
                )
            for value in links:
                read_link(docs, value, f"{path} {title} Evidence", errors)
        if (conclusion is None or not meaningful_text(conclusion.group(1))
                or generic_review_text(conclusion.group(1))):
            errors.append(
                f"{path} review section needs section-specific "
                f"Conclusion [{title}]"
            )
    return errors


def table_cells(line: str) -> list[str]:
    raw = line.strip()
    if not raw.startswith("|") or not raw.endswith("|"):
        return []
    cells: list[str] = []
    current: list[str] = []
    escaped = False
    for char in raw[1:-1]:
        if char == "|" and not escaped:
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(char)
        escaped = char == "\\" and not escaped
        if char != "\\":
            escaped = False
    cells.append("".join(current).strip())
    return cells


def structured_table(content: str, headers: tuple[str, ...], path: str,
                     label: str) -> tuple[list[dict[str, str]], list[str]]:
    lines = [line for line in content.splitlines() if line.strip().startswith("|")]
    if len(lines) < 2:
        return [], [f"{path} {label} must be a Markdown table"]
    actual = tuple(cell.casefold().replace(" ", "_")
                   for cell in table_cells(lines[0]))
    if actual != headers:
        return [], [f"{path} {label} columns must be: {', '.join(headers)}"]
    separator = table_cells(lines[1])
    if len(separator) != len(headers) or any(
            re.fullmatch(r":?-{3,}:?", cell) is None for cell in separator):
        return [], [f"{path} {label} has an invalid table separator"]
    rows: list[dict[str, str]] = []
    errors: list[str] = []
    for number, line in enumerate(lines[2:], 1):
        cells = table_cells(line)
        if len(cells) != len(headers):
            errors.append(f"{path} {label} row {number} has {len(cells)} cells; expected {len(headers)}")
            continue
        rows.append(dict(zip(headers, cells)))
    return rows, errors


def criterion_key(value: str) -> str:
    parsed = split_wikilink(value)
    if parsed is None:
        return ""
    alias = parsed[2]
    return alias if BA_ID_RE.fullmatch(alias) else ""


def approved_ba_universe(docs: Path,
                         errors: list[str] | None = None) -> dict[str, dict]:
    universe: dict[str, dict] = {}
    root = docs / "business-analysis"
    for registry_path in sorted(root.glob("*/_generated/registry.json")):
        space = registry_path.parent.parent.name
        try:
            registry = json.loads(registry_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            if errors is not None:
                errors.append(
                    f"{registry_path.relative_to(docs).as_posix()} is unreadable: {exc}"
                )
            continue
        ids = registry.get("ids", {}) if isinstance(registry, dict) else {}
        if not isinstance(ids, dict):
            if errors is not None:
                errors.append(
                    f"{registry_path.relative_to(docs).as_posix()} ids must be an object"
                )
            continue
        for identifier, entry in ids.items():
            if not isinstance(entry, dict) or not re.fullmatch(
                    r"(?:AC|BR)-[A-Z]{2,4}-[0-9]{3,}", str(identifier)):
                continue
            inferred_kind = str(identifier).split("-", 1)[0]
            if entry.get("kind", inferred_kind) not in {"AC", "BR"}:
                continue
            if entry.get("doc_status") != "approved":
                continue
            if entry.get("row_status", "active") != "active":
                continue
            key = f"{space}:{identifier}"
            universe[key] = {"space": space, "id": str(identifier), **entry}
    return universe


def scoped_ba_universe(docs: Path, scopes: list[str]) -> tuple[dict[str, dict],
                                                               list[str]]:
    selected: dict[str, dict] = {}
    errors: list[str] = []
    all_criteria = approved_ba_universe(docs, errors)
    if len(scopes) != len(set(scopes)):
        errors.append("backlog/backlog.md has duplicate analysis_scopes")
    for value in scopes:
        match = ANALYSIS_SCOPE_RE.fullmatch(value)
        if match is None:
            errors.append(
                "backlog/backlog.md has invalid analysis_scope; expected "
                f"<space> or <space>#domains/<path>: {value}"
            )
            continue
        space = match.group("space")
        domain = match.group("domain")
        matches = {
            key: entry for key, entry in all_criteria.items()
            if entry.get("space") == space and (
                domain is None
                or str(entry.get("doc", "")).startswith(domain + "/")
            )
        }
        if not matches:
            errors.append(
                f"backlog/backlog.md analysis_scope selects no active approved "
                f"BA criteria: {value}"
            )
        selected.update(matches)
    return selected, errors


def deferred_criteria(docs: Path, body: str,
                      path: str) -> tuple[dict[str, dict], list[str]]:
    rows, errors = structured_table(
        section(body, "Deferred Criteria"),
        ("criterion_ref", "owner_role", "reason", "revisit_trigger"),
        path, "Deferred Criteria",
    )
    result: dict[str, dict] = {}
    for number, row in enumerate(rows, 1):
        value = row["criterion_ref"]
        parsed = validate_criterion_ref(
            docs, value, f"{path} deferred criterion row {number}", errors
        )
        key = parsed[2] if parsed is not None and BA_ID_RE.fullmatch(parsed[2]) else ""
        if key in result:
            errors.append(f"{path} repeats deferred criterion: {key}")
        owner = row["owner_role"]
        if owner != "product_owner":
            errors.append(
                f"{path} deferred criterion {key or number} owner_role "
                "must be product_owner"
            )
        if not meaningful_text(row["reason"]):
            errors.append(f"{path} deferred criterion {key or number} needs a concrete reason")
        if not meaningful_text(row["revisit_trigger"]):
            errors.append(f"{path} deferred criterion {key or number} needs a concrete revisit_trigger")
        if key:
            result[key] = row
    return result, errors


def accepted_minor_findings(docs: Path, body: str, path: str,
                            contract: dict) -> list[str]:
    """Validate the optional record of minor review findings left unfixed."""
    if ACCEPTED_MINOR_FINDINGS not in headings(body):
        return []
    rows, errors = structured_table(
        section(body, ACCEPTED_MINOR_FINDINGS), ACCEPTED_MINOR_COLUMNS,
        path, ACCEPTED_MINOR_FINDINGS,
    )
    owners = list(contract["minor_finding_owner_roles"])
    seen: set[str] = set()
    for number, row in enumerate(rows, 1):
        label = f"{path} accepted minor finding {number}"
        links = re.findall(r"\[\[[^\[\]\n]+\]\]", INLINE_CODE_RE.sub("", row["finding"]))
        if not links:
            errors.append(f"{label} must cite the affected vault note")
        for value in links:
            read_link(docs, value, label, errors)
        # Link targets add path words; only the stated finding counts as text.
        description = re.sub(r"\[\[[^\[\]\n]+\]\]", " ", row["finding"])
        if not meaningful_text(description):
            errors.append(f"{label} needs a concrete finding")
        key = normalized_text(row["finding"])
        if key in seen:
            errors.append(f"{path} repeats accepted minor finding {number}")
        seen.add(key)
        if row["owner_role"] not in owners:
            errors.append(
                f"{label} owner_role must be one of: {', '.join(owners)}"
            )
        if not meaningful_text(row["reason"]):
            errors.append(f"{label} needs a concrete reason")
        if not meaningful_text(row["revisit_trigger"]):
            errors.append(f"{label} needs a concrete revisit_trigger")
    return errors


# Switch review_loop at blocking_delta keeps a review record: the findings a
# review returned with their ids and severities, the rulings of its calibration
# reader and the finding id of each accepted minor finding.
REVIEW_LOOP, RECORDING_LOOP = "review_loop", "blocking_delta"
RETURNED_FINDINGS = "Returned Findings"
RETURNED_FINDING_COLUMNS = ("finding", "severity", "description")
SEVERITY_CALIBRATION = "Severity Calibration"
SEVERITY_CALIBRATION_COLUMNS = ("finding", "claimed_severity", "calibrated_severity", "reason")
REVIEW_RECORD_SECTIONS = (RETURNED_FINDINGS, SEVERITY_CALIBRATION, ACCEPTED_MINOR_FINDINGS)
FINDING_ID_RE = re.compile(r"^[A-Z][A-Z0-9]*-[0-9]+$")
ACCEPTED_FINDING_ID_RE = re.compile(r"^([A-Z][A-Z0-9]*-[0-9]+)\s")
FINDING_SEVERITIES = ("critical", "major", "minor")
CLAIM_SEVERITIES = ("critical", "major")


def review_loop_value(docs: Path) -> str:
    """The review_loop value of the project's approved Process Policy.

    Without a policy it is the package default. A draft or invalid policy
    raises ValueError: it is refused, never read.
    """
    import process_policy

    values, _snapshot = process_policy.effective_values(docs)
    return values[REVIEW_LOOP]["value"]


def cited_statement(docs: Path, value: str, label: str, what: str,
                    errors: list[str]) -> None:
    """Require a concrete statement that cites a vault note with a resolvable wikilink."""
    links = re.findall(r"\[\[[^\[\]\n]+\]\]", INLINE_CODE_RE.sub("", value))
    if not links:
        errors.append(f"{label} {what} must cite a vault note")
    for link in links:
        read_link(docs, link, label, errors)
    if not meaningful_text(re.sub(r"\[\[[^\[\]\n]+\]\]", " ", value)):
        errors.append(f"{label} needs a concrete {what}")


def returned_findings(docs: Path, body: str, path: str) -> tuple[dict[str, str], list[str]]:
    """Read a review record's Returned Findings: each finding id with its returned severity."""
    if RETURNED_FINDINGS not in headings(body):
        return {}, []
    rows, errors = structured_table(section(body, RETURNED_FINDINGS), RETURNED_FINDING_COLUMNS,
                                    path, RETURNED_FINDINGS)
    returned: dict[str, str] = {}
    for number, row in enumerate(rows, 1):
        label = f"{path} returned finding {number}"
        identifier, severity = row["finding"], row["severity"].casefold()
        if not FINDING_ID_RE.fullmatch(identifier):
            errors.append(f"{label} finding must be an id such as F-3: {identifier or '(missing)'}")
        elif identifier in returned:
            errors.append(f"{path} returns finding {identifier} twice")
        if severity not in FINDING_SEVERITIES:
            errors.append(f"{label} severity must be critical, major or minor")
        cited_statement(docs, row["description"], label, "description", errors)
        if FINDING_ID_RE.fullmatch(identifier) and identifier not in returned:
            returned[identifier] = severity
    return returned, errors


def severity_calibration(docs: Path, body: str, path: str,
                         returned: dict[str, str] | None) -> tuple[dict[str, str], list[str]]:
    """Read a review record's Severity Calibration: each ruled finding id with its ruling.

    With ``returned``, the record's Returned Findings, every row rules a
    finding returned at its claimed severity, and every critical or major
    returned finding has exactly one row.
    """
    rows: list[dict[str, str]] = []
    errors: list[str] = []
    if SEVERITY_CALIBRATION in headings(body):
        rows, errors = structured_table(section(body, SEVERITY_CALIBRATION),
                                        SEVERITY_CALIBRATION_COLUMNS, path, SEVERITY_CALIBRATION)
    ruled: dict[str, str] = {}
    for number, row in enumerate(rows, 1):
        label = f"{path} severity calibration {number}"
        identifier = row["finding"]
        claimed = row["claimed_severity"].casefold()
        ruling = row["calibrated_severity"].casefold()
        known = FINDING_ID_RE.fullmatch(identifier) is not None
        if not known:
            errors.append(f"{label} finding must be an id such as F-3: {identifier or '(missing)'}")
        elif identifier in ruled:
            errors.append(f"{path} calibrates finding {identifier} twice")
        if claimed not in CLAIM_SEVERITIES:
            errors.append(f"{label} claimed_severity must be critical or major")
        elif ruling not in {claimed, "minor", "invalid"}:
            errors.append(f"{label} calibrated_severity must confirm {claimed} or be minor or invalid")
        cited_statement(docs, row["reason"], label, "reason", errors)
        if known and returned is not None:
            if identifier not in returned:
                errors.append(f"{label} rules {identifier}, which Returned Findings does not list")
            elif returned[identifier] != claimed:
                errors.append(f"{label} claimed_severity must be {returned[identifier]},"
                              f" the severity {identifier} was returned at")
        if known and identifier not in ruled:
            ruled[identifier] = ruling
    for identifier, severity in sorted((returned or {}).items()):
        if severity in CLAIM_SEVERITIES and identifier not in ruled:
            errors.append(f"{path} returned {severity} finding {identifier} has no Severity Calibration row")
    return ruled, errors


def review_record_findings(docs: Path, body: str, path: str, *, approved: bool) -> list[str]:
    """Validate the review record that the blocking_delta loop keeps in a document.

    A critical or major finding never enters Accepted Minor Findings: each row
    names the id of a finding the review returned as minor or its calibration
    lowered to minor. An approved document without Returned Findings was
    approved before its review kept a record, so it stays as it was.
    """
    present = headings(body)
    if approved and RETURNED_FINDINGS not in present:
        return []
    returned, errors = returned_findings(docs, body, path)
    ruled, calibration_errors = severity_calibration(docs, body, path, returned)
    errors.extend(calibration_errors)
    if ACCEPTED_MINOR_FINDINGS not in present:
        return errors
    # The table's own shape is reported by accepted_minor_findings.
    rows, _table_errors = structured_table(section(body, ACCEPTED_MINOR_FINDINGS),
                                           ACCEPTED_MINOR_COLUMNS, path, ACCEPTED_MINOR_FINDINGS)
    accepted: set[str] = set()
    for number, row in enumerate(rows, 1):
        label = f"{path} accepted minor finding {number}"
        match = ACCEPTED_FINDING_ID_RE.match(row["finding"])
        if match is None:
            errors.append(f"{label} must start with the id of the finding it accepts")
            continue
        identifier = match.group(1)
        if identifier in accepted:
            errors.append(f"{path} accepts finding {identifier} twice")
        accepted.add(identifier)
        if identifier not in returned:
            errors.append(f"{label} names {identifier}, which Returned Findings does not list")
        elif identifier in ruled and ruled[identifier] != "minor":
            errors.append(f"{label} names {identifier}, which calibration ruled {ruled[identifier]};"
                          " only a minor finding is accepted")
        elif identifier not in ruled and returned[identifier] != "minor":
            errors.append(f"{label} names {identifier}, which the review returned as"
                          f" {returned[identifier]}; only a minor finding is accepted")
    return errors


def review_loop_record(docs: Path, body: str, path: str, props: dict) -> list[str]:
    """Validate a review note's record when the project's review_loop keeps one.

    A note without a record section never reads the Process Policy, nor does
    an approved note without Returned Findings, which was approved before its
    review kept a record and stays as it was. At any value but blocking_delta
    a section of a record's name is authored text.
    """
    present = headings(body)
    if not set(REVIEW_RECORD_SECTIONS) & present:
        return []
    approved = props.get("status") == "approved"
    if approved and RETURNED_FINDINGS not in present:
        return []
    try:
        loop = session_read(("review_loop", docs.resolve()), lambda: review_loop_value(docs))
    except ValueError as exc:
        return [f"{path} needs the review_loop value of the Process Policy: {exc}"]
    if loop != RECORDING_LOOP:
        return []
    return review_record_findings(docs, body, path, approved=approved)


# Switch remediation_bookkeeping at compiler lets one compiler command write
# the rechecks' closure rows into each review note, compute the expected
# manifest hashes and write the preservation report after a remediation pass.
BOOKKEEPING, COMPILER_BOOKKEEPING = "remediation_bookkeeping", "compiler"
RECHECK_CLOSURES = "Recheck Closures"
RECHECK_COLUMNS = ("finding", "reader", "result", "manifest_hash", "evidence")
RECHECK_RESULTS = ("closed", "open")
RECHECK_READER_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MANIFEST_HASH_RE = re.compile(r"^sha256:[0-9a-f]{64}$")


def bookkeeping_value(docs: Path) -> str:
    """The remediation_bookkeeping value of the project's approved Process Policy."""
    import process_policy

    values, _snapshot = process_policy.effective_values(docs)
    return values[BOOKKEEPING]["value"]


def recheck_rows(docs: Path, body: str, path: str) -> tuple[list[dict[str, str]], list[str]]:
    """Read and validate a review note's Recheck Closures table."""
    rows, errors = structured_table(section(body, RECHECK_CLOSURES), RECHECK_COLUMNS, path,
                                    RECHECK_CLOSURES)
    returned = (returned_findings(docs, body, path)[0]
                if RETURNED_FINDINGS in headings(body) else None)
    seen: set[tuple[str, str]] = set()
    for number, row in enumerate(rows, 1):
        label = f"{path} recheck closure {number}"
        identifier, reader = row["finding"], row["reader"]
        if not FINDING_ID_RE.fullmatch(identifier):
            errors.append(f"{label} finding must be an id such as F-3: {identifier or '(missing)'}")
        elif returned is not None and identifier not in returned:
            errors.append(f"{label} closes {identifier}, which Returned Findings does not list")
        if not RECHECK_READER_RE.fullmatch(reader):
            errors.append(f"{label} reader must be a lens or role id: {reader or '(missing)'}")
        if (identifier, reader) in seen:
            errors.append(f"{path} records the recheck of {identifier} by {reader} twice")
        seen.add((identifier, reader))
        if row["result"] not in RECHECK_RESULTS:
            errors.append(f"{label} result must be closed or open")
        if not MANIFEST_HASH_RE.fullmatch(row["manifest_hash"]):
            errors.append(f"{label} manifest_hash must be the sha256 of the manifest the reader read")
        cited_statement(docs, row["evidence"], label, "evidence", errors)
    return rows, errors


def recheck_closure_record(docs: Path, body: str, path: str, props: dict) -> list[str]:
    """Validate a review note's Recheck Closures when the compiler writes them.

    A note without the section never reads the Process Policy, and an approved
    note keeps what it was approved with. At any value but compiler a section
    of that name is authored text.
    """
    if RECHECK_CLOSURES not in headings(body) or props.get("status") == "approved":
        return []
    try:
        value = session_read(("remediation_bookkeeping", docs.resolve()),
                             lambda: bookkeeping_value(docs))
    except ValueError as exc:
        return [f"{path} needs the remediation_bookkeeping value of the Process Policy: {exc}"]
    if value != COMPILER_BOOKKEEPING:
        return []
    return recheck_rows(docs, body, path)[1]


def table_cell(value: str) -> str:
    """Escape a wikilink alias for a table cell; any other pipe or a line break is refused."""
    escaped = re.sub(r"\[\[([^\[\]\n]+?)\]\]",
                     lambda match: "[[" + re.sub(r"(?<!\\)\|", r"\\|", match.group(1)) + "]]",
                     value.strip())
    outside = re.sub(r"\[\[[^\[\]\n]+?\]\]", "", escaped)
    if "\n" in value or re.search(r"(?<!\\)\|", outside):
        raise ValueError(f"a closure cell holds a line break or a table pipe: {value!r}")
    return escaped


def with_recheck_section(body: str, rows: list[dict[str, str]]) -> str:
    """Return a review body whose Recheck Closures section holds exactly ``rows``.

    An existing section is replaced in place; a new one goes before Accepted
    Minor Findings, or else before Verdict.
    """
    table = ["| " + " | ".join(RECHECK_COLUMNS) + " |",
             "|" + "---|" * len(RECHECK_COLUMNS),
             *("| " + " | ".join(row[column] for column in RECHECK_COLUMNS) + " |"
               for row in rows)]
    block = f"## {RECHECK_CLOSURES}\n\n" + "\n".join(table) + "\n\n"
    existing = re.search(rf"^##\s+{re.escape(RECHECK_CLOSURES)}\s*$", body, flags=re.MULTILINE)
    if existing:
        following = re.search(r"^##\s+", body[existing.end():], flags=re.MULTILINE)
        end = existing.end() + following.start() if following else len(body)
        return body[:existing.start()] + block + body[end:]
    for title in (ACCEPTED_MINOR_FINDINGS, "Verdict"):
        anchor = re.search(rf"^##\s+{re.escape(title)}\s*$", body, flags=re.MULTILINE)
        if anchor:
            return body[:anchor.start()] + block + body[anchor.start():]
    raise ValueError("review note has no Verdict section to place Recheck Closures before")


def backlog_preservation(project: Path, docs: Path, candidate: str) -> dict:
    """Compare the backlog's working files with the pinned candidate commit.

    Every backlog file is changed, added, removed or preserved byte for byte;
    a changed or removed review note that the candidate holds approved is a
    violation, since an approved review is immutable.
    """
    prefix = (docs / "backlog").relative_to(project).as_posix()
    committed = committed_approval_sources(project, docs, candidate)
    before = {path.relative_to(docs).as_posix(): content for path, content in committed.items()
              if "_generated" not in path.relative_to(docs).parts}
    after = {path.relative_to(docs).as_posix(): path.read_bytes()
             for path in sorted((docs / "backlog").rglob("*"))
             if path.is_file() and "_generated" not in path.relative_to(docs).parts}
    changed = sorted(path for path in set(before) & set(after) if before[path] != after[path])
    violations = []
    for path in changed + sorted(set(before) - set(after)):
        if not path.endswith(".md"):
            continue
        props, _body = parse_front_matter_text(before[path].decode("utf-8"))
        if props.get("type") in {"epic-review", "backlog-review"} and props.get("status") == "approved":
            violations.append(f"{path} is an approved review the candidate holds; it is immutable")
    return {"prefix": prefix, "changed": changed, "added": sorted(set(after) - set(before)),
            "removed": sorted(set(before) - set(after)),
            "preserved": len([path for path in before if path in after and before[path] == after[path]]),
            "violations": violations}


def record_rechecks(args) -> int:
    """Write the rechecks' closure rows, the expected hashes and the preservation report.

    One deterministic step after a remediation pass, at remediation_bookkeeping
    compiler. ``--verify`` writes nothing and checks that the review notes and
    the report still equal what the command would write.
    """
    import atomic_file
    import backlog_review_inputs

    docs = docs_root(args.docs)

    def fail(errors: list[str]) -> int:
        print(json.dumps({"ok": False, "errors": errors}, indent=2, ensure_ascii=False,
                         sort_keys=True))
        return 1

    try:
        if bookkeeping_value(docs) != COMPILER_BOOKKEEPING:
            return fail([f"record-rechecks runs at switch {BOOKKEEPING} {COMPILER_BOOKKEEPING}"])
    except ValueError as exc:
        return fail([f"process policy cannot set {BOOKKEEPING}: {exc}"])
    project = history_project(docs)
    report_path = Path(args.report).resolve()
    if project is None:
        return fail(["record-rechecks needs the project's Git checkout for the candidate"])
    if docs.resolve() in report_path.parents:
        return fail(["the report is runtime data; write it outside the docs vault"])
    resolved = subprocess.run(["git", "--no-replace-objects", "rev-parse", "--verify",
                               args.candidate + "^{commit}"], cwd=project, capture_output=True,
                              text=True, check=False)
    if args.candidate.startswith("-") or resolved.returncode:
        return fail([f"candidate does not resolve to a commit: {args.candidate}"])
    candidate = resolved.stdout.strip()
    try:
        raw = Path(args.closures).read_bytes()
        listed = json.loads(raw.decode("utf-8")).get("closures")
    except (OSError, UnicodeError, json.JSONDecodeError, AttributeError) as exc:
        return fail([f"closures cannot be read: {exc}"])
    if not isinstance(listed, list) or not listed or not all(
            isinstance(item, dict) and set(item) == {"review", *RECHECK_COLUMNS}
            and all(isinstance(value, str) for value in item.values()) for item in listed):
        return fail(["closures must list each row's review, " + ", ".join(RECHECK_COLUMNS)])
    record, _errors = collect(docs, review_inputs=True)
    scopes = {latest(item["reviews"])["path"]: item["id"] for item in record["epics"]
              if item["reviews"]}
    if record["backlog_reviews"]:
        scopes[latest(record["backlog_reviews"])["path"]] = "root"
    grouped: dict[str, list[dict[str, str]]] = {}
    errors = []
    for item in listed:
        if item["review"] not in scopes:
            errors.append(f"{item['review']} is not the current review note of an epic or the root")
            continue
        try:
            row = {column: table_cell(item[column]) for column in RECHECK_COLUMNS}
        except ValueError as exc:
            errors.append(str(exc))
            continue
        grouped.setdefault(item["review"], []).append(row)
    if errors:
        return fail(errors)
    written = {}
    for path, rows in sorted(grouped.items()):
        note = docs / path
        original = note.read_bytes()
        props, body = parse_front_matter_text(original.decode("utf-8"))
        if props.get("status") == "approved":
            errors.append(f"{path} is approved; an approved review is immutable")
            continue
        try:
            text = front_matter(props, with_recheck_section(body, rows))
        except ValueError as exc:
            errors.append(f"{path}: {exc}")
            continue
        errors.extend(recheck_rows(docs, with_recheck_section(body, rows), path)[1])
        written[path] = (note, original, text.encode("utf-8"))
    if errors:
        return fail(errors)
    for path, (note, original, content) in sorted(written.items()):
        if args.verify:
            if original != content:
                errors.append(f"{path} Recheck Closures differ from the closures")
            continue
        if original != content:
            atomic_file.replace_bytes(note, content)
    hashes = {}
    for path in sorted(grouped):
        scope = scopes[path]
        try:
            hashes[scope] = backlog_review_inputs.manifest(
                docs, epic=None if scope == "root" else scope)["source_hash"]
        except (backlog_review_inputs.InputError, OSError, ValueError, RuntimeError) as exc:
            hashes[scope] = f"error: {exc}"
            errors.append(f"{scope} manifest cannot be derived: {exc}")
    report = {"schema_version": 1, "candidate": candidate,
              "closures_sha256": "sha256:" + hashlib.sha256(raw).hexdigest(),
              "reviews": {path: "sha256:" + hashlib.sha256((docs / path).read_bytes()).hexdigest()
                          for path in sorted(grouped)},
              "expected_hashes": dict(sorted(hashes.items())),
              "preservation": backlog_preservation(project, docs, candidate)}
    errors.extend(report["preservation"]["violations"])
    if args.verify:
        try:
            stored = json.loads(report_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            stored = None
            errors.append(f"report cannot be read: {exc}")
        if stored is not None and stored != report:
            errors.append("report is stale: " + ", ".join(
                sorted(key for key in set(report) | set(stored)
                       if report.get(key) != stored.get(key))))
    else:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        atomic_file.replace_bytes(report_path, (json.dumps(
            report, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8"))
    print(json.dumps({"ok": not errors, "errors": errors, "report": report}, indent=2,
                     ensure_ascii=False, sort_keys=True))
    return 0 if not errors else 1


def acceptance_checklist_lines(story: dict) -> int:
    """Count the checklist criteria of the Acceptance section, outside code blocks.

    A fenced block opens with three or more backticks or tildes and closes
    only with a line of the same character at least as long. An indented
    block is a line indented four or more columns after a blank line, or
    after another such line, outside a list; inside a list the same line is
    a nested item.
    """
    text = raw_section(story["body"].split(NAV_MARKER, 1)[0], "Acceptance")
    count, fence, in_list, in_code, after_blank = 0, "", False, False, True
    for raw in text.splitlines():
        line = raw.expandtabs(4)
        if fence:
            if re.fullmatch(rf" {{0,3}}{re.escape(fence[0])}{{{len(fence)},}}[ \t]*", line):
                fence = ""
            continue
        opened = CODE_FENCE_RE.match(line)
        if opened:
            fence, in_code = opened.group(1), False
            continue
        if not line.strip():
            after_blank = True
            continue
        indent = len(line) - len(line.lstrip(" "))
        if indent >= 4 and not in_list and (after_blank or in_code):
            in_code, after_blank = True, False
            continue
        in_code = False
        if LIST_ITEM_RE.match(line):
            in_list = True
        elif indent == 0 and after_blank:
            in_list = False
        if CHECKLIST_LINE_RE.match(line):
            count += 1
        after_blank = False
    return count


