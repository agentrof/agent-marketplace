def classify_location(schema: dict, rel_parts: tuple[str, ...]) -> tuple[str, str] | None:
    """Return (node_rel, expected_type) for a markdown file path, or None
    when the location is illegal."""
    parts = list(rel_parts)
    node: list[str] = []
    while len(parts) > 2 and parts[0] == "domains":
        node.extend(parts[:2])
        parts = parts[2:]
    node_rel = "/".join(node)
    is_root = node_rel == ""
    if len(parts) == 1:
        name = parts[0]
        for type_name, spec in schema["doc_types"].items():
            loc = spec["location"]
            if loc["kind"] != "named_file" or loc["name"] != name:
                continue
            if loc.get("root_only") and not is_root:
                return None
            if loc.get("domain_only") and is_root:
                return None
            return node_rel, type_name
        if name == "domain.md" and is_root:
            return None
        return None
    if len(parts) == 2:
        folder, _name = parts
        for type_name, spec in schema["doc_types"].items():
            loc = spec["location"]
            if loc["kind"] != "folder" or loc["folder"] != folder:
                continue
            if loc.get("root_only") and not is_root:
                return None
            return node_rel, type_name
        return None
    return None


def scan_space(space_dir: Path, schema: dict) -> tuple[Space, list[Finding]]:
    space = Space(root=space_dir, schema=schema)
    findings: list[Finding] = []

    def err(path: str, line: int, check: str, message: str, fix: str) -> None:
        findings.append(Finding("error", path, line, check, message, fix))

    def warn(path: str, line: int, check: str, message: str, fix: str) -> None:
        findings.append(Finding("warning", path, line, check, message, fix))

    if not space_dir.is_dir():
        err(space_dir.as_posix(), 1, "space_layout",
            "space directory does not exist", "run the init subcommand first")
        space.broken = True
        return space, findings

    space.nodes[""] = ""
    for dir_path in sorted(space_dir.rglob("*")):
        if not dir_path.is_dir():
            continue
        rel = dir_path.relative_to(space_dir).as_posix()
        if rel.split("/")[0] == GENERATED_DIR:
            continue
        parts = rel.split("/")
        if parts[-1] == "domains":
            continue
        is_node = len(parts) % 2 == 0 and all(
            parts[i] == "domains" for i in range(0, len(parts), 2))
        if is_node:
            space.nodes[rel] = ""
            depth = len(parts) // 2
            if depth >= schema["thresholds"]["nesting_fail_depth"]:
                err(rel, 1, "space_layout",
                    f"domain nesting depth {depth} exceeds the cap",
                    "restructure: promote the subtree or merge domains")
            elif depth >= schema["thresholds"]["nesting_warn_depth"]:
                warn(rel, 1, "space_layout",
                     f"domain nesting depth {depth}; consider restructuring",
                     "deep trees hide content; prefer wider domain maps")

    for node_rel in sorted(space.nodes):
        node_dir = space_dir / node_rel if node_rel else space_dir
        overview = "space.md" if node_rel == "" else "domain.md"
        if not (node_dir / overview).is_file():
            err((Path(node_rel) / overview).as_posix() if node_rel else overview,
                1, "space_layout", f"node is missing its overview file {overview}",
                "every node carries exactly one overview document")

    for name in ("space.md", "glossary.md", "actors.md", "budgets.md"):
        if not (space_dir / name).is_file():
            err(name, 1, "space_layout",
                f"space root is missing required file {name}",
                "the five-file root skeleton is fixed; run init or add the file")
    if not (space_dir / GENERATED_DIR).is_dir():
        err(GENERATED_DIR, 1, "space_layout",
            "the _generated directory is missing",
            "create it (render will populate it)")

    for file_path in sorted(space_dir.rglob("*")):
        if not file_path.is_file():
            continue
        rel = file_path.relative_to(space_dir).as_posix()
        parts = rel.split("/")
        if parts[0] == GENERATED_DIR:
            if len(parts) != 2 or parts[1] not in GENERATED_VIEWS:
                warn(rel, 1, "space_layout",
                     "unexpected file inside _generated",
                     "render owns this directory; stray files are deleted")
            continue
        if file_path.suffix != ".md":
            if file_path.name == ".gitkeep":
                continue
            warn(rel, 1, "space_layout",
                 "non-markdown file in the authored tree",
                 "the space holds markdown documents only")
            continue
        text = file_path.read_text(encoding="utf-8", errors="replace")
        if text.lstrip().startswith("<!-- generated by"):
            err(rel, 1, "space_layout",
                "generated-marker file outside _generated",
                "generated views live only under _generated/")
            continue
        location = classify_location(schema, tuple(parts))
        if location is None:
            err(rel, 1, "space_layout",
                "file location matches no document type",
                "place docs in their type folder; see the space standard")
            continue
        node_rel, expected_type = location
        fm, fm_end, fm_error = parse_frontmatter(text)
        if fm_error:
            err(rel, 1, "frontmatter_schema", fm_error,
                "every authored doc opens with a --- frontmatter block")
            space.broken = True
            continue
        doc_type = fm.get("type", "")
        if doc_type not in schema["doc_types"]:
            err(rel, 1, "frontmatter_schema",
                f"unknown doc type '{doc_type}'",
                "type must be one of the schema's doc_types")
            space.broken = True
            continue
        if doc_type != expected_type:
            err(rel, 1, "frontmatter_schema",
                f"type '{doc_type}' does not match its location"
                f" (expected '{expected_type}')",
                "move the file or fix the type")
        doc = Doc(rel=rel, abs_path=file_path, fm=fm, fm_end=fm_end,
                  doc_type=doc_type, node=node_rel,
                  lines=text.splitlines())
        parse_doc_body(doc)
        space.docs[rel] = doc

    code_format = re.compile(schema["code_format"])
    seen_codes: dict[str, str] = {}
    for rel in sorted(space.docs):
        doc = space.docs[rel]
        if doc.doc_type not in ("space", "domain"):
            continue
        code = str(doc.fm.get("code", ""))
        if not code_format.match(code):
            findings.append(Finding("error", rel, 1, "frontmatter_schema",
                                    f"node code '{code}' does not match {schema['code_format']}",
                                    "declare a 2-4 uppercase-letter code"))
            continue
        if code in schema["reserved_codes"]:
            findings.append(Finding("error", rel, 1, "frontmatter_schema",
                                    f"node code '{code}' is reserved",
                                    "reserved codes cannot be claimed by nodes"))
            continue
        if code in seen_codes:
            findings.append(Finding("error", rel, 1, "frontmatter_schema",
                                    f"node code '{code}' is already used by {seen_codes[code]}",
                                    "codes are unique across the whole space"))
            continue
        seen_codes[code] = rel
        space.nodes[doc.node] = code

    collect_ids(space, findings)
    return space, findings


def nearest_code(space: Space, node_rel: str) -> str:
    current = node_rel
    while True:
        code = space.nodes.get(current, "")
        if code:
            return code
        if current == "":
            return ""
        current = "/".join(current.split("/")[:-2])


def collect_ids(space: Space, findings: list[Finding]) -> None:
    schema = space.schema
    for rel in sorted(space.docs):
        doc = space.docs[rel]
        spec = schema["doc_types"].get(doc.doc_type)
        if spec is None:
            continue
        code = nearest_code(space, doc.node)
        for kind in spec["mints"]:
            row_schema = schema["row_schemas"][kind.lower()]
            token = row_schema["section"]
            if token not in doc.sections:
                continue
            for table in doc.tables:
                if table.section != token:
                    continue
                if table.columns != row_schema["columns"]:
                    findings.append(Finding(
                        "error", rel, table.header_line, "row_schema",
                        f"table in section '{token}' must carry the {kind} columns"
                        f" {' | '.join(row_schema['columns'])}",
                        "row tables use the fixed English snake_case headers"))
                    continue
                for lineno, cells in table.rows:
                    if len(cells) != len(table.columns):
                        findings.append(Finding(
                            "error", rel, lineno, "row_schema",
                            f"row has {len(cells)} cells, expected {len(table.columns)}",
                            "one cell per column, in order"))
                        continue
                    row = dict(zip(table.columns, cells))
                    id_value = row["id"]
                    m = NAMESPACED_ID_RE.fullmatch(id_value)
                    if m:
                        row_kind, row_code = m.group(1), m.group(2)
                        if row_kind != kind:
                            findings.append(Finding(
                                "error", rel, lineno, "id_minting",
                                f"{id_value} minted in a {kind} table",
                                f"{row_kind} rows live in their own section"))
                            continue
                        if row_code != code:
                            findings.append(Finding(
                                "error", rel, lineno, "id_minting",
                                f"{id_value} carries code {row_code} but this"
                                f" node's code is {code}",
                                "an id is minted under its owning node's code;"
                                " moving a doc re-mints its ids"))
                            continue
                    else:
                        findings.append(Finding(
                            "error", rel, lineno, "id_format",
                            f"id '{id_value}' does not match {schema['id_format']}",
                            "mint KIND-CODE-NNN ids under the owning node's code"))
                        continue
                    if id_value in space.ids:
                        findings.append(Finding(
                            "error", rel, lineno, "id_unique",
                            f"{id_value} is already declared in"
                            f" {space.ids[id_value]['doc']}",
                            "an id is declared exactly once; numbers are never reused"))
                        continue
                    space.ids[id_value] = {"kind": kind, "doc": rel,
                                           "row": row, "line": lineno}


