def backlog_contract() -> dict:
    try:
        policy = json.loads(POLICY_PATH.read_text(encoding="utf-8"))
        contract = dict(policy["backlog_contract"])
        contract["_status_values"] = policy.get("status_values", {})
    except (OSError, KeyError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"backlog policy is missing or invalid: {exc}") from exc
    required = {
        "story_owner_roles", "story_supporting_roles",
        "optional_story_classifications",
        "required_story_sections", "required_epic_review_sections",
        "required_backlog_review_sections", "experience_ref_types",
        "minor_finding_owner_roles",
    }
    missing = sorted(required - set(contract))
    if missing:
        raise RuntimeError("backlog policy is missing: " + ", ".join(missing))
    return contract


def parse_scalar(value: str):
    value = value.strip()
    if not value:
        return ""
    if value.startswith("[") and value.endswith("]"):
        return [parse_scalar(item) for item in value[1:-1].split(",")
                if item.strip()]
    if value.lower() in {"true", "false"}:
        return value.lower() == "true"
    if value.isdigit():
        return int(value)
    return frontmatter_value(value)


def parse_front_matter(path: Path) -> tuple[dict, str]:
    return parse_front_matter_text(path.read_text(encoding="utf-8"))


def parse_front_matter_text(text: str) -> tuple[dict, str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    end = next((index for index, line in enumerate(lines[1:], 1)
                if line.strip() == "---"), -1)
    if end < 0:
        return {}, text
    result: dict = {}
    current = None
    for line in lines[1:end]:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line.startswith("  - ") and current:
            result.setdefault(current, []).append(parse_scalar(line[4:]))
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        key = key.strip()
        if value.strip():
            result[key] = parse_scalar(value)
            current = None
        else:
            result[key] = []
            current = key
    return result, "\n".join(lines[end + 1:])


def front_matter(props: dict, body: str) -> str:
    lines = ["---"]
    for key, value in props.items():
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {frontmatter_item(item)}" for item in value)
        elif value is not None:
            lines.append(f"{key}: {frontmatter_scalar(value)}")
    lines.extend(["---", body.lstrip("\n")])
    return "\n".join(lines).rstrip() + "\n"


def canonical_text(text: str) -> bytes:
    props, body = parse_front_matter_text(text)
    body = without_generated_relations(body)
    stable = {key: value for key, value in props.items()
              if key not in APPROVAL_FIELDS}
    payload = json.dumps(stable, sort_keys=True, ensure_ascii=False,
                         separators=(",", ":"))
    return (payload + "\n" + body.strip() + "\n").encode("utf-8")


def canonical(path: Path) -> bytes:
    return canonical_text(path.read_text(encoding="utf-8"))


def digest_text(text: str) -> str:
    """The digest of a note's text, as ``digest`` gives it for the file that holds that text."""
    return "sha256:" + hashlib.sha256(canonical_text(text)).hexdigest()


def digest(path: Path) -> str:
    return "sha256:" + hashlib.sha256(canonical(path)).hexdigest()


def package_digest(docs: Path, paths: list[Path]) -> str:
    manifest = {
        path.relative_to(docs).as_posix(): digest(path)
        for path in sorted(paths)
    }
    data = json.dumps(manifest, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":")).encode("utf-8")
    return "sha256:" + hashlib.sha256(data).hexdigest()


def note_id(props: dict, fallback: str) -> str:
    value = props.get("id")
    if isinstance(value, str) and value.strip():
        return value.strip()
    aliases = props.get("aliases", [])
    if isinstance(aliases, str):
        aliases = [aliases]
    for alias in aliases or []:
        if ID_RE.fullmatch(str(alias)):
            return str(alias)
    return fallback


def values(props: dict, key: str) -> list[str]:
    value = props.get(key, [])
    if isinstance(value, str):
        return [value] if value else []
    return [str(item) for item in value or []]


def split_wikilink(value: str) -> tuple[str, str, str] | None:
    match = WIKILINK_RE.fullmatch(value.strip())
    if not match:
        return None
    inner = match.group(1)
    alias = ""
    for separator in ("\\|", "|"):
        if separator in inner:
            inner, alias = inner.split(separator, 1)
            break
    target, _, anchor = inner.partition("#")
    return target.strip(), anchor.strip(), alias.strip()


def implements_findings(props: dict, story_rel: str, requirement_ref: str) -> list[str]:
    """Require one typed link from a new Requirement-mode story to its Requirement.

    `implements` is a typed relation like every other story link: a quoted
    vault-absolute wikilink to the Requirement note. The vault law refuses a bare
    identifier there, and the incorporation predicate reads the link target, so a
    bare identifier could never close the Requirement it names.
    """
    links = values(props, "implements")
    errors: list[str] = []
    if len(links) != 1:
        errors.append(f"{story_rel} must implement exactly one Requirement, {requirement_ref}")
        return errors
    parts = split_wikilink(links[0])
    if parts is None:
        errors.append(f"{story_rel} implements must be a quoted vault-absolute wikilink to {requirement_ref}")
        return errors
    target, _anchor, alias = parts
    if alias != requirement_ref or not target.startswith("requirements/req-"):
        errors.append(f"{story_rel} must implement exact current Requirement {requirement_ref}")
    return errors


def requirement_link(docs: Path, requirement_ref: str) -> str | None:
    """Return the quoted-ready wikilink of the Requirement note carrying *requirement_ref*."""
    for path in requirement_compile.requirement_paths(docs):
        if requirement_compile.requirement_id(path) == requirement_ref:
            return f"[[requirements/{path.stem}|{requirement_ref}]]"
    return None


def valid_target(target: str) -> bool:
    if (not target or target.startswith("/") or target.endswith(".md")
            or "\\" in target):
        return False
    return all(part not in {"", ".", ".."} for part in target.split("/"))


def read_link(docs: Path, value: str, label: str, errors: list[str], *,
              require_alias: bool = True) -> tuple[str, str, str] | None:
    parsed = split_wikilink(value)
    if parsed is None:
        errors.append(f"{label} must be a quoted vault-absolute wikilink: {value}")
        return None
    target, anchor, alias = parsed
    if not valid_target(target):
        errors.append(f"{label} has invalid vault target: {target or value}")
        return None
    if require_alias and not alias:
        errors.append(f"{label} must have a display alias: {value}")
    if anchor and not anchor.startswith("^"):
        errors.append(f"{label} may use only a stable block anchor: {value}")
    target_path = docs / f"{target}.md"
    if not target_path.is_file():
        errors.append(f"{label} targets missing note: {target}")
        return None
    if anchor:
        body = target_path.read_text(encoding="utf-8")
        if not re.search(rf"(?:^|\s)\^{re.escape(anchor[1:])}(?:\s|$)", body,
                         flags=re.MULTILINE):
            errors.append(f"{label} targets missing block #{anchor}: {target}")
    return target, anchor, alias


