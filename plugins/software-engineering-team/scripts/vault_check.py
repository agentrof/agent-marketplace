def scoped(findings: list[Finding], policy: dict,
           scope: str | None) -> list[Finding]:
    if not scope:
        return findings
    keep_prefixes = (scope.rstrip("/") + "/", policy["maps_dir"] + "/",
                     ".obsidian/")
    keep_files = {policy["home_file"]}
    return [f for f in findings
            if f.check in GLOBAL_CHECKS
            or f.path.startswith(keep_prefixes)
            or f.path in keep_files]


def excluded(findings: list[Finding], excludes: list[str]) -> list[Finding]:
    if not excludes:
        return findings
    normalized = {normalize_vault_rel(raw) for raw in excludes}
    out: list[Finding] = []
    for f in findings:
        if f.path in normalized:
            out.append(Finding("warning", f.path, f.line, f.check,
                               f.message + " (excluded path)",
                               f.remediation))
        else:
            out.append(f)
    return out


def cmd_check(args, policy: dict) -> int:
    root = args.vault.resolve()
    if not root.is_dir():
        print(f"vault_check: vault directory not found: {args.vault}",
              file=sys.stderr)
        return 2
    vault = build_vault(root, policy)
    findings: list[Finding] = []
    if args.changed:
        changed_rel = args.changed.replace("\\", "/")
        for prefix in ("workspace/docs/", "docs/"):
            if changed_rel.startswith(prefix):
                changed_rel = changed_rel[len(prefix):]
                break
        if changed_rel in vault.notes and not vault.notes[changed_rel].generated:
            for check_id in CHANGED_CHECKS:
                sub: list[Finding] = []
                CHECKS[check_id](vault, sub)
                findings.extend(f for f in sub if f.path == changed_rel)
    else:
        for check_id, check in CHECKS.items():
            check(vault, findings)
        check_obsidian_payload(vault, findings, args.payload)
        findings = scoped(findings, policy, args.scope)
    findings = excluded(findings, args.exclude or [])
    findings.sort(key=lambda f: (f.path, f.line, f.check, f.message))
    errors = [f for f in findings if f.severity == "error"]
    warnings = [f for f in findings if f.severity == "warning"]
    for f in findings:
        if args.json:
            print(json.dumps(f.__dict__, sort_keys=True))
        else:
            print(f"{f.severity.upper():7} {f.path}:{f.line} [{f.check}]"
                  f" {f.message} | Fix: {f.remediation}")
    print(f"vault_check: {len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", type=Path, default=DEFAULT_POLICY)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("check")
    p.add_argument("--vault", type=Path, required=True)
    p.add_argument("--scope", default=None)
    p.add_argument("--exclude", action="append", default=[])
    p.add_argument("--payload", type=Path, default=DEFAULT_PAYLOAD)
    p.add_argument("--changed", default=None)
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("render-decisions")
    p.add_argument("--vault", type=Path, required=True)
    p.set_defaults(func=cmd_render_decisions)

    p = sub.add_parser("stamp-decision")
    p.add_argument("--vault", type=Path, required=True)
    p.add_argument("--note", required=True)
    p.add_argument("--status", required=True,
                   choices=["proposed", "accepted", "rejected", "superseded"])
    p.add_argument("--supersedes", default=None)
    p.set_defaults(func=cmd_stamp_decision)

    p = sub.add_parser("migrate")
    p.add_argument("--vault", type=Path, required=True)
    p.add_argument("--scope", default=None)
    p.add_argument("--exclude", action="append", default=[])
    p.add_argument("--payload", type=Path, default=DEFAULT_PAYLOAD)
    p.add_argument("--rename", action="store_true")
    p.add_argument("--dry-run", action="store_true", dest="dry_run")
    p.add_argument("--json", action="store_true")
    p.add_argument("--override-freeze", action="store_true",
                   dest="override_freeze",
                   help="sanctioned override: skip the work-order freeze"
                        " veto for this run")
    p.set_defaults(func=cmd_migrate)

    args = parser.parse_args(argv)
    try:
        policy = load_policy(args.policy)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"vault_check: cannot load policy {args.policy}: {exc}",
              file=sys.stderr)
        return 2
    return args.func(args, policy)


if __name__ == "__main__":
    raise SystemExit(main())
