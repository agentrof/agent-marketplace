    def setUp(self) -> None:
        self.project = Project(self.market)
        self.addCleanup(self.project.close)

    def register(self, package: Path | None = None, source: str = "startup", *,
                 stdin: str | None = None, project_dir: bool = True) -> dict:
        package = package or self.market.package
        env = {key: value for key, value in os.environ.items() if key != "CLAUDE_PROJECT_DIR"}
        if project_dir:
            env["CLAUDE_PROJECT_DIR"] = str(self.project.root)
        event = {"hook_event_name": "SessionStart", "source": source, "session_id": "stamp",
                 "cwd": str(self.project.root)}
        result = subprocess.run(
            [sys.executable, str(package / "scripts" / "hook_launcher.py"), "scripts/team_guard.py", "register"],
            input=json.dumps(event) if stdin is None else stdin, capture_output=True, text=True,
            check=False, timeout=60, env={**env, "PYTHONDONTWRITEBYTECODE": "1"})
        self.assertEqual((result.returncode, result.stderr), (0, ""))
        output = json.loads(result.stdout)
        context = output["hookSpecificOutput"]["additionalContext"]
        self.assertTrue(context.startswith(f"AGENT_MARKETPLACE_HOOKS_ACTIVE: {PLUGIN}\n"))
        return output

    def render(self, package: Path | None = None) -> None:
        result = self.project.generator("apply", "--scope", "local", package=package)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def release(self, version: str, role: str | None = None) -> Path:
        """Install a copy of the package as another release, one role's body changed."""
        package = self.project.work / f"release-{version}" / PLUGIN
        shutil.copytree(self.market.package, package)
        manifest = package / ".agent-marketplace-package.json"
        value = load(manifest)
        value["version"] = version
        manifest.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
        if role is not None:
            agent = package / "agents" / f"{role}.md"
            agent.write_text(agent.read_text(encoding="utf-8") + "\nA new rule.\n",
                             encoding="utf-8")
        return package

    def assert_quiet(self, output: dict) -> None:
        self.assertNotIn("systemMessage", output)
        self.assertNotIn("AGENT_MARKETPLACE_RENDERED_AGENTS",
                         output["hookSpecificOutput"]["additionalContext"])

    def assert_stale(self, output: dict, count: int, version: str, *, told: bool = True) -> None:
        total = len(package_tiers(self.market.map))
        context = " ".join(output["hookSpecificOutput"]["additionalContext"].split())
        self.assertIn("AGENT_MARKETPLACE_RENDERED_AGENTS: stale", context)
        self.assertIn(f"{count} of the {total} rendered role agents in .claude/agents/", context)
        self.assertIn(f"spawn every role as the plugin's `{PLUGIN}:<agent-id>` identity, never"
                      f" as `{PLUGIN}-<agent-id>`", context)
        if not told:
            self.assertNotIn("systemMessage", output)
            return
        message = output["systemMessage"]
        self.assertIn(f"{count} of the {total} role agents in .claude/agents/", message)
        self.assertIn(f"do not match the installed {PLUGIN} {version} or this project's"
                      " workspace/config.json", message)
        self.assertIn(f"Run /{PLUGIN}:setup", message)
        self.assertIn("other model settings than this project's workspace/config.json", context)

    def test_a_current_stamp_reports_nothing(self):
        self.render()
        self.assert_quiet(self.register())
        # Without CLAUDE_PROJECT_DIR the payload's cwd names the project.
        self.assert_quiet(self.register(project_dir=False))

    def test_a_stale_stamp_sends_every_role_to_the_plugin_until_a_refresh(self):
        self.render()
        update = self.release("9.9.9", role="code-reviewer")
        total = len(package_tiers(self.market.map))
        for source in ("startup", "resume", "clear", "fork"):
            with self.subTest(source=source):
                self.assert_stale(self.register(update, source), total, "9.9.9")
        # Claude keeps the instruction after a compaction; the user is told once.
        self.assert_stale(self.register(update, "compact"), total, "9.9.9", told=False)
        self.assert_stale(self.register(update, project_dir=False), total, "9.9.9")
        # The same version with one changed role makes only that role stale.
        rebuilt = self.release(load(self.market.package / ".agent-marketplace-package.json")
                               ["version"], role="code-reviewer")
        self.assert_stale(self.register(rebuilt), 1, "0.0.1")
        # A file rendered before stamps existed carries none.
        path = self.project.agents_dir / f"{PREFIX}qa-engineer.md"
        lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
        self.assertEqual(lines[2], stamp(self.market.package, "qa-engineer", role_settings.resolve(
            self.market.map, {}, "claude")["qa-engineer"]) + "\n")
        path.write_text("".join(lines[:2] + lines[3:]), encoding="utf-8")
        self.assert_stale(self.register(), 1, "0.0.1")
        # The refresh renders them again; the Codex package never reports them.
        self.render(update)
        self.assert_quiet(self.register(update))
        self.assert_quiet(self.register(self.market.root / "dist" / "codex" / PLUGIN))

    def test_a_config_change_not_yet_rendered_sends_the_roles_to_the_plugin(self):
        # Setup or /configure models renders the roles again after a config
        # change; until then, as after a pull, the stamps say what they run.
        self.render()
        version = load(self.market.package / ".agent-marketplace-package.json")["version"]
        before = role_settings.resolve(self.market.map, {}, "claude")
        for config in ({"class_models": {"claude": {MEDIUM: {"model": "session"}}}},
                       {"role_classes": {MOVED: LOW}},
                       {"class_models": {"claude": {LOW: {"effort": "max"}}},
                        "role_classes": {VARIANT: HIGH}}):
            with self.subTest(config=config):
                self.project.write_config(**config)
                after = role_settings.resolve(self.market.map, config, "claude")
                changed = sum(after[role] != before[role] and
                              (after[role]["model"], after[role]["effort"])
                              != (before[role]["model"], before[role]["effort"])
                              for role in before)
                self.assertGreater(changed, 0)
                self.assert_stale(self.register(), changed, version)
        # A move that keeps every role's model and effort renders nothing new.
        self.project.write_config(class_models={"claude": {HIGH: {"effort": "high"}}})
        self.assert_quiet(self.register())
        # While the config cannot be resolved, no rendered file is current.
        self.project.write_config(class_models={"claude": {HIGH: {"effort": "ultra"}}})
        self.assert_stale(self.register(), len(before), version)
        # Rendering the current config makes every stamp current again.
        self.project.write_config(class_models={"claude": {MEDIUM: {"model": "session"}}})
        self.render()
        self.assert_quiet(self.register())

    def test_a_project_without_rendered_agents_reports_nothing(self):
        self.assert_quiet(self.register())
        agents = self.project.agents_dir
        agents.mkdir(parents=True)
        (agents / "mine.md").write_text("---\nname: mine\n---\n\nMine.\n", encoding="utf-8")
        (agents / f"{PREFIX}helper.md").write_text(
            f"---\nname: {PREFIX}helper\n---\n\nThe user's own.\n", encoding="utf-8")
        self.assert_quiet(self.register())
        # Input the hook cannot read never blocks the session.
        self.assert_quiet(self.register(stdin="not json"))
        self.assert_quiet(self.register(stdin=""))


