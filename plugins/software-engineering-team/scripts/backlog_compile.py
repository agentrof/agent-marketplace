def stub_epic(args) -> int:
    docs = docs_root(args.docs)
    if not SLUG_RE.fullmatch(args.slug):
        print("invalid epic slug", file=sys.stderr)
        return 2
    if getattr(args, "new_review", False):
        return stub_epic_review(docs, args.slug)
    root = docs / "backlog" / "epics" / args.slug
    (root / "stories").mkdir(parents=True, exist_ok=True)
    (root / "reviews").mkdir(parents=True, exist_ok=True)
    epic_id = args.id or "EP-001"
    path = root / "epic.md"
    base_title = args.title or args.slug.replace("-", " ").title()
    backlog_title = title_of(
        docs / "backlog" / "backlog.md", DEFAULT_BACKLOG_TITLE
    )
    if not path.exists():
        title = base_title.strip()
        goal = args.goal or "Define the customer outcome and boundary."
        path.write_bytes(front_matter(
            {"type": "epic", "title": title, "status": "draft",
             "id": epic_id, "owner_role": "product_owner", "goal": goal,
             "tags": ["doc/epic", "status/draft"], "aliases": [epic_id]},
            f"# {title}\n\n{goal}\n").encode("utf-8"))
    review = root / "reviews" / "round-1-epic-review.md"
    if not review.exists():
        review_title = f"Review round 1 for {base_title.strip()}"
        review.write_bytes(front_matter(
            {"type": "epic-review", "title": review_title, "status": "draft",
             "round": 1, "owner_role": "product_owner",
             "derives_from": [f"[[backlog/epics/{args.slug}/epic|{epic_id}]]"],
             "tags": ["doc/epic-review", "status/draft"],
             "aliases": [f"{epic_id}-REVIEW-001"], **round_pin(docs)},
            review_body(review_title,
                        backlog_contract()["required_epic_review_sections"])).encode("utf-8"))
    append_nav(path, [
        "[[maps/backlog|Backlog map]]",
        f"[[backlog/backlog|{backlog_title}]]",
    ])
    append_nav(review, [
        "[[maps/backlog|Backlog map]]",
        f"[[backlog/epics/{args.slug}/epic|{epic_id}]]",
    ])
    print(root)
    return 0


def stub_story(args) -> int:
    docs = docs_root(args.docs)
    if not SLUG_RE.fullmatch(args.slug) or not SLUG_RE.fullmatch(args.epic):
        print("invalid epic or story slug", file=sys.stderr)
        return 2
    root = docs / "backlog" / "epics" / args.epic / "stories" / args.slug
    root.mkdir(parents=True, exist_ok=True)
    story_id = args.id or "ST-001"
    base_title = args.title or args.slug.replace("-", " ").title()
    story_title = base_title.strip()
    test_title = f"Test plan for {base_title.strip()}"
    criteria = list(args.criterion_ref or [])
    experience = list(args.experience_ref or [])
    evidence = list(args.evidence_ref or [])
    design_refs = list(args.uses_design or [])
    constraint_refs = list(args.constrained_by or [])
    implements = list(getattr(args, "implements", None) or [])
    backlog_props, _backlog_body = parse_front_matter(docs / "backlog" / "backlog.md")
    planning_mode = str(backlog_props.get("planning_mode", ""))
    if planning_mode not in {"manual", "requirement"} and not backlog_props.get("legacy_contract"):
        print("backlog_compile: initialize or revise backlog with a planning_mode first", file=sys.stderr)
        return 2
    if planning_mode == "requirement":
        requirement_ref = str(backlog_props.get("requirement_ref", ""))
        link = requirement_link(docs, requirement_ref)
        if link is None:
            print(f"backlog_compile: Requirement {requirement_ref} was not found under requirements/", file=sys.stderr)
            return 2
        implements = [link]
    elif implements:
        print("backlog_compile: manual stories cannot implement a Requirement", file=sys.stderr)
        return 2
    story = root / "story.md"
    if not story.exists():
        scope = args.scope or "Describe the smallest valuable behavior."
        epic_link = f"[[backlog/epics/{args.epic}/epic|{args.epic.upper()}]]"
        body = (
            f"# {story_title}\n\n"
            "## User Value\n\nDescribe the observable user or business value.\n\n"
            f"## Scope\n\n{scope}\n\n"
            "## Non-Goals\n\nList behavior deliberately excluded from this story.\n\n"
            "## Implementation Responsibilities\n\n"
            "- backend_developer: Own implementation and integration.\n\n"
            "## Acceptance\n\n- [ ] Map every cited criterion to an observable result.\n\n"
            "## Dependencies\n\nNone.\n\n"
            "## Delivery Notes\n\nRecord delivery constraints without execution state.\n"
        )
        story_props = {
            "type": "story", "title": story_title, "status": "planned",
            "id": story_id, "owner_role": "backend_developer",
            "supporting_roles": [], "priority": "must",
            "priority_reason": "Required for the epic outcome.", "scope": scope,
            "work_kind": args.work_kind,
            "criterion_refs": criteria, "experience_refs": experience,
            "uses_design": design_refs,
            "constrained_by": constraint_refs,
            "origin_mode": planning_mode,
            "introduced_in_revision": int(backlog_props.get("revision", 1) or 1),
            "derives_from": [epic_link],
            "tags": ["doc/story", "status/planned"], "aliases": [story_id],
        }
        # The vault relation contract refuses an empty typed relation list.
        for key in ("uses_design", "constrained_by"):
            if not story_props[key]:
                del story_props[key]
        # A legacy backlog has no planning mode to record; a bare key would
        # read back as a list.
        if not planning_mode:
            del story_props["origin_mode"]
        if implements:
            story_props["implements"] = implements
        if evidence:
            story_props["related_to"] = evidence
        story.write_bytes(front_matter(
            story_props,
            body).encode("utf-8"))
    test = root / "test-plan.md"
    if not test.exists():
        scenario = f"{story_id}-TS-001"
        story_link = f"[[backlog/epics/{args.epic}/stories/{args.slug}/story|{story_id}]]"
        planning_sources = (criteria if args.work_kind == "feature"
                            else criteria + evidence)
        source_refs = "\n".join(f"  - {value}" for value in planning_sources)
        source_block = (f"- source_refs:\n{source_refs}\n"
                        if source_refs else "")
        test.write_bytes(front_matter(
            {"type": "test-plan", "title": test_title, "status": "draft",
             "revision": 1, "owner_role": "qa_engineer",
             "derives_from": [story_link], "verifies": [story_link],
             "tags": ["doc/test-plan", "status/draft"],
             "aliases": [f"{story_id}-TP"]},
            f"# {test_title}\n\n{coverage_class_table()}\n\n"
            f"## {scenario}\n\n"
            "- category: happy-path\n- target: component\n"
            "- automation: required\n"
            f"- automation_target: tests/{args.slug.replace('-', '_')}.py::test_{args.slug.replace('-', '_')}\n"
            f"{source_block}"
            "- Given: the preconditions are satisfied\n"
            "- When: the user performs the story action\n"
            "- Then: the expected outcome is observable\n").encode("utf-8"))
    epic_link = f"[[backlog/epics/{args.epic}/epic|{args.epic.upper()}]]"
    story_link = (
        f"[[backlog/epics/{args.epic}/stories/{args.slug}/story|{story_id}]]"
    )
    test_link = (
        f"[[backlog/epics/{args.epic}/stories/{args.slug}/test-plan|{test_title}]]"
    )
    append_nav(story, ["[[maps/backlog|Backlog map]]", epic_link, test_link])
    append_nav(test, ["[[maps/backlog|Backlog map]]", epic_link, story_link])
    print(root)
    return 0


