# Hooks
# ---------------------------------------------------------------------------


def _matcher_tokens(matcher: str) -> list[str]:
    return [t for t in matcher.split("|") if t]


def _derive_matcher(matcher: str, route: dict, expansions: dict) -> str:
    drop = set(route.get("drop_tokens", []))
    out: list[str] = []
    for token in _matcher_tokens(matcher):
        if token in drop:
            continue
        for expanded in expansions.get(token, [token]):
            if expanded not in out:
                out.append(expanded)
    return "|".join(out)


def _is_guard_command(command: str, harness: dict) -> bool:
    return any(marker in command for marker in harness.get("guard_command_markers", []))


def render_hooks(source: dict, harness: dict, harness_id: str) -> dict:
    """Transform a source hooks.json object into the harness manifest.

    Every source entry must be claimed by at least one route or belong to
    an event listed in unsupported_events; a silently dropped entry is a
    config error, never an omission.
    """
    routes = harness.get("hook_routes", [])
    unsupported = set(harness.get("unsupported_events", []))
    expansions = harness.get("token_expansions", {})
    rewrite = harness.get("command_rewrite", {"policy": "keep_verbatim"})
    fmt = harness.get("agent_format", "")
    cursor_style = "hooks_version" in harness

    out_events: dict[str, list] = {}
    for event, entries in source.get("hooks", {}).items():
        for entry in entries:
            matcher = entry.get("matcher", "")
            tokens = set(_matcher_tokens(matcher))
            routed = False
            for route in routes:
                if route.get("source_event") != event:
                    continue
                required = route.get("requires_token")
                if required and required not in tokens:
                    continue
                routed = True
                mode = route.get("matcher", "keep")
                if mode == "none":
                    target_matcher = ""
                elif mode == "derive":
                    target_matcher = _derive_matcher(matcher, route, expansions)
                else:
                    target_matcher = matcher
                for hook in entry.get("hooks", []):
                    command = rewrite_command(hook.get("command", ""), rewrite)
                    target = route["target_event"]
                    if cursor_style:
                        item: dict = {"command": command}
                        if target_matcher:
                            item["matcher"] = target_matcher
                        if _is_guard_command(command, harness):
                            item.update(harness.get("guard_options", {}))
                        out_events.setdefault(target, []).append(item)
                    else:
                        bucket = out_events.setdefault(target, [])
                        wrapped = None
                        for existing in bucket:
                            if existing.get("matcher", "") == target_matcher:
                                wrapped = existing
                                break
                        if wrapped is None:
                            wrapped = {}
                            if target_matcher:
                                wrapped["matcher"] = target_matcher
                            wrapped["hooks"] = []
                            bucket.append(wrapped)
                        wrapped["hooks"].append({"type": "command", "command": command})
            if not routed and event not in unsupported:
                raise HarnessConfigError(
                    f"harness '{harness_id}' has no route for source event"
                    f" '{event}' (matcher '{matcher}') and does not list it"
                    f" as unsupported"
                )
    _ = fmt
    if cursor_style:
        return {"version": harness["hooks_version"], "hooks": out_events}
    return {"hooks": out_events}


