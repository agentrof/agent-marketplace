def load_product_contract(root: Path) -> dict:
    path = root / PRODUCT_CONTRACT_RELPATH
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"{path}: missing or invalid product contract") from exc
    try:
        vendor = data["vendor"]
        product = data["product"]
        hosts = data["hosts"]
        values = (
            data["schema_version"], vendor["id"], vendor["display_name"],
            vendor["home_env"], vendor["default_home_dir"], product["id"],
            product["display_name"], product["home_env"],
            product["home_subdir"], hosts["claude"]["plugins_dir_env"],
            hosts["codex"]["plugins_dir_env"],
        )
    except (KeyError, TypeError) as exc:
        raise ValueError(f"{path}: incomplete product contract") from exc
    expected = (
        1, "agentrof", "Agentrof", "AGENT_MARKETPLACE_HOME", ".agent-marketplace",
        "agent-marketplace", "Agent Marketplace", "AGENT_MARKETPLACE_HOME",
        "", "AGENT_MARKETPLACE_CLAUDE_PLUGINS_DIR",
        "AGENT_MARKETPLACE_CODEX_PLUGINS_DIR",
    )
    if values != expected:
        raise ValueError(f"{path}: product contract differs from the supported namespace")
    environment = data.get("project_environment", {})
    if environment != {
        "runtime_root": ".agentrof",
        "projection_roots": {"claude": ".claude", "codex": ".codex"},
    }:
        raise ValueError(f"{path}: project environment roots are invalid")
    return data


def packaging_names(root: Path) -> tuple[str, str]:
    product_id = load_product_contract(root)["product"]["id"]
    return (
        f".{product_id}-generated-distribution",
        f".{product_id}-package.json",
    )


def marketplace_paths_source(product_contract: dict) -> str:
    del product_contract
    return f'''#!/usr/bin/env python3
"""Resolve the Software Engineering Team owner from project config."""

from __future__ import annotations

from collections.abc import Mapping


def team_from_config(config: Mapping[str, object]) -> str:
    """Resolve the sole team from the current project config contract."""
    return str(config.get("team_id", "")).strip()
'''


def marketplace_paths_targets(root: Path) -> list[Path]:
    return [
        plugin / "scripts" / "marketplace_paths.py"
        for plugin in sorted((root / "plugins").iterdir())
        if plugin.is_dir()
    ]


def sync_marketplace_paths_sources(root: Path) -> None:
    expected = marketplace_paths_source(load_product_contract(root))
    for target in marketplace_paths_targets(root):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")


def marketplace_paths_source_drift(root: Path) -> list[str]:
    expected = marketplace_paths_source(load_product_contract(root))
    problems = []
    for target in marketplace_paths_targets(root):
        try:
            actual = target.read_text(encoding="utf-8")
        except OSError:
            actual = ""
        if actual != expected:
            problems.append(
                f"generated runtime source is out of sync: {target}"
            )
    return problems


