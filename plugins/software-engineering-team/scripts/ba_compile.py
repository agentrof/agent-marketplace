def table_skeleton(columns: list[str]) -> list[str]:
    return ["| " + " | ".join(columns) + " |",
            "|" + "---|" * len(columns)]


def stub_lines(schema: dict, doc_type: str, title: str, **extra) -> list[str]:
    spec = schema["doc_types"][doc_type]
    fm = ["---", f"type: {doc_type}", f"title: {title}", "status: draft",
          "owner_role: business_analyst"]
    for key in spec["extra_frontmatter"]["required"]:
        value = extra.get(key)
        if isinstance(value, list):
            fm.append(f"{key}:")
            fm += [f"  - {v}" for v in value]
        else:
            fm.append(f"{key}: {value}")
    fm.append("---")
    body = ["", f"# {title}", "", f"One-line summary of {title}.", ""]
    section_titles = {token: token.replace("_", " ").title()
                      for token in spec["required_sections"]}
    row_by_section = {schema["row_schemas"][k.lower()]["section"]: k
                      for k in spec["mints"]
                      if schema["row_schemas"][k.lower()]["section"] in spec["required_sections"]}
    for token in spec["required_sections"]:
        body.append(f"## {section_titles[token]} <!-- sec: {token} -->")
        body.append("")
        kind = row_by_section.get(token)
        if kind:
            body += table_skeleton(schema["row_schemas"][kind.lower()]["columns"])
        else:
            body.append("To be analyzed.")
        body.append("")
    return fm + body


def write_stub(schema: dict, path: Path, doc_type: str, title: str, **extra) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(stub_lines(schema, doc_type, title, **extra)).rstrip("\n")
                    + "\n", encoding="utf-8")


def next_ids(space: Space, code: str) -> dict[str, str]:
    result = {}
    for kind in ("BR", "AC", "AS", "OQ", "DEC", "CH"):
        highest = 0
        for id_value, info in space.ids.items():
            m = NAMESPACED_ID_RE.fullmatch(id_value)
            if m and m.group(1) == kind and m.group(2) == code:
                highest = max(highest, int(m.group(3)))
        result[kind] = f"{kind}-{code}-{highest + 1:03d}"
    return result


