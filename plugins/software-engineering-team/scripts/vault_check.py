def check_vault_layout(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    home = policy["home_file"]
    maps_dir = policy["maps_dir"]
    if home not in vault.index:
        findings.append(Finding(
            "error", home, 1, "vault_layout",
            "vault has no home note",
            "materialize the vault payload (setup, or the stewardship copy"
            " rule) so navigation has a root"))
    for subtree in policy["subtrees"]:
        if not (vault.root / subtree).is_dir():
            continue
        if not subtree_has_notes(vault, subtree):
            continue  # a map is born with its tree's first note
        map_rel = f"{maps_dir}/{subtree}.md"
        if map_rel not in vault.index:
            findings.append(Finding(
                "error", map_rel, 1, "vault_layout",
                f"subtree '{subtree}' has no map note",
                "seed the map from the vault payload and curate it"))
    for name in policy.get("extra_maps", []):
        map_rel = f"{maps_dir}/{name}.md"
        if map_rel not in vault.index:
            findings.append(Finding(
                "error", map_rel, 1, "vault_layout",
                f"map note '{name}' is missing",
                "seed it from the vault payload"))
    known_roots = set(policy["subtrees"]) | {
        maps_dir, ".obsidian", ".trash",
        policy.get("attachments_dir", "_attachments"),
    }
    known_roots.update(p.rstrip("/").split("/")[0]
                       for p in policy.get("generated_subtrees", []))
    # The vault root holds exactly the home note (plus any root-level
    # policy-listed generated view); a retired scaffold file left behind
    # by an older generation fires "outside layout" here, which is the
    # enforced-deletion mechanism (migrate deletes the class).
    known_files = {home}
    known_files.update(v for v in policy.get("generated_views", [])
                       if "/" not in v)
    attachments = policy.get("attachments_dir", "_attachments")
    embedded = {t for note in vault.notes.values()
                for (_, embed, t, _, _, _) in note.wikilinks if embed}
    for rel in sorted(vault.index):
        top = rel.split("/")[0]
        if rel.rsplit("/", 1)[-1] == ".gitkeep":
            continue  # git plumbing for empty skeleton directories
        if in_machine_dir(policy, rel):
            continue  # compiler-owned directories manage their own files
        if rel.endswith(".base"):
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                "base files are not part of the vault contract",
                "views are markdown map notes and generated indexes;"
                " remove the base file"))
            continue
        if top == ".obsidian":
            continue
        if "/" not in rel:
            if rel.endswith(".md"):
                if rel not in known_files and rel not in {home}:
                    findings.append(Finding(
                        "error", rel, 1, "vault_layout",
                        f"root-level note '{rel}' is outside the vault layout",
                        "notes live inside a policy subtree; move it or"
                        " register the surface in vault-policy.json"))
            elif rel not in known_files:
                findings.append(Finding(
                    "error", rel, 1, "vault_layout",
                    f"root-level file '{rel}' is outside the vault layout",
                    "only policy-listed views and the payload live at the"
                    " vault root"))
            continue
        if top not in known_roots:
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                f"unknown top-level directory '{top}'",
                "vault subtrees are policy-listed; add it to"
                " vault-policy.json or move the content"))
        elif top == attachments:
            if rel not in embedded:
                findings.append(Finding(
                    "error", rel, 1, "vault_layout",
                    "attachment is not referenced by any embed",
                    "reference it with an embed wikilink or delete it"))
        elif not rel.endswith(".md") and top not in {
                p.rstrip("/").split("/")[0]
                for p in policy.get("generated_subtrees", [])}:
            findings.append(Finding(
                "error", rel, 1, "vault_layout",
                f"non-markdown file '{rel}' inside a note subtree",
                "attachments live under the attachments directory;"
                " transient working files leave the vault before the gate"))


def check_wikilink_resolution(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, embed, target, _anchor, _alias, _inner) in note.wikilinks:
            if not target:
                continue  # pure in-note anchor form is judged by anchor check
            resolved = (target in vault.index if embed
                        else f"{target}.md" in vault.index)
            if not resolved:
                findings.append(Finding(
                    "error", note.rel, lineno, "wikilink_resolution",
                    f"unresolved wikilink target '{target}'",
                    "targets are vault-absolute paths from the vault root"
                    " (no leading slash, forward slashes, exact case)"))


def check_anchor_resolution(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, _embed, target, anchor, _alias, _inner) in note.wikilinks:
            if not anchor:
                continue
            if not anchor.startswith("^"):
                findings.append(Finding(
                    "error", note.rel, lineno, "anchor_resolution",
                    f"heading anchor '#{anchor}' is banned",
                    "link the note itself, or a block id (#^block-id);"
                    " heading text is prose and dies silently"))
                continue
            target_note = vault.notes.get(f"{target}.md" if target else note.rel)
            if target_note and anchor[1:] not in target_note.block_ids:
                findings.append(Finding(
                    "error", note.rel, lineno, "anchor_resolution",
                    f"block anchor '{anchor}' does not exist in"
                    f" '{target or note.rel}'",
                    "add the ^block-id to the target line or fix the anchor"))


def check_link_policy(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        for (lineno, _text, target) in note.mdlinks:
            if target.startswith(("http://", "https://", "mailto:", "#", "/")):
                continue
            clean = target.split("#", 1)[0]
            if not clean:
                continue
            resolved = (note.path.parent / clean).resolve()
            try:
                resolved.relative_to(vault.root)
                inside = True
            except ValueError:
                inside = False
            if inside:
                findings.append(Finding(
                    "error", note.rel, lineno, "link_policy",
                    f"vault-internal citation uses a markdown link: {target}",
                    "cite vault content as a vault-absolute wikilink with an"
                    " alias; the migrate verb rewrites this class"))
            elif not resolved.exists():
                findings.append(Finding(
                    "warning", note.rel, lineno, "link_policy",
                    f"out-of-vault link target does not exist: {target}",
                    "fix the relative path or drop the link"))


def check_table_pipe(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        in_fence = False
        for lineno, line in enumerate(note.lines, start=1):
            if lineno < note.fm_end:
                continue
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence or not is_table_row(line):
                continue
            for match in WIKILINK_RE.finditer(INLINE_CODE_RE.sub("", line)):
                inner = match.group("inner")
                if re.search(r"(?<!\\)\|", inner):
                    findings.append(Finding(
                        "error", note.rel, lineno, "table_pipe",
                        "unescaped alias pipe inside a table-cell wikilink",
                        "escape it as \\| or the pipe splits the row"))


def is_separator_row(line: str) -> bool:
    stripped = line.strip()
    return (stripped.startswith("|") and "-" in stripped
            and set(stripped.replace("|", "").strip()) <= set("-: "))


def check_table_shape(vault: Vault, findings: list[Finding]) -> None:
    for note in authored(vault):
        in_fence = False
        prev_is_row = False
        for lineno, line in enumerate(note.lines, start=1):
            if lineno < note.fm_end:
                continue
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                prev_is_row = False
                continue
            if in_fence:
                continue
            row_here = is_table_row(line)
            if row_here and not prev_is_row:
                nxt = note.lines[lineno] if lineno < len(note.lines) else ""
                if not is_separator_row(nxt):
                    findings.append(Finding(
                        "error", note.rel, lineno, "table_shape",
                        "table header row is not followed by its separator"
                        " row",
                        "put the |---| separator directly under the header;"
                        " a fenced block right after the header swallows the"
                        " whole table into plain text"))
            prev_is_row = row_here


def check_banned_basename(vault: Vault, findings: list[Finding]) -> None:
    """Policy-banned generic basenames only. Duplicate basenames across
    folders are legal: the title layer owns display identity (title
    uniqueness is title_shape's warning). Findings are per FILE (never
    vault-global) so scoped gates compose."""
    policy = vault.policy
    banned = set(policy.get("banned_basenames", []))
    for note in authored(vault):
        if in_machine_dir(policy, note.rel):
            continue
        name = note.rel.rsplit("/", 1)[-1]
        if name in banned:
            findings.append(Finding(
                "error", note.rel, 1, "banned_basename",
                f"basename '{name}' is policy-banned",
                "generic filenames say nothing; give the file a meaningful"
                " slug name (typed content: <slug>-<type suffix>.md)"))


def note_decision_tree(policy: dict, rel: str) -> dict | None:
    for tree in policy.get("decision_trees", {}).values():
        path = tree["path"].rstrip("/")
        if "*" in path:
            if "/" in rel and glob_match(path, rel.rsplit("/", 1)[0]):
                return tree
        elif rel.startswith(path + "/"):
            return tree
    return None


# The shape of a record id a note may own through its aliases: PREFIX-,
# an optional node code, then digits (SD-001, ADR-012, DEC-INV-001).
ID_ALIAS_RE = re.compile(r"^[A-Z][A-Z0-9]*(?:-[A-Z0-9]{2,4})?-\d{3,}$")


def id_shaped_aliases(note: Note) -> list[str]:
    aliases = note.fm.get("aliases")
    if not isinstance(aliases, list):
        return []
    return [str(a).strip() for a in aliases
            if isinstance(a, str) and ID_ALIAS_RE.fullmatch(str(a).strip())]


def check_title_shape(vault: Vault, findings: list[Finding]) -> None:
    policy = vault.policy
    banned_stems = {b[:-3] for b in policy.get("banned_basenames", [])}
    seen_titles: dict[str, str] = {}
    for note in authored(vault):
        if in_machine_dir(policy, note.rel):
            continue
        title = note.fm.get("title")
        if not isinstance(title, str) or not title.strip():
            findings.append(Finding(
                "error", note.rel, 1, "title_shape",
                "authored note has no title",
                "the title is the user-facing graph label: a natural"
                " output_language phrase ending in the type's designation,"
                " never id-led"))
            continue
        for alias in id_shaped_aliases(note):
            if title.startswith(alias):
                findings.append(Finding(
                    "error", note.rel, 1, "title_shape",
                    f"title is id-led ('{alias}')",
                    "ids live in the frontmatter alias, never in the"
                    " label; the migrate verb strips this class"))
                break
        first_h1 = next((text for (_l, text, level) in note.headings
                         if level == 1), None)
        if first_h1 is not None and first_h1 != title:
            findings.append(Finding(
                "error", note.rel, 1, "title_shape",
                f"first H1 '{first_h1}' is not byte-identical to the title",
                "the H1 and the title are one label; edit them in the"
                " same write"))
        stem = note.rel.rsplit("/", 1)[-1][:-3]
        if title == stem:
            findings.append(Finding(
                "warning", note.rel, 1, "title_shape",
                "title is byte-identical to the basename stem",
                "titles are human-readable output_language labels; a"
                " humanized form of the slug is compliant, the raw stem"
                " is not"))
        if title.strip().lower() in banned_stems:
            findings.append(Finding(
                "warning", note.rel, 1, "title_shape",
                f"generic title '{title}'",
                "a generic label is meaningless in the graph; qualify it"
                " with its owning space or subject"))
        if title in seen_titles:
            findings.append(Finding(
                "warning", note.rel, 1, "title_shape",
                f"title '{title}' is also used by {seen_titles[title]}",
                "duplicate labels are indistinguishable in the graph;"
                " qualify one of them"))
        else:
            seen_titles[title] = note.rel
        note_type = note.fm.get("type")
        kebab_type = kebab(note_type) if note_type else ""
        if kebab_type in vault.taxonomy_types:
            check_title_designation(vault, note, title, kebab_type, findings)
    check_designation_coverage(vault, findings)


def check_title_designation(vault: Vault, note: Note, title: str,
                            kebab_type: str, findings: list[Finding]) -> None:
    """The title carries its type's configured designation (word-boundary,
    folded), and a challenge-record title also carries its round number as a
    standalone token. The map is config data: absent, or missing this type,
    is the mint-duty WARNING (never a silent pass); present binds the
    containment ERROR."""
    designations = vault.designations
    if designations is None:
        findings.append(Finding(
            "warning", note.rel, 1, "title_shape",
            "type designations are not configured, so the title cannot be"
            " verified to carry its type's designation",
            "run setup/configure or build-docs-vault to mint"
            " doc_type_designations in workspace/config.json"))
        return
    designation = designations.get(kebab_type)
    if not designation:
        findings.append(Finding(
            "warning", note.rel, 1, "title_shape",
            f"type '{kebab_type}' has no configured designation, so the"
            " title cannot be verified",
            "run setup/configure or build-docs-vault to mint this type's"
            " designation in workspace/config.json"))
        return
    if not designation_present(title, designation):
        findings.append(Finding(
            "error", note.rel, 1, "title_shape",
            f"title '{title}' does not carry the '{kebab_type}'"
            f" designation '{designation}'",
            "the title is a natural output_language phrase carrying its"
            " type's designation; the migrate verb appends it"))
    if kebab_type == "challenge-record":
        round_no = note.fm.get("round")
        if isinstance(round_no, int) and not re.search(
                r"(?<!\d)" + re.escape(str(round_no)) + r"(?!\d)", title):
            findings.append(Finding(
                "error", note.rel, 1, "title_shape",
                f"review-round title '{title}' does not carry its round"
                f" number {round_no} as a standalone token",
                "review-round titles read '<scope> <review-round"
                " designation> <n>'; retitle it (auto-append leaves"
                " round-number placement to judgment)"))


def check_designation_coverage(vault: Vault, findings: list[Finding]) -> None:
    """The configured map covers exactly the taxonomy universe. A type with
    no map entry is a mint-duty WARNING; a map key naming no known type is a
    dead-entry ERROR. Silent when no map is configured (the per-note
    warnings already name the duty)."""
    designations = vault.designations
    if designations is None:
        return
    for missing in sorted(vault.taxonomy_types - set(designations)):
        findings.append(Finding(
            "warning", DESIGNATION_CONFIG_REL, 1, "title_shape",
            f"doc type '{missing}' has no designation in the configured map",
            "mint one designation per taxonomy type; run setup/configure or"
            " build-docs-vault"))
    for unknown in sorted(set(designations) - vault.taxonomy_types):
        findings.append(Finding(
            "error", DESIGNATION_CONFIG_REL, 1, "title_shape",
            f"designation map key '{unknown}' names no known doc type",
            "map keys are kebab taxonomy types; drop the stale key or"
            " declare the type"))


def check_map_coverage(vault: Vault, findings: list[Finding]) -> None:
    """Every policy-hub note is linked from its subtree map. Leaves stay
    optional on maps; hubs are the map's contract."""
    policy = vault.policy
    maps_dir = policy["maps_dir"]
    for rel in sorted(vault.notes):
        note = vault.notes[rel]
        if note.generated or not is_hub(policy, rel):
            continue
        map_rel = f"{maps_dir}/{rel.split('/')[0]}.md"
        map_note = vault.notes.get(map_rel)
        if map_note is None:
            continue  # vault_layout reports the missing map
        targets = {t for (_, _, t, _, _, _) in map_note.wikilinks}
        if rel[:-3] not in targets:
            findings.append(Finding(
                "error", map_rel, 1, "map_coverage",
                f"map does not link the hub '{rel[:-3]}'",
                "every policy hub gets an inbound link from its subtree"
                " map; leaves are optional, hubs are not"))


def check_alias_ownership(vault: Vault, findings: list[Finding]) -> None:
    """An id-shaped link alias must decorate a link to the id's owning
    note: decision-tree ids resolve by filename, BA row ids through the
    target space's generated registry. Absent or unknown = silent skip."""
    policy = vault.policy
    owners: dict[str, str] = {}
    for tree in policy.get("decision_trees", {}).values():
        for note in decision_notes(vault, tree):
            rec_id = decision_id(tree, note)
            if rec_id is not None:
                owners.setdefault(rec_id, note.rel)
    registries: dict[str, dict | None] = {}

    def space_registry(rel: str) -> tuple[str, dict] | None:
        parts = rel.split("/")
        for i in range(1, len(parts)):
            root = "/".join(parts[:i])
            reg_rel = f"{root}/_generated/registry.json"
            if reg_rel not in vault.index:
                continue
            if root not in registries:
                try:
                    registries[root] = json.loads(
                        (vault.root / reg_rel).read_text(encoding="utf-8"))
                except (OSError, json.JSONDecodeError):
                    registries[root] = None
            data = registries[root]
            return (root, data) if isinstance(data, dict) else None
        return None

    for note in authored(vault):
        for (lineno, embed, target, _anchor, alias, _inner) in note.wikilinks:
            if embed or not target or not alias:
                continue
            aid = alias.strip()
            owner = owners.get(aid)
            if owner is not None:
                if f"{target}.md" != owner:
                    findings.append(Finding(
                        "error", note.rel, lineno, "alias_ownership",
                        f"alias '{aid}' decorates a link to '{target}' but"
                        f" the id's owning note is {owner}",
                        "an id-shaped alias always rides a link to its"
                        " owner; use plain prose for anything else"))
                continue
            if not NAMESPACED_ID_RE.fullmatch(aid):
                continue
            resolved = space_registry(f"{target}.md")
            if resolved is None:
                continue  # no registry in reach: silent skip
            root, registry = resolved
            info = registry.get("ids", {}).get(aid)
            if not isinstance(info, dict) or "doc" not in info:
                continue  # unknown id: silent skip
            owner_rel = f"{root}/{info['doc']}"
            if f"{target}.md" != owner_rel:
                findings.append(Finding(
                    "error", note.rel, lineno, "alias_ownership",
                    f"alias '{aid}' decorates a link to '{target}' but the"
                    f" registry declares its owner as {owner_rel}",
                    "an id-shaped alias always rides a link to its owner;"
                    " re-render the space if the registry is stale"))


